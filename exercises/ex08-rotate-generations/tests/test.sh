#!/bin/bash
#===============================================================================
# ex08 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# 採点用のバックアップ置き場を作り直す関数
#   backup_20260901 〜 backup_20260905 の5世代を、更新日時を1日ずつずらして作る。
#   touch -t YYYYMMDDhhmm で更新日時を固定するので、採点をいつ実行しても
#   「新しい順」は必ず同じになる(テストを決定的にするため)。
#
#   keepme.txt と other.tar.gz は backup_*.tar.gz に一致しないファイル。
#   絶対に削除されてはいけないので、わざと最も古い日時にしてある。
#-------------------------------------------------------------------------------
setup_backups() {
    local dir="$1" day
    rm -rf "$dir"
    mkdir -p "$dir"
    for day in 01 02 03 04 05; do
        : > "${dir}/backup_202609${day}_010000.tar.gz"
        touch -t "202609${day}0100" "${dir}/backup_202609${day}_010000.tar.gz"
    done
    : > "${dir}/keepme.txt"
    touch -t 202601010000 "${dir}/keepme.txt"
    : > "${dir}/other.tar.gz"
    touch -t 202601010000 "${dir}/other.tar.gz"
    return 0
}

#-------------------------------------------------------------------------------
describe "異常系: -d を指定しなかったとき"
#-------------------------------------------------------------------------------
run_target

hint "BACKUP_DIR の初期値を空にし、[[ -z \"\$BACKUP_DIR\" ]] で未指定を判定します。"
assert_status 1 "-d を指定しないと終了ステータス1で終わる"

hint "「エラー: -d でバックアップ保存ディレクトリを指定してください」を >&2 で出します。"
assert_stderr_contains "エラー: -d でバックアップ保存ディレクトリを指定してください" \
    "「エラー: -d でバックアップ保存ディレクトリを指定してください」を標準エラー出力に出す"

#-------------------------------------------------------------------------------
describe "異常系: 指定したディレクトリが存在しないとき"
#-------------------------------------------------------------------------------
run_target -d nosuchdir

hint "[[ ! -d \"\$BACKUP_DIR\" ]] で存在を確認し、無ければ exit 1 で止めます。"
assert_status 1 "存在しないディレクトリを指定すると終了ステータス1で終わる"

hint "書式は「エラー: ディレクトリが見つかりません: <パス>」。パスは受け取った文字列のままです。"
assert_stderr_contains "エラー: ディレクトリが見つかりません: nosuchdir" \
    "「エラー: ディレクトリが見つかりません: <パス>」を標準エラー出力に出す"

#-------------------------------------------------------------------------------
describe "異常系: -g に数値以外を指定したとき"
#-------------------------------------------------------------------------------
setup_backups backup
run_target -d backup -g three

hint "[[ ! \"\$GENERATIONS\" =~ ^[0-9]+\$ ]] で判定します。正規表現は囲みません。"
assert_status 1 "-g が数値でないと終了ステータス1で終わる"

hint "メッセージは「エラー: 世代数には数値を指定してください」。標準エラー出力へ出します。"
assert_stderr_contains "エラー: 世代数には数値を指定してください" \
    "「エラー: 世代数には数値を指定してください」を標準エラー出力に出す"

#-------------------------------------------------------------------------------
describe "正常系: -n (ドライラン) を指定したとき"
#   -g を付けずに実行するので、既定の世代数3が使われているかも同時に確認する。
#-------------------------------------------------------------------------------
setup_backups backup
run_target -d backup -n

hint "書式は「[dry-run] 削除します: <ファイル名>」。basename で名前だけにします。"
assert_stdout_contains "[dry-run] 削除します: backup_20260901_010000.tar.gz" \
    "-n のとき最も古い世代について「[dry-run] 削除します: <ファイル名>」と表示する"

hint "-g を省略したときの既定値は 3 です。GENERATIONS=3 を初期値にします。"
assert_stdout_contains "保持: 3件 / 削除: 2件" \
    "-g を省略すると3世代を残し、最後に「保持: 3件 / 削除: 2件」と表示する"

hint "ドライランでは rm を実行しません。DRY_RUN の判定と rm の位置を確認します。"
assert_file_count "backup/backup_*.tar.gz" 5 "-n のときは1件も削除しない"

#-------------------------------------------------------------------------------
describe "正常系: -g 3 で実行したとき"
#-------------------------------------------------------------------------------
setup_backups backup
run_target -d backup -g 3

hint "最後まで処理できたら exit 0 で終わります。"
assert_status 0 "正常に実行できると終了ステータス0で終わる"

hint "削除できたら1件ごとに「削除しました: <ファイル名>」を標準出力に出します。"
assert_stdout_contains "削除しました: backup_20260901_010000.tar.gz" \
    "最も古い世代について「削除しました: <ファイル名>」と表示する"

hint "sort -rn で新しい順に並べ、先頭から3件を残します。逆順だと新しい方が消えます。"
assert_file_count "backup/backup_*.tar.gz" 3 "新しい3世代だけが残る"

hint "find に -name 'backup_*.tar.gz' を付けて対象を絞ります。"
assert_file_exists "backup/keepme.txt" "パターンに一致しない keepme.txt は削除しない"

hint "other.tar.gz は .tar.gz ですが backup_ で始まりません。パターンを確認します。"
assert_file_exists "backup/other.tar.gz" "パターンに一致しない other.tar.gz は削除しない"

#-------------------------------------------------------------------------------
describe "正常系: 対象が世代数以下しかないとき"
#-------------------------------------------------------------------------------
setup_backups few
rm -f few/backup_20260903_010000.tar.gz \
      few/backup_20260904_010000.tar.gz \
      few/backup_20260905_010000.tar.gz
run_target -d few -g 3

hint "残す世代数に足りないときは1件も削除せず、件数だけ表示して正常終了します。"
assert_stdout_contains "保持: 2件 / 削除: 0件" \
    "対象が世代数以下のときは削除せず「保持: 2件 / 削除: 0件」と表示する"

finish
