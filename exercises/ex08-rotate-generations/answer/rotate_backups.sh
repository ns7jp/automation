#!/bin/bash
#===============================================================================
# ex08: 世代管理(古い世代の削除)(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている
#   「削除対象を -name で厳しく絞る」
#   「入力の検証を最初にまとめる」
#   「ドライランを用意する」
# の3点は、ファイルを消すスクリプトを書くときの必須の作法です。
# 案件No.2の backup.sh も同じ考え方で古い世代を削除しています。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   削除スクリプトで最も怖いのは、変数のタイプミスで空文字になった状態のまま
#   rm が動くことである。set -u は、その事故を実行前に止めるための防御線。
set -u

#===============================================================================
# 1. 既定値の設定
#
#   「オプションで上書きできる既定値」は、変数の初期値として先に入れておく。
#   BACKUP_DIR だけは既定値を作らず空にしておく。削除先を勝手に決めてしまうと、
#   -d の指定を忘れたときに意図しないディレクトリを掃除してしまうため。
#===============================================================================
SCRIPT_NAME="$(basename "$0")"
BACKUP_DIR=""             # -d は必須。既定値は持たせない
GENERATIONS=3             # -g の既定値。残す世代数
DRY_RUN="false"           # -n / --dry-run が指定されたら "true" になる

#===============================================================================
# 2. 使い方の表示
#
#   既定値を ${GENERATIONS} のように埋め込んでおくと、
#   既定値を変えたときにヘルプの直し忘れが起きない。
#===============================================================================
usage() {
    echo "使い方: ${SCRIPT_NAME} -d <バックアップ保存ディレクトリ> [-g <残す世代数>] [-n] [-h]"
    echo "  backup_*.tar.gz を新しい順に <残す世代数> 個だけ残し、古いものを削除します。"
    echo "  -d <ディレクトリ>  バックアップ保存ディレクトリ (必須)"
    echo "  -g <世代数>        残す世代数 (既定: ${GENERATIONS})"
    echo "  -n                 ドライラン。実際には削除しません (--dry-run も可)"
    echo "  -h                 この使い方を表示します (--help も可)"
}

#===============================================================================
# 3. 長いオプションを短いオプションに変換する
#
#   bash 組み込みの getopts は -n のような1文字オプションしか扱えない。
#   --dry-run も受け付けたいので、getopts に渡す前に -n へ置き換えてしまう。
#   set -- は位置引数 ($1, $2, ...) を丸ごと入れ替える組み込みコマンド。
#===============================================================================
args=()
for arg in "$@"; do
    case "$arg" in
        --dry-run) args+=("-n") ;;
        --help)    args+=("-h") ;;
        *)         args+=("$arg") ;;
    esac
done
set -- "${args[@]}"

#===============================================================================
# 4. オプションの解析
#
#   "d:g:nh" の : は「そのオプションは値を取る」という印で、値は $OPTARG に入る。
#   ヘルプ(-h)は利用者が求めた出力なので標準出力に出して exit 0、
#   未定義のオプション(\?)は操作ミスなので標準エラー出力に出して exit 1 とする。
#===============================================================================
while getopts "d:g:nh" opt; do
    case "$opt" in
        d)  BACKUP_DIR="$OPTARG" ;;
        g)  GENERATIONS="$OPTARG" ;;
        n)  DRY_RUN="true" ;;
        h)  usage; exit 0 ;;
        \?) usage >&2; exit 1 ;;
    esac
done
# 処理したオプションの分だけ位置引数をずらす定番の1行。
shift $((OPTIND - 1))

#===============================================================================
# 5. 入力の検証
#
#   「消す」処理に入る前に、確認できることをすべて確認して落とす。
#   ここを通過したあとは「値は正しい」と信じて書けるので、
#   後半の処理がぐっと読みやすくなる。
#
#   -z は「空文字かどうか」、-d は「ディレクトリとして存在するか」の判定。
#   =~ は正規表現との照合で、^[0-9]+$ は「数字だけが1文字以上」という意味。
#   正規表現はクォートで囲まない(囲むとただの文字列比較になってしまう)。
#===============================================================================
if [[ -z "$BACKUP_DIR" ]]; then
    echo "エラー: -d でバックアップ保存ディレクトリを指定してください" >&2
    usage >&2
    exit 1
fi

if [[ ! -d "$BACKUP_DIR" ]]; then
    echo "エラー: ディレクトリが見つかりません: ${BACKUP_DIR}" >&2
    exit 1
fi

if [[ ! "$GENERATIONS" =~ ^[0-9]+$ ]]; then
    echo "エラー: 世代数には数値を指定してください" >&2
    exit 1
fi

#===============================================================================
# 6. 削除候補の一覧を「新しい順」に作る
#
#   find のオプション:
#     -maxdepth 1                直下だけを見る。サブディレクトリまで潜らない
#     -type f                    通常ファイルだけを対象にする
#     -name 'backup_*.tar.gz'    このスクリプトが作ったバックアップだけに絞る。
#                                この1行が、他のファイルを守る最重要の安全装置。
#     -printf '%T@\t%p\n'        「更新日時(エポック秒)<タブ>パス」で出力する
#
#   sort -rn は数値として逆順に並べる。つまり更新日時が新しい順になる。
#   cut -f2- でタブ区切りの2列目以降(パス)だけを取り出す。
#
#   ls -t の出力を使わないのは、ls が「人間が読むための表示」だからである。
#   ファイル名に空白が含まれると単語が分割され、意図しないファイルを
#   消しにいく事故につながる。find に必要な情報を出力させて自分で並べるほうが安全。
#
#   mapfile -t は1行を1要素として配列に読み込む(-t は行末の改行を捨てる)。
#   < <(...) はプロセス置換で、コマンドの出力をファイルのように読み込ませる書き方。
#   パイプ( | while read )で書くとループがサブシェルになり、
#   中で数えたカウンタが外に残らないという有名な落とし穴があるため、
#   件数を数えたい今回はいったん配列に受け取るほうが確実。
#===============================================================================
mapfile -t FILES < <(
    find "$BACKUP_DIR" -maxdepth 1 -type f -name 'backup_*.tar.gz' -printf '%T@\t%p\n' \
        | sort -rn \
        | cut -f2-
)

#===============================================================================
# 7. 世代数までは残し、それより古いものを削除する
#
#   配列は新しい順に並んでいるので、先頭から数えて世代数以内なら残す、
#   それ以降は削除、という単純な判定で世代管理になる。
#
#   ドライランのときは rm を通らない経路に分けている。
#   「表示だけして続ける」ではなく「削除の直前で分岐する」形にしておくと、
#   あとから処理を足したときに誤って rm が実行される事故を防げる。
#
#   rm の -- は「これ以降はオプションではなくファイル名」という区切り。
#   -foo.tar.gz のような名前をオプションと誤解させないための保険。
#===============================================================================
KEPT=0
DELETED=0
INDEX=0

for file in "${FILES[@]}"; do
    INDEX=$((INDEX + 1))
    name="$(basename "$file")"

    if [[ "$INDEX" -le "$GENERATIONS" ]]; then
        KEPT=$((KEPT + 1))
        continue
    fi

    if [[ "$DRY_RUN" == "true" ]]; then
        echo "[dry-run] 削除します: ${name}"
    else
        rm -f -- "$file"
        echo "削除しました: ${name}"
    fi
    DELETED=$((DELETED + 1))
done

#===============================================================================
# 8. 結果の表示
#
#   削除が0件でも必ず1行出す。何も出力せずに終わると、
#   「動いていないのか、対象が無かったのか」を運用者が区別できない。
#   cron のログに毎日この1行が残ることが、後から状況を追う助けになる。
#===============================================================================
echo "保持: ${KEPT}件 / 削除: ${DELETED}件"

# 削除件数が0件でも、処理そのものは成功しているので終了ステータスは0。
exit 0
