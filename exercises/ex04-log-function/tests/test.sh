#!/bin/bash
#===============================================================================
# ex04 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
describe "正常系: オプションなしで実行したとき(既定の ./logs に出力)"
#-------------------------------------------------------------------------------
run_target

hint "ログファイル名は with_log_<YYYYMMDD>_<HHMMSS>.log です。date '+%Y%m%d_%H%M%S' の結果を使います。"
assert_file_count "logs/with_log_[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]_[0-9][0-9][0-9][0-9][0-9][0-9].log" 1 \
    "既定の ./logs に with_log_<YYYYMMDD>_<HHMMSS>.log を1つ作る"

# 作られたログファイルのパスを取り出す(以降のファイル内容の判定で使う)
LOG_FILES=(logs/with_log_*.log)
LOG_FILE="${LOG_FILES[0]}"

hint "書式は [YYYY-MM-DD HH:MM:SS] [レベル] メッセージ です。角括弧と半角スペースの位置に注意してください。"
assert_stdout_matches "\[[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2}\] \[INFO\] ===== 処理を開始します =====" \
    "開始のログを [日時] [INFO] ===== 処理を開始します ===== の書式で画面に出す"

assert_stdout_contains "[INFO] 対象を3件読み込みました" \
    "INFO レベルで「対象を3件読み込みました」を画面に出す"

hint "レベルは INFO / WARN / ERROR の半角大文字です。"
assert_stdout_contains "[WARN] 1件は対象外のためスキップしました" \
    "WARN レベルで「1件は対象外のためスキップしました」を画面に出す"

assert_stdout_contains "[ERROR] 1件の処理に失敗しました" \
    "ERROR レベルで「1件の処理に失敗しました」を画面に出す"

assert_stdout_contains "[INFO] ===== 処理を終了します =====" \
    "INFO レベルで「===== 処理を終了します =====」を画面に出す"

hint "件数は本体処理の5行ぶんです。サマリ行自身は数えません。log 関数の中で case を使って数えると確実です。"
assert_stdout_contains "INFO: 3件 / WARN: 1件 / ERROR: 1件" \
    "サマリ行「INFO: 3件 / WARN: 1件 / ERROR: 1件」を画面に出す"

hint "ERROR を1件記録しているので、最後は exit 1 です。ERROR_COUNT を数えて判定してください。"
assert_status 1 "ERROR が1件以上あるので終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "正常系: ログファイルの中身"
#-------------------------------------------------------------------------------
hint "画面とファイルの両方に出すには tee -a を使います。echo ... > ファイル ではファイルにしか残りません。"
assert_file_contains "$LOG_FILE" '\[INFO\] ===== 処理を開始します =====' \
    "画面に出したのと同じ内容をログファイルにも書く"

hint "行頭から [日時] [レベル] の順に並んでいるか確認してください。"
assert_file_contains "$LOG_FILE" '^\[[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2}\] \[(INFO|WARN|ERROR)\] .' \
    "ログファイルの各行が [YYYY-MM-DD HH:MM:SS] [レベル] メッセージ の書式になっている"

assert_file_contains "$LOG_FILE" 'INFO: 3件 / WARN: 1件 / ERROR: 1件' \
    "サマリ行もログファイルに記録する"

#-------------------------------------------------------------------------------
describe "正常系: -l で出力先を変えたとき"
#-------------------------------------------------------------------------------
run_target -l mylogs

hint "getopts \"l:\" で受け取った値は \$OPTARG に入ります。LOG_DIR に代入してください。"
assert_file_count "mylogs/with_log_*.log" 1 "-l で指定したディレクトリにログを出力する"

run_target -l a/b/c

hint "mkdir に -p を付けると、途中のディレクトリもまとめて作れます。"
assert_file_count "a/b/c/with_log_*.log" 1 "-l a/b/c のような多段のパスでも mkdir -p で作る"

#-------------------------------------------------------------------------------
describe "異常系: ログディレクトリを作れないとき"
#-------------------------------------------------------------------------------
# 同じ名前の通常ファイルがあると mkdir は失敗する。その状況を作って確認する。
: > notdir
run_target -l notdir

hint "if ! mkdir -p \"\$LOG_DIR\"; then ... fi で、作成に失敗した場合を判定します。"
assert_status 1 "ログディレクトリを作れないときは終了ステータス1で終わる"

hint "エラーメッセージは echo \"...\" >&2 で標準エラー出力に出します。"
assert_stderr_contains "エラー: ログディレクトリを作成できません: notdir" \
    "「エラー: ログディレクトリを作成できません: <パス>」を標準エラー出力に出す"

finish
