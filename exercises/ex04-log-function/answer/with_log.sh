#!/bin/bash
#===============================================================================
# ex04: ログ関数と実行記録(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている書き方(log 関数 / tee -a / カウンタ変数)は
# 案件No.1〜No.4のスクリプトすべてで同じ形が使われている実務の定番なので、
# 意味を理解したうえで真似することを勧めます。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   ログ処理では LOG_FILE の準備前にうっかり log を呼んでしまう事故が起きやすい。
#   set -u を付けておくと「空文字のまま動いて、どこにも記録が残らない」という
#   最悪のパターンを、その場のエラーとして気づける。
set -u

#===============================================================================
# 1. 既定値の設定
#===============================================================================
SCRIPT_NAME="$(basename "$0")"
LOG_DIR="./logs"                       # -l で指定が無ければこのディレクトリに出す

# ファイル名用の日時は「記号を含めない」書式にする。
#   ファイル名に : や空白が入ると、コマンドで扱うたびにクォートが必要になり
#   事故のもとになるため、ファイル名は _ と数字だけで組み立てるのが慣習。
TIMESTAMP="$(date '+%Y%m%d_%H%M%S')"

# レベルごとの件数を数えるカウンタ。必ず 0 で初期化しておく。
#   初期化しないと、set -u によって $((INFO_COUNT + 1)) の時点でエラーになる。
INFO_COUNT=0
WARN_COUNT=0
ERROR_COUNT=0

#===============================================================================
# 2. 使い方の表示
#===============================================================================
usage() {
    echo "使い方: ${SCRIPT_NAME} [-l <ログ出力ディレクトリ>]"
    echo "  処理の実行記録を、画面とログファイルの両方に出力します。"
    echo "  -l を省略した場合の出力先は ./logs です。"
}

#===============================================================================
# 3. オプションの解析
#
#   getopts はbash組み込みのオプション解析機能。"l:" の : は
#   「このオプションは値を取る」という意味で、渡された値は $OPTARG に入る。
#   未定義のオプションが来た場合、$opt には ? が入る。
#   case のパターンとして書くときは、? がワイルドカードと解釈されないよう
#   \? とエスケープする。
#===============================================================================
while getopts "l:" opt; do
    case "$opt" in
        l)
            LOG_DIR="$OPTARG"
            ;;
        \?)
            # 未定義のオプション。エラーなので使い方は標準エラー出力へ。
            usage >&2
            exit 1
            ;;
    esac
done
# 処理済みのオプションぶんだけ引数をずらす。
# 今回は使わないが、この後ろで位置引数($1 など)を扱う場合に必要になる定番の1行。
shift $((OPTIND - 1))

#===============================================================================
# 4. ログ出力先の準備
#
#   mkdir -p は「途中のディレクトリもまとめて作る」「既にあってもエラーにしない」
#   という2つの性質を持つ。-l logs/2026/09 のような多段の指定にも1回で対応できる。
#
#   ただし、同名の通常ファイルが既にある場合など、作れないケースもある。
#   ログを残せないまま処理を続けると事故調査ができなくなるため、
#   ここで止めるのが安全な設計。
#===============================================================================
if ! mkdir -p "$LOG_DIR"; then
    echo "エラー: ログディレクトリを作成できません: ${LOG_DIR}" >&2
    exit 1
fi

# ${LOG_DIR%/} は「末尾にスラッシュがあれば取り除く」パラメータ展開。
# -l /var/log/ のように指定されても //with_log_... と二重にならないようにする。
LOG_FILE="${LOG_DIR%/}/with_log_${TIMESTAMP}.log"

#===============================================================================
# 5. ログ出力関数
#
#   local を付けた変数は、この関数の中だけで有効になる。
#   付け忘れるとスクリプト全体で共有される変数になり、たまたま同じ名前の
#   変数を外で使っていた場合に、静かに値を壊してしまう。
#
#   shift + "$*" の組み合わせで「1つ目=レベル、2つ目以降=メッセージ本文」
#   という受け取り方ができる。log "INFO" "件数が" "3件です" のように
#   分かれて渡されても、1つの文にまとめて記録できる。
#
#   tee -a は「画面(標準出力)とファイルの両方に同時に書き出す」コマンド。
#   -a は追記(append)。付け忘れると実行のたびにログが上書きされてしまう。
#===============================================================================
log() {
    local level="$1"
    shift
    local message="$*"
    local now
    now="$(date '+%Y-%m-%d %H:%M:%S')"

    # レベルごとの件数を数える。
    #   log を呼ぶたびにここで数えておくと、呼び出し側で数え忘れる心配がない。
    case "$level" in
        INFO)  INFO_COUNT=$((INFO_COUNT + 1)) ;;
        WARN)  WARN_COUNT=$((WARN_COUNT + 1)) ;;
        ERROR) ERROR_COUNT=$((ERROR_COUNT + 1)) ;;
    esac

    echo "[${now}] [${level}] ${message}" | tee -a "$LOG_FILE"
}

#===============================================================================
# 6. 本体処理
#
#   この演習では実際の処理は行わず、記録の書き方だけを練習する。
#   案件No.1では、この位置でCSVを1行ずつ読み、ユーザーを作成しながら
#   同じ形の log を呼んでいる。
#===============================================================================
log "INFO" "===== 処理を開始します ====="
log "INFO" "対象を3件読み込みました"
log "WARN" "1件は対象外のためスキップしました"
log "ERROR" "1件の処理に失敗しました"
log "INFO" "===== 処理を終了します ====="

#===============================================================================
# 7. サマリの出力
#
#   関数の引数は「関数を呼び出す前」に展開されるため、ここで渡している
#   ${INFO_COUNT} などは、本体処理の5行を数え終えた時点の値になる。
#   つまりサマリ行そのものは件数に含まれない。
#===============================================================================
log "INFO" "INFO: ${INFO_COUNT}件 / WARN: ${WARN_COUNT}件 / ERROR: ${ERROR_COUNT}件"

#===============================================================================
# 8. 終了ステータス
#
#   ERROR を1件でも記録していれば異常終了(1)として呼び出し元に知らせる。
#   cron から実行した場合、この終了ステータスが「失敗したかどうか」を
#   機械的に判断する唯一の手段になる。
#===============================================================================
if [[ "$ERROR_COUNT" -gt 0 ]]; then
    exit 1
fi

exit 0
