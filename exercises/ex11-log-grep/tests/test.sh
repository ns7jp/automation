#!/bin/bash
#===============================================================================
# ex11 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# 採点用のログファイルを作る
#   中身は毎回まったく同じなので、いつ採点しても結果は変わらない(決定的)。
#
#   既定パターン ERROR|FATAL|CRITICAL に一致するのは次の4行。
#     10:00:03 ERROR / 10:00:05 FATAL / 10:00:07 ERROR / 10:00:08 CRITICAL
#   このうち 10:00:07 の行は監視ツール自身が出す「想定内のERROR」という設定で、
#   除外パターン(-e)の練習に使う。
#-------------------------------------------------------------------------------
cat > app.log <<'LOGEOF'
2026-09-06 10:00:01 INFO service started
2026-09-06 10:00:02 DEBUG cache warm up
2026-09-06 10:00:03 ERROR db connection failed
2026-09-06 10:00:04 WARN disk usage 85%
2026-09-06 10:00:05 FATAL out of memory
2026-09-06 10:00:06 INFO retry scheduled
2026-09-06 10:00:07 ERROR health-check dummy probe (テスト用の想定内エラー)
2026-09-06 10:00:08 CRITICAL disk failure detected
LOGEOF

#-------------------------------------------------------------------------------
describe "異常系: -f でログファイルを指定しなかったとき"
#-------------------------------------------------------------------------------
run_target

hint "LOG_FILE の初期値を空にしておき、[[ -z \"\$LOG_FILE\" ]] で未指定を判定します。"
assert_status 1 "-f を指定しないと終了ステータス1で終わる"

hint "「エラー: -f で調べるログファイルを指定してください」を echo \"...\" >&2 で出します。"
assert_stderr_contains "エラー: -f で調べるログファイルを指定してください" \
    "「エラー: -f で調べるログファイルを指定してください」を標準エラー出力に出す"

#-------------------------------------------------------------------------------
describe "異常系: 指定したログファイルが存在しないとき"
#-------------------------------------------------------------------------------
run_target -f nosuch.log

hint "[[ ! -f \"\$LOG_FILE\" ]] で存在を確認し、無ければ exit 1 で止めます。"
assert_status 1 "存在しないファイルを指定すると終了ステータス1で終わる"

hint "書式は「エラー: ログファイルが見つかりません: <パス>」。パスは受け取った文字列のままです。"
assert_stderr_contains "エラー: ログファイルが見つかりません: nosuch.log" \
    "「エラー: ログファイルが見つかりません: <パス>」を標準エラー出力に出す"

#-------------------------------------------------------------------------------
describe "正常系: -h を指定したとき"
#-------------------------------------------------------------------------------
run_target -h

hint "ヘルプは利用者が意図して求めた出力なので、成功(0)で終了します。"
assert_status 0 "-h を指定すると終了ステータス0で終わる"

hint "ヘルプは標準出力に出します(>&2 を付けない)。"
assert_stdout_contains "使い方" "-h で使い方を標準出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: 既定の検知パターンで実行したとき"
#-------------------------------------------------------------------------------
run_target -f app.log

hint "検知が1件以上あるときは exit 1 です。監視スクリプトは異常を非0で伝えます。"
assert_status 1 "検知が1件以上あると終了ステータス1で終わる"

hint "書式は「検知: 」(半角コロン+半角スペース)のあとにログの行をそのまま続けます。"
assert_stdout_contains "検知: 2026-09-06 10:00:03 ERROR db connection failed" \
    "検知した行を「検知: <行の内容>」の形式で表示する"

hint "既定パターン ERROR|FATAL|CRITICAL に一致するのは4行です。空文字を wc -l で数えていませんか。"
assert_stdout_contains "検知件数: 4件" "既定パターンでの検知件数を「検知件数: 4件」と表示する"

hint "検知パターンに一致しない行(INFO / DEBUG / WARN)は出力してはいけません。"
assert_output_not_contains "service started" "検知パターンに一致しない行は表示しない"

#-------------------------------------------------------------------------------
describe "正常系: -p で検知パターンを絞ったとき"
#-------------------------------------------------------------------------------
run_target -f app.log -p FATAL

hint "-p が指定されたら \$OPTARG で PATTERN を上書きします。既定値のままになっていませんか。"
assert_stdout_contains "検知件数: 1件" "-p FATAL を指定すると「検知件数: 1件」になる"

#-------------------------------------------------------------------------------
describe "正常系: -e で除外パターンを指定したとき"
#-------------------------------------------------------------------------------
run_target -f app.log -e health-check

hint "検知した結果をさらに grep -Ev に通して、除外パターンに一致する行を取り除きます。"
assert_stdout_contains "検知件数: 3件" "-e health-check を指定すると「検知件数: 3件」になる"

hint "除外した行は画面にも出しません。検知と除外を両方通した結果を表示してください。"
assert_output_not_contains "health-check dummy probe" "除外パターンに一致した行は表示しない"

#-------------------------------------------------------------------------------
describe "正常系: 1件も検知しなかったとき"
#-------------------------------------------------------------------------------
run_target -f app.log -p PANIC

hint "0件のときも件数の行は必ず出します。空文字を数えて1件にしていませんか。"
assert_stdout_contains "検知件数: 0件" "検知が0件のときは「検知件数: 0件」と表示する"

hint "異常が無かったのだから、これは正常終了です。exit 0 で終わります。"
assert_status 0 "検知が0件のときは終了ステータス0で終わる"

finish
