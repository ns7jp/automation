#!/bin/bash
#===============================================================================
# ex11: 正規表現でログを検知する(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている「検知パターンと除外パターンを両方持つ」「異常を
# 見つけたら非0で終わる」という形は、案件No.3 log-watch-alert.sh と同じ
# 監視スクリプトの定番構成です。意味を理解したうえで真似してください。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   検知パターンの変数名をタイプミスすると「空パターン=全行に一致」となり、
#   ログ全部が異常として通知される事故になる。set -u はその手前で止めるための保険。
#
# set -e はあえて使わない。grep は「1件も見つからなかった」ときに終了ステータス1を
# 返す仕様で、これはこのスクリプトにとって異常ではなく正常な結果だからである。
# set -e を付けると、その時点でスクリプトが黙って終わってしまう。
set -u

#===============================================================================
# 1. 設定値(オプションで上書きできる既定値)
#
#   既定値は変数の初期値として先に入れておく。こうしておくと getopts の case は
#   「指定されたときだけ上書きする」という単純な処理で済む。
#
#   PATTERN をダブルクォートで囲んでいるのは、| をシェルがパイプとして
#   解釈しないようにするため。クォートを外すと文法エラーになる。
#===============================================================================
SCRIPT_NAME="$(basename "$0")"
LOG_FILE=""                          # -f で指定する。未指定はエラー
PATTERN="ERROR|FATAL|CRITICAL"       # -p の既定値
EXCLUDE_PATTERN=""                   # -e の既定値。空なら除外しない

#===============================================================================
# 2. 使い方の表示
#
#   既定値をメッセージにも書いておくと、ヘルプと実装の食い違いが起きにくい。
#===============================================================================
usage() {
    echo "使い方: ${SCRIPT_NAME} -f <ログファイル> [-p <検知パターン>] [-e <除外パターン>] [-h]"
    echo "  ログファイルから検知パターンに一致する行を探して表示します。"
    echo "  -f <ログファイル>    調べるログファイル (必須)"
    echo "  -p <検知パターン>    検知する拡張正規表現 (既定: ${PATTERN})"
    echo "  -e <除外パターン>    検知結果から取り除く拡張正規表現 (既定: 除外しない)"
    echo "  -h                   この使い方を表示します"
}

#===============================================================================
# 3. オプションの解析
#
#   "f:p:e:h" の : は「そのオプションは値を取る」という印で、値は $OPTARG に入る。
#   -h は値を取らないので : を付けない。
#
#   ヘルプ(-h)は利用者が意図して求めた出力なので標準出力に出して exit 0。
#   未定義のオプション(\?)は操作ミスなので標準エラー出力に出して exit 1。
#   この2つを区別しておくと、cron から呼ばれたときに「ヘルプが出ただけなのに
#   異常扱いされる」といった誤検知を防げる。
#===============================================================================
while getopts "f:p:e:h" opt; do
    case "$opt" in
        f)  LOG_FILE="$OPTARG" ;;
        p)  PATTERN="$OPTARG" ;;
        e)  EXCLUDE_PATTERN="$OPTARG" ;;
        h)  usage; exit 0 ;;
        \?) usage >&2; exit 1 ;;
    esac
done

#===============================================================================
# 4. 入力チェック
#
#   監視スクリプトは無人で動く。「引数を間違えたまま静かに0件を報告し続ける」のが
#   いちばん怖いので、前提が崩れていたら必ずエラーで止める。
#
#   -z は「空文字である」、-f は「通常ファイルとして存在する」という判定。
#   エラーは標準エラー出力(>&2)に出す。検知結果(標準出力)と混ざらないように
#   分けておくと、./scan_log.sh -f app.log > result.txt のように保存したときに
#   エラーだけは画面に残る。
#===============================================================================
if [[ -z "$LOG_FILE" ]]; then
    echo "エラー: -f で調べるログファイルを指定してください" >&2
    usage >&2
    exit 1
fi

if [[ ! -f "$LOG_FILE" ]]; then
    echo "エラー: ログファイルが見つかりません: ${LOG_FILE}" >&2
    exit 1
fi

#===============================================================================
# 5. 検知
#
#   grep -E は拡張正規表現(ERE)モード。ERROR|FATAL|CRITICAL のような
#   OR 条件をそのまま書ける。
#
#   -- は「ここから先はオプションではない」という区切り。検知パターンが
#   -v のように - で始まっていても、オプションと誤解されなくなる。
#
#   1件も一致しないと grep は終了ステータス1を返すが、set -e を使っていないので
#   スクリプトは止まらず、MATCHED は空文字になる。
#===============================================================================
MATCHED="$(grep -E -- "$PATTERN" "$LOG_FILE")"

#===============================================================================
# 6. 除外
#
#   監視ツール自身が定期的に出す「想定内のERROR」まで通知していると、
#   本物の異常が埋もれてしまう(アラート疲れ)。そこで検知結果から
#   除外パターンに一致する行を取り除く。
#
#   grep -v は「一致した行を捨てる」オプション。
#
#   [[ -n "$MATCHED" ]] を条件に加えているのは、MATCHED が空のときに
#   printf '%s\n' "" を流すと「空行が1行ある」状態になり、除外後の結果が
#   意図せず空行1行になってしまうのを防ぐため。
#===============================================================================
if [[ -n "$EXCLUDE_PATTERN" && -n "$MATCHED" ]]; then
    MATCHED="$(printf '%s\n' "$MATCHED" | grep -Ev -- "$EXCLUDE_PATTERN")"
fi

#===============================================================================
# 7. 表示と件数の集計
#
#   ここで wc -l を使わずに自分で数えているのは、空文字を数えると
#   「0件なのに1件」と報告してしまう有名な落とし穴を避けるため。
#     echo "" | wc -l  → 1
#   表示しながら COUNT を増やせば、表示した行数と件数が必ず一致する。
#
#   IFS= read -r は「行頭・行末の空白を削らず、バックスラッシュも文字として扱う」
#   ための定番の組み合わせ。ログの行をそのままの形で扱いたいので必ずこう書く。
#
#   <<< はヒアストリング。変数の中身をコマンドの標準入力として渡す。
#   printf を使っているのは、ログ行が -n のような文字列で始まっていても
#   echo がオプションと誤解しないようにするため。
#===============================================================================
COUNT=0
if [[ -n "$MATCHED" ]]; then
    while IFS= read -r line; do
        printf '検知: %s\n' "$line"
        COUNT=$((COUNT + 1))
    done <<< "$MATCHED"
fi

printf '検知件数: %d件\n' "$COUNT"

#===============================================================================
# 8. 終了ステータス
#
#   監視スクリプトの慣習として、異常を検知したら0以外を返す。
#   cron や systemd、CI といった呼び出し側は終了ステータスしか見ていないため、
#   これが「異常を伝える唯一の手段」になる。
#
#     ./scan_log.sh -f app.log || notify.sh "ログに異常あり"
#
#   のように、後続の処理へつなげられるのがこの約束の利点。
#===============================================================================
if [[ "$COUNT" -gt 0 ]]; then
    exit 1
fi

exit 0
