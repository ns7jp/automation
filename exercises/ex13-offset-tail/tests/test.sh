#!/bin/bash
#===============================================================================
# ex13 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#
#   ログファイルと状態ファイルは、このテストの中で作業ディレクトリに作る。
#   「1回目 → 追記して2回目 → 変更なしで3回目 → ローテートして4回目」と
#   順番に実行し、そのつど出力と状態ファイルを確認する。
#   現在時刻には一切依存しないため、いつ実行しても結果は同じになる。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

# 採点で使うログファイルと状態ファイル(harness により $WORKDIR に cd 済み)
LOG_FILE="${WORKDIR}/app.log"
STATE_FILE="${WORKDIR}/app.log.offset"

#-------------------------------------------------------------------------------
describe "異常系: 引数を渡さずに実行したとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。1個でなければ exit 1 で終了してください。"
assert_status 1 "引数が無いと終了ステータス1で終わる"

hint "エラーと使い方は echo \"...\" >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "異常系: 存在しないログファイルを指定したとき"
#-------------------------------------------------------------------------------
run_target "${WORKDIR}/no-such-file.log"

hint "[[ ! -f \"\$LOG_FILE\" ]] で存在しないことを判定し、exit 1 で終了します。"
assert_status 1 "ログファイルが無いと終了ステータス1で終わる"

hint "メッセージは「エラー: ログファイルが見つかりません: <パス>」の形式です。"
assert_stderr_contains "ログファイルが見つかりません" \
    "ログファイルが見つからないことを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: 1回目の実行(状態ファイルが無い)"
#-------------------------------------------------------------------------------
rm -f "$STATE_FILE"
cat > "$LOG_FILE" <<'EOF'
2026-09-06 10:00:00 INFO サービスを起動しました
2026-09-06 10:00:05 WARN ディスク使用率 82%
2026-09-06 10:00:09 ERROR データベースに接続できません
EOF

run_target app.log

hint "正常に処理できた場合は exit 0 です。"
assert_status 0 "1回目の実行は終了ステータス0で終わる"

hint "状態ファイルが無いときは全行が新規です。書式は「新規行: <行の内容>」です。"
assert_stdout_contains "新規行: 2026-09-06 10:00:00 INFO サービスを起動しました" \
    "状態ファイルが無いときは全行を「新規行: <内容>」の形式で表示する"

hint "まとめ行の書式は「新規: 3行 (総行数: 3行)」です。括弧もコロンのあとの空白も半角です。"
assert_stdout_contains "新規: 3行 (総行数: 3行)" \
    "最後に「新規: 3行 (総行数: 3行)」を表示する"

hint "状態ファイルは <ログファイルのパス>.offset です。中身は行数の数字だけを書きます。"
assert_file_contains "$STATE_FILE" '^3$' \
    "状態ファイル app.log.offset に総行数 3 だけを書き込む"

#-------------------------------------------------------------------------------
describe "正常系: 2回目の実行(2行追記したあと)"
#-------------------------------------------------------------------------------
cat >> "$LOG_FILE" <<'EOF'
2026-09-06 10:05:00 INFO 再接続に成功しました
2026-09-06 10:05:30 ERROR タイムアウトが発生しました
EOF

run_target app.log

hint "読み始める行番号は「前回の行数 + 1」です。tail -n \"+4\" で4行目から取り出せます。"
assert_stdout_contains "新規行: 2026-09-06 10:05:30 ERROR タイムアウトが発生しました" \
    "追記された行を新規として表示する"

hint "前回処理した行を再表示してはいけません。tail -n 5 のような末尾指定になっていませんか。"
assert_output_not_contains "新規行: 2026-09-06 10:00:00 INFO サービスを起動しました" \
    "前回すでに処理した行は表示しない"

hint "新規は2行、総行数は5行です。"
assert_stdout_contains "新規: 2行 (総行数: 5行)" \
    "「新規: 2行 (総行数: 5行)」を表示する"

hint "処理し終えたあとに、状態ファイルを今の総行数で上書き(>)します。"
assert_file_contains "$STATE_FILE" '^5$' "状態ファイルを総行数 5 に更新する"

#-------------------------------------------------------------------------------
describe "正常系: 3回目の実行(ログが増えていない)"
#-------------------------------------------------------------------------------
run_target app.log

hint "新規行が0行でも「正常に確認できた」ので、exit 0 で終わります。"
assert_status 0 "新規行が0行のときも終了ステータス0で終わる"

hint "新規行が0行でも、まとめ行だけは必ず表示します。"
assert_stdout_contains "新規: 0行 (総行数: 5行)" \
    "新規行が0行のときも「新規: 0行 (総行数: 5行)」を表示する"

#-------------------------------------------------------------------------------
describe "正常系: 4回目の実行(ログローテート相当。1行だけに作り直す)"
#-------------------------------------------------------------------------------
cat > "$LOG_FILE" <<'EOF'
2026-09-06 11:00:00 INFO ログをローテートしました
EOF

run_target app.log

hint "今の行数(1)が状態ファイルの値(5)より小さいときがローテートです。-lt で比較します。"
assert_stdout_contains "ログがローテートされたため先頭から読み直します" \
    "行数が減っていたらローテートを検知してメッセージを表示する"

hint "メッセージを出すだけでは足りません。前回の行数を0に戻して、先頭から読み直してください。"
assert_stdout_contains "新規行: 2026-09-06 11:00:00 INFO ログをローテートしました" \
    "ローテート後は全行を新規として表示する"

hint "ローテート後の新規は1行、総行数も1行です。"
assert_stdout_contains "新規: 1行 (総行数: 1行)" \
    "「新規: 1行 (総行数: 1行)」を表示する"

finish
