#!/bin/bash
#===============================================================================
# ex13: 前回の続きから読む(差分処理)(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている「状態ファイルに位置を覚えておく」「処理し終えてから
# 状態を更新する」「行数が減ったらローテートとみなす」という形は、cron から
# 定期実行する監視スクリプトの定番構成です。意味を理解したうえで真似してください。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   例えば $STATE_FIL のようにタイプミスすると、set -u が無ければ空文字として
#   扱われ、状態ファイルを毎回作り直す(=毎回全行を処理する)動きになる。
#   原因が非常に分かりにくいので、この保険を掛けておく。
#
# set -e はあえて使わない。この演習の範囲では失敗しうるコマンドを個別に
# チェックしており、途中で黙って終了されるほうが調査しにくいためである。
set -u

#===============================================================================
# 1. 使い方の表示
#
#   「引数の個数が違うとき」に使う。関数にしておくと、あとで
#   -h オプションを足したくなったときも、同じメッセージを再利用できる。
#===============================================================================
usage() {
    echo "使い方: $(basename "$0") <ログファイル>"
    echo "  前回の続きから、増えた行だけを読み取って表示します。"
}

#===============================================================================
# 2. 引数チェック
#
#   $# は引数の個数。-ne は「等しくない(not equal)」。
#   0個でも2個以上でも同じ「使い方の間違い」なので、まとめて弾く。
#
#   エラーは標準エラー出力(>&2)に出す。このスクリプトは
#     read_new_lines.sh app.log >> /var/log/new_lines.log
#   のように出力を保存して使うことが多く、そのときエラーだけは
#   画面(や cron のメール)に残ってほしいからである。
#===============================================================================
if [[ "$#" -ne 1 ]]; then
    echo "エラー: ログファイルを1つ指定してください。" >&2
    usage >&2
    exit 1
fi

LOG_FILE="$1"

#===============================================================================
# 3. ログファイルの存在チェック
#
#   -f は「通常ファイルとして存在する」という判定。! を付けて否定している。
#   監視スクリプトで最も怖いのは「対象を読めていないのに正常終了すること」なので、
#   前提が崩れていたら必ずエラーで止める。
#===============================================================================
if [[ ! -f "$LOG_FILE" ]]; then
    echo "エラー: ログファイルが見つかりません: ${LOG_FILE}" >&2
    exit 1
fi

#===============================================================================
# 4. 状態ファイルの決定と読み込み
#
#   状態ファイルは「<ログファイルのパス>.offset」に置く。ログの隣に置くことで、
#   複数のログを別々に監視しても、状態ファイルが取り違えられることがない。
#
#   ファイルがまだ無い1回目は LAST_LINE=0 のままにする。
#   「0行目まで処理済み」= 全行が新規、という自然な意味になる。
#===============================================================================
STATE_FILE="${LOG_FILE}.offset"

LAST_LINE=0
if [[ -f "$STATE_FILE" ]]; then
    LAST_LINE="$(cat "$STATE_FILE")"
fi

#===============================================================================
# 5. 現在の総行数を数える
#
#   wc -l < "$LOG_FILE" のように「<」でリダイレクトするのが重要。
#   wc -l "$LOG_FILE" と書くと「3 app.log」のようにファイル名まで出力され、
#   そのままでは計算に使えない。
#
#   なお wc -l は「改行の個数」を数える。最終行が改行で終わっていないログでは
#   1行少なく数えられるが、一般的なログ出力は必ず改行で終わるため実用上は問題ない。
#===============================================================================
TOTAL_LINES="$(wc -l < "$LOG_FILE")"

#===============================================================================
# 6. ログローテートの検知
#
#   ログは肥大化を防ぐために定期的に退避・空にされる(ログローテート)。
#   その結果、行数は「増える」だけでなく「いきなり減る」ことがある。
#
#   もし減っているのに前回の続き(例: 10001行目)から読もうとすると、
#   新しいログを1行も読めないまま「新規0行」を報告し続けることになる。
#   これは監視が死んでいるのと同じで、事故の温床になる。
#
#   そこで「今の行数 < 前回の行数」なら先頭から読み直す。
#   通常運用で行数が減ることはないため、この単純な比較で十分機能する。
#===============================================================================
if [[ "$TOTAL_LINES" -lt "$LAST_LINE" ]]; then
    echo "ログがローテートされたため先頭から読み直します"
    LAST_LINE=0
fi

#===============================================================================
# 7. 新規行の表示
#
#   読み始める行番号は「前回までに処理した行数 + 1」。
#   tail -n +N は「N行目から最後まで」を意味する(-n 10 の「末尾10行」とは別物)。
#   +1 がファイルの先頭で、+0 という指定は使わない。
#
#   while IFS= read -r line は「1行ずつ、加工せずに読む」定型句。
#     IFS=  : 行頭・行末の空白を削らない
#     -r    : バックスラッシュをエスケープ記号として解釈しない
#   ログには空白やバックスラッシュがそのまま出てくるため、この形が安全である。
#
#   < <(コマンド) はプロセス置換。コマンドの出力をファイルのように読み込む。
#   tail ... | while ... というパイプでも書けるが、その場合 while はサブシェル
#   (別プロセス)で動くため、ループ内で更新した変数がループの外に残らない。
#   今回は変数を更新していないので実害はないが、後から集計を足したくなったときに
#   ハマりやすいので、最初からプロセス置換で書く癖を付けておくとよい。
#===============================================================================
NEW_COUNT=$((TOTAL_LINES - LAST_LINE))

if [[ "$NEW_COUNT" -gt 0 ]]; then
    while IFS= read -r line; do
        echo "新規行: ${line}"
    done < <(tail -n "+$((LAST_LINE + 1))" "$LOG_FILE")
fi

#===============================================================================
# 8. まとめの表示と状態ファイルの更新
#
#   状態ファイルの更新は「新規行を処理し終えたあと」に行う。
#   先に更新してしまうと、表示や通知の途中で異常終了したときに
#   「まだ処理していない行を処理済みとして記録する」ことになり、
#   その分の行が永久に失われる。
#
#   書き込みは >> (追記) ではなく > (上書き) を使う。この状態ファイルは
#   常に「最新の1つの数字」だけを持っていればよいからである。
#===============================================================================
echo "新規: ${NEW_COUNT}行 (総行数: ${TOTAL_LINES}行)"

printf '%s\n' "$TOTAL_LINES" > "$STATE_FILE"

# 新規行が0行でも「正常に確認できた」ことに変わりはないので、成功で終わる。
exit 0
