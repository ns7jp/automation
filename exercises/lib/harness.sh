#!/bin/bash
#===============================================================================
# harness.sh — 演習の自動採点を安全に実行するための共通処理
#
# 概要:
#   各演習の tests/test.sh は、先頭でこのファイルを読み込む。
#   このファイルは次の3つを用意する。
#
#     1. 使い捨ての作業ディレクトリ($WORKDIR)
#        採点はすべてこの中で行う。あなたのホームディレクトリや
#        システムのファイルを書き換えることは一切ない。
#
#     2. ダミーコマンド(スタブ)の仕組み
#        useradd / ping / curl などの「本物を動かすと危険・または
#        root権限が必要」なコマンドを、呼び出しを記録するだけの
#        偽物に差し替える。これにより一般ユーザー権限のまま、
#        実サーバーを持っていなくても採点できる。
#
#     3. 対象スクリプトを実行するための関数(run_target)
#        標準出力・標準エラー出力・終了ステータスを取得する。
#
#   このファイル自体を編集する必要はありません。
#   仕組みの詳細は docs/04-self-check-guide.md を参照してください。
#
# check.sh から渡される環境変数:
#   EX_ROOT  : exercises ディレクトリの絶対パス
#   EX_DIR   : 採点対象の演習ディレクトリの絶対パス
#   EX_LIB   : ライブラリ(このファイルがある)ディレクトリ
#   MODE     : work(自分の解答) または answer(解答例)
#   TARGET   : 採点対象ファイルの絶対パス
#===============================================================================

set -u

# 判定関数ライブラリを読み込む
# shellcheck source=./assert.sh
source "${EX_LIB:?EX_LIB が未設定です。check.sh 経由で実行してください}/assert.sh"

#-------------------------------------------------------------------------------
# 実行タイムアウト(秒)
#   無限ループを書いてしまった場合でも、採点が固まらないようにするための保険。
#   個別の演習で伸ばしたい場合は test.sh 側で TIMEOUT_SEC=30 のように上書きする。
#-------------------------------------------------------------------------------
TIMEOUT_SEC="${TIMEOUT_SEC:-20}"

#-------------------------------------------------------------------------------
# 使い捨ての作業ディレクトリを作る
#   mktemp -d は「他と衝突しない一時ディレクトリ」を作るコマンド。
#   trap で「このスクリプトが終了したら必ず消す」よう予約しておく。
#-------------------------------------------------------------------------------
WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/exercise-check.XXXXXX")"
STUB_DIR="${WORKDIR}/.stubs"
STUB_LOG="${WORKDIR}/.stub-calls.log"
mkdir -p "$STUB_DIR"
: > "$STUB_LOG"
export STUB_LOG

_cleanup() {
    # KEEP_WORKDIR=1 を付けて実行すると、調査用に作業ディレクトリを残せる
    if [[ -n "${KEEP_WORKDIR:-}" ]]; then
        printf '  %s作業ディレクトリを残しました: %s%s\n' "${_C_GRAY}" "$WORKDIR" "${_C_OFF}"
        return 0
    fi
    [[ -n "${WORKDIR:-}" && -d "$WORKDIR" ]] && rm -rf "$WORKDIR"
    return 0
}
trap _cleanup EXIT

# 以降、テストは作業ディレクトリの中で動く(相対パスはすべてこの中を指す)
cd "$WORKDIR" || exit 1

#-------------------------------------------------------------------------------
# 直前の実行結果を保持する変数(assert_* 関数が参照する)
#-------------------------------------------------------------------------------
# shellcheck disable=SC2034  # assert.sh 側から参照されるため、ここでは未使用に見える
LAST_STDOUT=""
LAST_STDERR=""
LAST_OUTPUT=""
LAST_STATUS=0

#-------------------------------------------------------------------------------
# require_target: 採点対象ファイルが存在するか確認する
#   存在しない場合はその場で不合格として終了する。
#-------------------------------------------------------------------------------
require_target() {
    if [[ ! -f "$TARGET" ]]; then
        printf '  %s✗ 採点対象のファイルが見つかりません: %s%s\n' "$_C_RED" "$TARGET" "$_C_OFF"
        printf '      README.md の「作業するファイル」を確認してください。\n'
        exit 1
    fi
    return 0
}

#-------------------------------------------------------------------------------
# enable_stubs: 指定したコマンドをダミー(スタブ)に差し替える
#   例: enable_stubs useradd groupadd chpasswd chage getent
#
#   差し替えたコマンドは、呼び出し内容が $STUB_LOG に1行ずつ記録される。
#   記録内容は assert_stub_called / assert_stub_not_called で判定できる。
#-------------------------------------------------------------------------------
enable_stubs() {
    local cmd
    for cmd in "$@"; do
        cp "${EX_LIB}/stubs/_recorder.sh" "${STUB_DIR}/${cmd}"
        chmod +x "${STUB_DIR}/${cmd}"
    done
    return 0
}

#-------------------------------------------------------------------------------
# reset_stub_log: スタブの呼び出し記録を消す
#   1つの test.sh の中で複数回スクリプトを実行するとき、
#   「今回の実行で何が呼ばれたか」だけを見たい場合に使う。
#-------------------------------------------------------------------------------
reset_stub_log() {
    : > "$STUB_LOG"
    return 0
}

#-------------------------------------------------------------------------------
# run_target: 採点対象のスクリプトを実行する
#   使い方: run_target -f users.csv --dry-run
#
#   実行後、次の変数に結果が入る。
#     LAST_STDOUT : 標準出力
#     LAST_STDERR : 標準エラー出力
#     LAST_OUTPUT : 標準出力と標準エラー出力をつないだもの
#     LAST_STATUS : 終了ステータス(タイムアウト時は124)
#-------------------------------------------------------------------------------
run_target() {
    run_script "$TARGET" "$@"
}

#-------------------------------------------------------------------------------
# run_script: 任意のスクリプトを作業ディレクトリ内で実行する
#   run_target と同じ結果変数を設定する。
#-------------------------------------------------------------------------------
run_script() {
    local script="$1"
    shift
    local out="${WORKDIR}/.stdout" err="${WORKDIR}/.stderr"

    (
        cd "$WORKDIR" || exit 1
        PATH="${STUB_DIR}:${PATH}" \
        STUB_LOG="$STUB_LOG" \
            timeout "$TIMEOUT_SEC" bash "$script" "$@"
    ) > "$out" 2> "$err"
    # shellcheck disable=SC2034  # assert_status などが参照する
    LAST_STATUS=$?

    LAST_STDOUT="$(cat "$out")"
    LAST_STDERR="$(cat "$err")"
    # shellcheck disable=SC2034  # assert_output_* が参照する
    if [[ -n "$LAST_STDERR" ]]; then
        LAST_OUTPUT="${LAST_STDOUT}"$'\n'"${LAST_STDERR}"
    else
        LAST_OUTPUT="${LAST_STDOUT}"
    fi
    return 0
}

#-------------------------------------------------------------------------------
# note: 採点中の補足メッセージを表示する
#-------------------------------------------------------------------------------
note() {
    printf '  %s%s%s\n' "$_C_GRAY" "$1" "$_C_OFF"
    return 0
}

#-------------------------------------------------------------------------------
# assert_no_syntax_error: bash の構文エラーがないことを確認する
#   bash -n は「実行せずに文法だけチェックする」オプション。
#   最初にこれを確認しておくと、以降の失敗理由が分かりやすくなる。
#-------------------------------------------------------------------------------
assert_no_syntax_error() {
    hint "bash -n ${TARGET#"$EX_ROOT"/} を実行すると、エラー箇所の行番号が分かります。引用符や fi / done の閉じ忘れが原因のことが多いです。"
    assert_cmd "bashの構文エラーがない" bash -n "$TARGET"
    return 0
}
