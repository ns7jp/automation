# set -u : 未定義の変数を使ったらエラーで止める(タイプミス検知のため)
# set -e は付けない。1件失敗しても最後までテストを走らせ、
# 何件失敗したかをまとめて報告したいため。
set -u

#-------------------------------------------------------------------------------
# TODO 1: 検査対象のプロジェクトディレクトリを決める
#   1個目の引数を使う。引数が無ければカレントディレクトリ(.)を使う。
#   ヒント: ${1:-既定値} と書くと「引数が無ければ既定値」という意味になる
#-------------------------------------------------------------------------------
PROJECT_DIR=""

# 成功・失敗・スキップの件数を数えるカウンタ(ここは書き換えなくてよい)
PASS_COUNT=0
FAIL_COUNT=0
SKIP_COUNT=0

#-------------------------------------------------------------------------------
# 使い方を表示する関数(ここは書き換えなくてよい)
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") [<プロジェクトディレクトリ>]"
    echo "  省略した場合はカレントディレクトリを検査します。"
}

#-------------------------------------------------------------------------------
# TODO 2: 結果を1行表示し、同時にカウンタを1つ増やす関数を完成させる
#   表示の形式は README の「出力フォーマット」のとおり。
#   ヒント: 数を1つ増やすには PASS_COUNT=$((PASS_COUNT + 1)) と書く
#-------------------------------------------------------------------------------
pass() {
    echo "[PASS] $1"
}

fail() {
    echo "[FAIL] $1"
}

skip_test() {
    echo "[SKIP] $1"
}

#-------------------------------------------------------------------------------
# TODO 3: 指定されたディレクトリが存在しなければ、標準エラー出力に
#         「エラー: ディレクトリが見つかりません: <指定値>」と usage を表示し、
#         終了ステータス1で終わる
#   ヒント: ディレクトリの存在判定は [[ -d "$PROJECT_DIR" ]] 。
#           標準エラー出力に出すには >&2 を付ける
#-------------------------------------------------------------------------------


echo "===== CIテスト開始: ${PROJECT_DIR} ====="

#-------------------------------------------------------------------------------
# TODO 4: T1 必須ファイルが存在するか調べる
#   対象: app/index.html と scripts/deploy.sh (どちらも PROJECT_DIR からの相対)
#   両方あれば pass 、1つでも無ければ fail を呼ぶ。
#   ヒント: ファイルの存在判定は [[ -f "${PROJECT_DIR}/app/index.html" ]]
#-------------------------------------------------------------------------------
T1_DESC="T1: 必須ファイルが存在する"


#-------------------------------------------------------------------------------
# TODO 5: T2 scripts配下の .sh すべてに構文エラーが無いか調べる
#   ヒント: for f in "${PROJECT_DIR}"/scripts/*.sh; do ... done で1つずつ回す。
#           実在しないパターンが渡ることがあるので [[ -f "$f" ]] || continue を入れる。
#           構文チェックは bash -n "$f" 。失敗した数を数えて、0なら pass
#-------------------------------------------------------------------------------
T2_DESC="T2: scripts配下のシェルスクリプトに構文エラーが無い"


#-------------------------------------------------------------------------------
# TODO 6: T3 app/index.html に <title> タグが含まれるか調べる
#   ヒント: grep -qi "<title>" "ファイル" が成功(終了ステータス0)なら含まれている
#-------------------------------------------------------------------------------
T3_DESC="T3: app/index.html に <title> タグがある"


#-------------------------------------------------------------------------------
# TODO 7: T4 scripts配下の .sh すべての1行目が #!/bin/bash か調べる
#   ヒント: 1行目の取り出しは "$(head -n 1 "$f")" 。
#           文字列の比較は [[ "$a" != "$b" ]]
#-------------------------------------------------------------------------------
T4_DESC="T4: scripts配下のシェルスクリプトの1行目が #!/bin/bash である"


#-------------------------------------------------------------------------------
