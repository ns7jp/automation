#   形式は README の「出力フォーマット」のとおり
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 10: 失敗が1件以上なら終了ステータス1、無ければ0で終わる
#   ヒント: [[ "$FAIL_COUNT" -gt 0 ]] で判定する
#-------------------------------------------------------------------------------
exit 0
