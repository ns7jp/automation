#             失敗すれば fail
#   使えない: skip_test を呼ぶ。渡す文字列は README の出力フォーマットを参照
#   ヒント: コマンドが使えるかの判定は command -v shellcheck > /dev/null 2>&1
#-------------------------------------------------------------------------------
T5_DESC="T5: shellcheck の警告が無い"


