#!/bin/bash
#===============================================================================
# ex21: CIで動かすテストスクリプト(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている書き方(結果を関数にまとめる、件数を数える、
# 最後に終了ステータスで成否を返す)は、実務のテストスクリプトでも定番です。
#
# このスクリプトは GitHub Actions の
#   - name: テストを実行する
#     run: bash scripts/test.sh
# のように呼び出されることを想定している。CIは画面の文字を読まず、
# 終了ステータス(0か、それ以外か)だけを見て緑と赤を判定する。
# だから「表示は人間のため、終了ステータスはCIのため」に書き分ける。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   set -e は「あえて付けない」。各テストは失敗しても最後まで走らせて、
#   何件失敗したかをまとめて報告したいため。1件目で止まってしまうと
#   「他にも壊れている箇所があるか」が分からず、直すたびに再実行が必要になる。
set -u

#-------------------------------------------------------------------------------
# 検査対象のプロジェクトディレクトリ
#
#   ${1:-.} は「$1 が無ければ . (カレントディレクトリ)を使う」という書き方。
#   CIからは bash scripts/test.sh のように引数なしで呼ばれることが多いので、
#   既定値を用意しておくと、そのまま使える。
#-------------------------------------------------------------------------------
PROJECT_DIR="${1:-.}"

#-------------------------------------------------------------------------------
# 集計用のカウンタ
#   成功・失敗・スキップを別々に数える。
#   「スキップ」は「その環境では確かめられなかった」という意味であり、
#   「失敗」とは区別する。両者を混ぜると、本当に壊れているのか、
#   単に道具が無いだけなのかがログから読み取れなくなる。
#-------------------------------------------------------------------------------
PASS_COUNT=0
FAIL_COUNT=0
SKIP_COUNT=0

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") [<プロジェクトディレクトリ>]"
    echo "  省略した場合はカレントディレクトリを検査します。"
}

#-------------------------------------------------------------------------------
# 結果を1行表示し、同時にカウンタを増やす関数
#
#   「表示」と「集計」を1か所にまとめておくと、書式を直したいときに
#   ここだけ直せば済む。テストを増やしても数え漏れが起きない。
#-------------------------------------------------------------------------------
pass() {
    echo "[PASS] $1"
    PASS_COUNT=$((PASS_COUNT + 1))
}

fail() {
    echo "[FAIL] $1"
    FAIL_COUNT=$((FAIL_COUNT + 1))
}

# 関数名を skip ではなく skip_test にしている理由:
#   短くありふれた名前は、将来ほかのコマンドや関数と衝突しやすい。
skip_test() {
    echo "[SKIP] $1"
    SKIP_COUNT=$((SKIP_COUNT + 1))
}

#-------------------------------------------------------------------------------
# 前提チェック: 指定されたディレクトリが存在するか
#
#   ここだけは「テストの失敗」ではなく「そもそも検査できない」状態なので、
#   件数には数えず、標準エラー出力にメッセージを出してすぐ終了する。
#-------------------------------------------------------------------------------
if [[ ! -d "$PROJECT_DIR" ]]; then
    echo "エラー: ディレクトリが見つかりません: ${PROJECT_DIR}" >&2
    usage >&2
    exit 1
fi

echo "===== CIテスト開始: ${PROJECT_DIR} ====="

#-------------------------------------------------------------------------------
# T1: 必須ファイルが存在する
#
#   配列にファイル名を並べ、1つずつ確認する。
#   足りないものは MISSING_FILES に貯めておき、あとでまとめて表示する。
#   「何が足りないか」を出しておくと、CIのログを見ただけで直せる。
#-------------------------------------------------------------------------------
T1_DESC="T1: 必須ファイルが存在する"
REQUIRED_FILES=("app/index.html" "scripts/deploy.sh")
MISSING_FILES=()

for f in "${REQUIRED_FILES[@]}"; do
    if [[ ! -f "${PROJECT_DIR}/${f}" ]]; then
        MISSING_FILES+=("$f")
    fi
done

if [[ "${#MISSING_FILES[@]}" -eq 0 ]]; then
    pass "$T1_DESC"
else
    fail "$T1_DESC"
    for f in "${MISSING_FILES[@]}"; do
        echo "       見つからないファイル: ${f}"
    done
fi

#-------------------------------------------------------------------------------
# T2: scripts配下のシェルスクリプトに構文エラーが無い
#
#   bash -n は「実行せずに文法だけ確かめる」オプション。
#   実行しないので、デプロイ用スクリプトを安全に検査できる。
#
#   [[ -f "$f" ]] || continue を入れている理由:
#   *.sh に一致するファイルが1つも無い場合、シェルはパターンの文字列
#   そのもの(scripts/*.sh)をループに渡してしまう。実在チェックで弾く。
#-------------------------------------------------------------------------------
T2_DESC="T2: scripts配下のシェルスクリプトに構文エラーが無い"
T2_NG_FILES=()

for f in "${PROJECT_DIR}"/scripts/*.sh; do
    [[ -f "$f" ]] || continue
    if ! bash -n "$f" 2> /dev/null; then
        T2_NG_FILES+=("$f")
    fi
done

# 補足の行は、必ず結果の1行を出したあとに続けて出す。
# 先に補足を出してしまうと、結果行との対応が読み取りにくくなる。
if [[ "${#T2_NG_FILES[@]}" -eq 0 ]]; then
    pass "$T2_DESC"
else
    fail "$T2_DESC"
    for f in "${T2_NG_FILES[@]}"; do
        echo "       構文エラー: ${f}"
    done
fi

#-------------------------------------------------------------------------------
# T3: app/index.html に <title> タグがある
#
#   grep -q は「見つかったかどうかだけを終了ステータスで返す」オプション。
#   画面には何も出さないので、条件判定に使いやすい。
#   -i を付けて大文字小文字を区別しないようにしている(<TITLE> でも合格)。
#-------------------------------------------------------------------------------
T3_DESC="T3: app/index.html に <title> タグがある"
INDEX_HTML="${PROJECT_DIR}/app/index.html"

if [[ -f "$INDEX_HTML" ]] && grep -qi "<title>" "$INDEX_HTML"; then
    pass "$T3_DESC"
else
    fail "$T3_DESC"
fi

#-------------------------------------------------------------------------------
# T4: scripts配下のシェルスクリプトの1行目が #!/bin/bash である
#
#   1行目のシバンが違うと、CIのランナーでは別のシェルで実行され、
#   手元では動いたのにCIだけ落ちる、という原因の分かりにくい事故になる。
#   head -n 1 で1行目だけを取り出し、文字列として比べる。
#-------------------------------------------------------------------------------
T4_DESC="T4: scripts配下のシェルスクリプトの1行目が #!/bin/bash である"
T4_NG_FILES=()

for f in "${PROJECT_DIR}"/scripts/*.sh; do
    [[ -f "$f" ]] || continue
    if [[ "$(head -n 1 "$f")" != "#!/bin/bash" ]]; then
        T4_NG_FILES+=("$f")
    fi
done

if [[ "${#T4_NG_FILES[@]}" -eq 0 ]]; then
    pass "$T4_DESC"
else
    fail "$T4_DESC"
    for f in "${T4_NG_FILES[@]}"; do
        echo "       1行目が #!/bin/bash ではない: ${f}"
    done
fi

#-------------------------------------------------------------------------------
# T5: shellcheck の警告が無い(shellcheck がある環境だけ)
#
#   command -v コマンド名 は「そのコマンドが使えるか」を調べる定番の書き方。
#   使えれば0、使えなければ0以外を返す(which より移植性が高い)。
#
#   道具が無い環境で「失敗」にしてしまうと、手元では常に赤になり、
#   やがて誰も結果を見なくなる。無いなら「スキップ」として素直に記録する。
#-------------------------------------------------------------------------------
T5_DESC="T5: shellcheck の警告が無い"

if command -v shellcheck > /dev/null 2>&1; then
    if shellcheck "${PROJECT_DIR}"/scripts/*.sh > /dev/null 2>&1; then
        pass "$T5_DESC"
    else
        fail "$T5_DESC"
    fi
else
    skip_test "shellcheck が未インストールのため省略します"
fi

#-------------------------------------------------------------------------------
# 集計の表示と、終了ステータスによる通知
#
#   人間向けの要約を1行出したあと、CI向けに終了ステータスを返す。
#   失敗が1件でもあれば1、無ければ0。この1バイトの情報だけで、
#   GitHub Actions は後続のデプロイジョブを止めるかどうかを決める。
#-------------------------------------------------------------------------------
echo "テスト結果: ${PASS_COUNT}件成功 / ${FAIL_COUNT}件失敗 / ${SKIP_COUNT}件スキップ"

if [[ "$FAIL_COUNT" -gt 0 ]]; then
    exit 1
fi

exit 0
