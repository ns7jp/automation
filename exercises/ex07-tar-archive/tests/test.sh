#!/bin/bash
#===============================================================================
# ex07 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# 採点用の練習データを作業ディレクトリに用意する
#   data/index.html   … 通常ファイル
#   data/style.css    … 通常ファイル
#   data/sub/note.txt … サブディレクトリの中のファイル
#   data/a.log        … 除外されるべきログファイル
#-------------------------------------------------------------------------------
mkdir -p data/sub
echo "<html>index</html>"  > data/index.html
echo "body { margin: 0; }" > data/style.css
echo "memo"                > data/sub/note.txt
echo "2026-09-06 access"   > data/a.log

#-------------------------------------------------------------------------------
# アーカイブの中身の一覧をファイルに書き出す補助関数
#   引数1: アーカイブが置かれたディレクトリ
#   引数2: 一覧の書き出し先
#-------------------------------------------------------------------------------
list_archive() {
    local dir="$1" out="$2" f archive=""
    : > "$out"
    for f in "$dir"/*.tar.gz; do
        [[ -f "$f" ]] && archive="$f"
    done
    if [[ -n "$archive" ]]; then
        tar -tzf "$archive" > "$out" 2>/dev/null
    fi
    return 0
}

#-------------------------------------------------------------------------------
describe "異常系: 引数が足りないとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# です。2個ちょうどでなければ exit 1 で終了してください。"
assert_status 1 "引数なしで実行すると終了ステータス1で終わる"

hint "使い方は usage >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "異常系: 対象ディレクトリが存在しないとき"
#-------------------------------------------------------------------------------
run_target nosuchdir backup_ng

hint "[[ ! -d \"\$SRC_DIR\" ]] で存在を確認し、無ければ exit 1 で止めます。"
assert_status 1 "存在しない対象ディレクトリを指定すると終了ステータス1で終わる"

hint "書式は「エラー: 対象ディレクトリが見つかりません: <パス>」。パスはそのまま出します。"
assert_stderr_contains "エラー: 対象ディレクトリが見つかりません: nosuchdir" \
    "「エラー: 対象ディレクトリが見つかりません: <パス>」を標準エラー出力に出す"

#-------------------------------------------------------------------------------
describe "正常系: data を backup に保存したとき"
#-------------------------------------------------------------------------------
run_target data backup

hint "アーカイブを作れたら exit 0 で終わります。"
assert_status 0 "正常に実行できると終了ステータス0で終わる"

hint "1回の実行で作るアーカイブは1つだけです。保存先を確認してください。"
assert_file_count "backup/*.tar.gz" 1 "保存先に .tar.gz が1つだけ作られる"

hint "名前は backup_<YYYYMMDD>_<HHMMSS>.tar.gz。date '+%Y%m%d_%H%M%S' の結果を埋め込みます。"
assert_cmd "アーカイブ名が backup_<YYYYMMDD>_<HHMMSS>.tar.gz の形式になっている" \
    bash -c 'ls backup | grep -Eq "^backup_[0-9]{8}_[0-9]{6}\.tar\.gz$"'

list_archive backup list.txt

hint "tar -tzf で中身を確認できます。対象ディレクトリの中身が入っていますか。"
assert_file_contains list.txt 'data/index\.html' "アーカイブに data/index.html が含まれる"

hint "--exclude='*.log' を付けます。クォートを忘れると除外が効きません。"
assert_file_not_contains list.txt 'a\.log' "*.log はアーカイブに含めない"

hint "書式は「バックアップ完了: <パス> (サイズ: <du -h の結果>)」。括弧と空白の位置も合わせます。"
assert_stdout_matches 'バックアップ完了: .*backup_[0-9]{8}_[0-9]{6}\.tar\.gz \(サイズ: [^)]+\)' \
    "「バックアップ完了: <保存先のパス> (サイズ: <du -h の結果>)」を標準出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: 保存先ディレクトリがまだ無いとき"
#-------------------------------------------------------------------------------
run_target data out/nested

hint "保存先が無ければ mkdir -p で作ります。-p は親ごとまとめて作ります。"
assert_file_count "out/nested/*.tar.gz" 1 "保存先ディレクトリが無ければ作ってから保存する"

#-------------------------------------------------------------------------------
describe "正常系: 対象を絶対パスで指定したとき"
#-------------------------------------------------------------------------------
run_target "${WORKDIR}/data" backup_abs

list_archive backup_abs list_abs.txt

hint "-C \"\$(dirname ...)\" と \"\$(basename ...)\" に分けて渡すと data/ から始まります。"
assert_file_contains list_abs.txt '^(\./)?data/' \
    "絶対パスで指定してもアーカイブ内のパスが data/ から始まる"

#-------------------------------------------------------------------------------
describe "異常系: tar が失敗したとき"
#   本物の tar の代わりにダミーコマンドを使い、必ず失敗する状況を再現する。
#-------------------------------------------------------------------------------
enable_stubs tar
export STUB_FAIL_CMDS="tar"

run_target data backup_fail

hint "if tar ...; then ... else ... fi のように、tar の終了ステータスで分岐します。"
assert_status 1 "tar が失敗すると終了ステータス1で終わる"

hint "失敗時のメッセージは「エラー: バックアップに失敗しました」。標準エラー出力へ出します。"
assert_stderr_contains "エラー: バックアップに失敗しました" \
    "「エラー: バックアップに失敗しました」を標準エラー出力に出す"

hint "失敗したのに完了メッセージを出してはいけません。else 側で exit 1 して止めます。"
assert_output_not_contains "バックアップ完了" "tar が失敗したときは完了メッセージを表示しない"

finish
