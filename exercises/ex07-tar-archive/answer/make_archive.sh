#!/bin/bash
#===============================================================================
# ex07: tarでバックアップを作る(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている「前提を全部確認してから危ない処理をする」順番と、
# 「tar の終了ステータスで成否を分ける」書き方は、案件No.2の backup.sh と
# まったく同じ構成です。バックアップ処理の「型」として真似してください。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   バックアップは cron から人が見ていない時間に動く。変数のタイプミスで
#   空文字のまま tar を実行してしまうと、中身が空のアーカイブが毎晩作られ、
#   本当に必要になったときに「戻せない」ことに気づく。set -u はその最初の防御線。
set -u

# $0 はスクリプト自身のパス。basename でパスを除いた名前だけにしておくと、
# どこから呼ばれても使い方メッセージの見た目が変わらない。
SCRIPT_NAME="$(basename "$0")"

#===============================================================================
# 1. 使い方の表示
#
#   引数エラーのときと、将来 --help を足したときの両方から呼べるよう関数にする。
#   メッセージを直す場所が1か所で済むのが関数にする最大の利点。
#===============================================================================
usage() {
    echo "使い方: ${SCRIPT_NAME} <バックアップ対象ディレクトリ> <保存先ディレクトリ>"
    echo "  対象ディレクトリを tar.gz に固めて保存先へ保存します。"
    echo "  *.log は除外されます。"
}

#===============================================================================
# 2. 引数の個数チェック
#
#   $# は引数の個数。-ne は「等しくない」。
#   「2個未満」ではなく「2個ちょうどでない」で判定すると、
#   引数を3個渡してしまった打ち間違いも同時に検出できる。
#
#   使い方は「利用者の操作ミスを知らせる出力」なので標準エラー出力(>&2)に出す。
#   usage >&2 と書くと、関数の中の echo をまとめて標準エラー出力へ向けられる。
#===============================================================================
if [[ "$#" -ne 2 ]]; then
    usage >&2
    exit 1
fi

SRC_DIR="$1"
DEST_DIR="$2"

#===============================================================================
# 3. 対象ディレクトリの存在チェック
#
#   -d は「ディレクトリとして存在するか」。-f(通常ファイル)と間違えやすい。
#
#   ここで止めずに tar を実行すると、中身が空のアーカイブができてしまう。
#   「バックアップは作れているように見えるのに中身が無い」は最悪の失敗なので、
#   危ない処理に入る前に必ず前提を確認して落とす。
#===============================================================================
if [[ ! -d "$SRC_DIR" ]]; then
    echo "エラー: 対象ディレクトリが見つかりません: ${SRC_DIR}" >&2
    exit 1
fi

#===============================================================================
# 4. 保存先ディレクトリの用意
#
#   -p は「途中の親ディレクトリもまとめて作る」「既に存在してもエラーにしない」
#   という2つの意味を持つ。初回実行でも2回目以降でも同じように動かせるので、
#   自動化スクリプトでは mkdir -p を使うのが定番。
#===============================================================================
mkdir -p "$DEST_DIR"

#===============================================================================
# 5. アーカイブ名の組み立て
#
#   backup_20260906_031500.tar.gz のように日時を埋め込む。
#   同じ名前で上書きしてしまうと過去のバックアップが消えるため、
#   秒まで入れて「実行するたびに必ず別名になる」ようにしている。
#
#   ${DEST_DIR%/} は末尾のスラッシュを1つ取り除くパラメータ展開。
#   backup/ と指定されても backup//backup_... という二重スラッシュにならない。
#===============================================================================
TIMESTAMP="$(date '+%Y%m%d_%H%M%S')"
ARCHIVE_NAME="backup_${TIMESTAMP}.tar.gz"
ARCHIVE_PATH="${DEST_DIR%/}/${ARCHIVE_NAME}"

#===============================================================================
# 6. tar に渡す「親ディレクトリ」と「対象の名前」を取り出す
#
#   dirname  /var/www/html → /var/www
#   basename /var/www/html → html
#
#   この2つに分けておいて -C "$SRC_PARENT" "$SRC_BASE" と渡すと、
#   tar は /var/www に移動してから html を固める。
#   結果としてアーカイブの中は html/index.html のような短い相対パスになる。
#
#   分けずに絶対パスをそのまま渡すと、tar は先頭の / を取り除いて
#   var/www/html/index.html という深いパスで保存する。
#   別のサーバーの作業ディレクトリで展開したときに、
#   意図しない場所へファイルが散らばる原因になる。
#===============================================================================
SRC_PARENT="$(dirname "$SRC_DIR")"
SRC_BASE="$(basename "$SRC_DIR")"

#===============================================================================
# 7. アーカイブの作成と成否の判定
#
#   tar のオプション:
#     c = create   新しいアーカイブを作る
#     z = gzip     圧縮する
#     f = file     直後にアーカイブのファイル名を指定する
#     --exclude='*.log'  アクセスログなど、戻す必要がなくサイズだけ大きい
#                        ファイルを除外する。シングルクォートで囲むのが重要で、
#                        囲まないとシェルが先に * を展開してしまう。
#
#   if tar ...; then ... else ... fi は「コマンドの終了ステータスで分岐する」
#   書き方。$? を変数に取ってから比較しても同じことができるが、
#   間に別のコマンドを挟むと $? が上書きされる事故が起きるため、
#   直接 if に書くほうが安全。
#
#   set -e を使っていないのは、失敗したときにも自分の言葉でエラーメッセージを
#   出してから終了したいため。案件No.2の backup.sh も同じ考え方で書かれている。
#===============================================================================
if tar -czf "$ARCHIVE_PATH" --exclude='*.log' -C "$SRC_PARENT" "$SRC_BASE"; then
    # du -h の出力は「サイズ<タブ>パス」なので、cut -f1 で1列目だけ取り出す。
    # -h は human readable(4096 ではなく 4.0K のように読みやすい単位で出す)。
    ARCHIVE_SIZE="$(du -h "$ARCHIVE_PATH" | cut -f1)"
    echo "バックアップ完了: ${ARCHIVE_PATH} (サイズ: ${ARCHIVE_SIZE})"
    exit 0
else
    # 失敗はエラーメッセージだけでなく、終了ステータス1でも伝える。
    # cron や CI は画面を見ないので、終了ステータスが唯一の連絡手段になる。
    echo "エラー: バックアップに失敗しました" >&2
    exit 1
fi
