#!/bin/bash
#===============================================================================
# ex02: 入力チェックと安全装置(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている「駄目な条件を見つけたらその場で exit する」書き方は
# 実務のシェルスクリプトの定番なので、意味を理解したうえで真似することを勧めます。
#
# このスクリプトの役割:
#   本処理(CSVの読み込みなど)を始める前に、入力ファイルが本当に使える状態かを
#   確認する「安全装置」。問題があれば、理由ごとに違う終了ステータスで停止する。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   例えば $INPUT_FIL のようにタイプミスした場合、set -u が無いと「空文字」として
#   動いてしまい、原因の分かりにくいバグになる。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#
#   引数エラーのときに2行のメッセージを出すが、関数にしておけば
#   将来 --help を足したくなったときも同じ関数を呼ぶだけで済む。
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <入力ファイル>"
    echo "  指定したファイルが、これから処理できる状態かどうかを確認します。"
}

#===============================================================================
# 1. 引数の個数チェック
#
#   $# は引数の個数。-ne は「等しくない(not equal)」。
#   0個でも2個以上でもエラーにしたいので「1と等しくない」で判定する。
#
#   エラーメッセージは標準エラー出力(>&2)に出す。こうしておくと
#     ./check_input.sh users.csv > result.txt
#   のように結果をファイルに保存したときでも、エラーだけは画面に残る。
#   usage >&2 と書くと、関数が出力する行すべてが標準エラー出力に向かう。
#===============================================================================
if [[ "$#" -ne 1 ]]; then
    echo "エラー: 入力ファイルを1つ指定してください。" >&2
    usage >&2
    exit 1
fi

# 引数はこの先で何度も使うので、意味の分かる名前の変数に入れておく。
# $1 のまま使い回すと、あとで読んだときに何の値か分からなくなる。
INPUT_FILE="$1"

#===============================================================================
# 2. 存在チェック
#
#   -f は「通常ファイルとして存在する」という判定。
#   -e (存在する) ではなく -f を使うのは、ディレクトリを指定されたときも
#   ここで弾きたいため。ディレクトリは wc -l で読めない。
#
#   条件の前の ! は否定。「ファイルとして存在しないなら」という意味になる。
#   ! と -f の間には半角スペースが必要。
#===============================================================================
if [[ ! -f "$INPUT_FILE" ]]; then
    echo "エラー: ファイルが見つかりません: ${INPUT_FILE}" >&2
    exit 2
fi

#===============================================================================
# 3. 読み取り権限チェック
#
#   ファイルはあるのに読めない、というのは共有サーバーではよくある。
#   例: 他部署のメンバーが作ったファイルが 600(所有者だけ読み書き可)のまま
#   置かれている、など。
#
#   ここで止めておかないと、この後の wc や read が空の結果を返し、
#   「0行のCSVを処理した」という誤った成功で終わってしまう。
#
#   注意: root は権限設定を無視してどんなファイルでも読めるため、
#   root で実行するとこの判定は真になりにくい(自動採点でも省略される)。
#===============================================================================
if [[ ! -r "$INPUT_FILE" ]]; then
    echo "エラー: 読み取り権限がありません: ${INPUT_FILE}" >&2
    exit 3
fi

#===============================================================================
# 4. 空ファイルチェック
#
#   -s は「サイズが0より大きい(中身がある)」という判定なので、
#   「空のとき」は ! を付けて否定する。
#
#   Excelで開いて保存し直したら中身が消えていた、転送が途中で切れて0バイトに
#   なっていた、というのは実際に起きる事故。「空でも処理は成功した」と
#   見えてしまうのが一番たちが悪いので、明確にエラーとして扱う。
#===============================================================================
if [[ ! -s "$INPUT_FILE" ]]; then
    echo "エラー: ファイルが空です: ${INPUT_FILE}" >&2
    exit 4
fi

#===============================================================================
# 5. すべての関門を通過した場合の処理
#
#   wc -l は行数を数えるコマンド。
#     wc -l "$INPUT_FILE"    → 「4 users.csv」のようにファイル名まで出る
#     wc -l < "$INPUT_FILE"  → 「4」だけが出る
#   < はリダイレクトで「ファイルの中身を標準入力として流し込む」書き方。
#   wc は自分が読んでいるファイルの名前を知らないので、数字だけを返す。
#   メッセージに埋め込む数値がほしいときは、必ずこちらの形を使う。
#===============================================================================
LINE_COUNT="$(wc -l < "$INPUT_FILE")"

echo "OK: ${INPUT_FILE} は処理できます (${LINE_COUNT}行)"

# 入力に問題が無いことを、呼び出し元へ終了ステータス0で伝える。
exit 0
