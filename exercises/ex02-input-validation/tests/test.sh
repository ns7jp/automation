#!/bin/bash
#===============================================================================
# ex02 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# テストで使う入力ファイルを作業ディレクトリに用意する
#   harness.sh が作った使い捨てディレクトリ($WORKDIR)の中で作業しているので、
#   ここで作ったファイルは採点が終わると自動的に消える。
#-------------------------------------------------------------------------------
cat > users.csv <<'EOF'
氏名,ユーザー名,部署,初期パスワード
佐藤 花子,sato_h,eigyou,Passw0rd!
田中 太郎,tanaka_t,soumu,Secret123
鈴木 一郎,suzuki_i,kaihatsu,Pw12345
EOF

# 1行だけのファイル(行数が固定値ではなく実際に数えられているかを見る)
echo "1行だけのファイル" > one_line.txt

# 中身が空のファイル(サイズ0)
: > empty.csv

# 読み取り権限が無いファイル
echo "secret" > secret.csv
chmod 000 secret.csv

# 空でも読めもしないファイル(判定の順番を確認するため)
: > empty_and_unreadable.csv
chmod 000 empty_and_unreadable.csv

#-------------------------------------------------------------------------------
describe "異常系: 引数の個数が正しくないとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。1個でなければ exit 1 で終了してください。"
assert_status 1 "引数なしで実行すると終了ステータス1で終わる"

hint "使い方のメッセージは echo \"...\" >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

run_target users.csv extra.csv

hint "「1個ではないとき」はエラーです。-ne 1 で判定すると多い場合も検出できます。"
assert_status 1 "引数が2つのときも終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "異常系: ファイルが存在しないとき"
#-------------------------------------------------------------------------------
run_target missing.csv

hint "存在しないときの終了ステータスは 2 です。[[ ! -f \"\$INPUT_FILE\" ]] で判定します。"
assert_status 2 "存在しないファイルを指定すると終了ステータス2で終わる"

hint "メッセージは README の仕様表からそのままコピーしてください。半角コロン+半角スペースです。"
assert_stderr_contains "エラー: ファイルが見つかりません: missing.csv" \
    "標準エラー出力に「エラー: ファイルが見つかりません: <パス>」を表示する"

#-------------------------------------------------------------------------------
describe "異常系: 読み取り権限が無いとき"
#-------------------------------------------------------------------------------
if [[ "$EUID" -eq 0 ]]; then
    note "root は権限設定を無視してファイルを読めるため、実際に動かしての判定はできません。"
    skip "root で採点しているため、読み取り権限のテストは省略します"
    skip "root で採点しているため、読み取り権限のメッセージのテストは省略します"

    # 実行しては確かめられないぶん、-r の判定がコードに書かれているかだけは確認する。
    # ここを省くと、root で採点した人は仕様3を書かないまま合格できてしまう。
    hint "root で採点しているため実行では確かめられませんが、仕様3の [[ ! -r \"\$INPUT_FILE\" ]] の判定は必ず書いてください。"
    assert_file_contains "$TARGET" '-r[[:space:]]+"?\$' \
        "読み取り権限(-r)を判定するコードが書かれている"
else
    run_target secret.csv

    hint "読み取り権限が無いときの終了ステータスは 3 です。判定は [[ ! -r \"\$INPUT_FILE\" ]] です。"
    assert_status 3 "読み取り権限が無いファイルを指定すると終了ステータス3で終わる"

    hint "メッセージは「エラー: 読み取り権限がありません: <パス>」です。"
    assert_stderr_contains "エラー: 読み取り権限がありません: secret.csv" \
        "標準エラー出力に「エラー: 読み取り権限がありません: <パス>」を表示する"

    run_target empty_and_unreadable.csv

    hint "「存在するか」→「読めるか」→「空でないか」の順に判定します。読めないファイルは中身も確認できません。"
    assert_status 3 "空かつ読めないファイルは、空チェックより先に権限エラー(3)になる"
fi

#-------------------------------------------------------------------------------
describe "異常系: ファイルの中身が空のとき"
#-------------------------------------------------------------------------------
run_target empty.csv

hint "空のときの終了ステータスは 4 です。-s は「空でない」なので ! を付けて否定します。"
assert_status 4 "中身が空のファイルを指定すると終了ステータス4で終わる"

hint "メッセージは「エラー: ファイルが空です: <パス>」です。"
assert_stderr_contains "エラー: ファイルが空です: empty.csv" \
    "標準エラー出力に「エラー: ファイルが空です: <パス>」を表示する"

#-------------------------------------------------------------------------------
describe "正常系: 問題のないファイルを指定したとき"
#-------------------------------------------------------------------------------
run_target users.csv

hint "すべての関門を通過したら exit 0 です。"
assert_status 0 "問題のないファイルを指定すると終了ステータス0で終わる"

hint "行数は \$(wc -l < \"\$INPUT_FILE\") で数えます。括弧は半角、行数と「行」の間に空白は入れません。"
assert_stdout_contains "OK: users.csv は処理できます (4行)" \
    "標準出力に「OK: <パス> は処理できます (<行数>行)」を表示する"

hint "問題が無いときにエラーメッセージを出してはいけません。判定は否定形になっているか確認してください。"
assert_output_not_contains "エラー" "問題が無いときはエラーメッセージを表示しない"

run_target one_line.txt

hint "行数を固定値で書かず、wc -l で実際に数えてください。"
assert_stdout_contains "OK: one_line.txt は処理できます (1行)" \
    "行数はファイルごとに数え直した値を表示する"

#-------------------------------------------------------------------------------
describe "書き方のチェック"
#-------------------------------------------------------------------------------
hint "1行目に #!/bin/bash(シバン)を書きます。"
assert_file_contains "$TARGET" '^#!/bin/bash' "1行目にシバンがある"

finish
