#!/bin/bash
#===============================================================================
# ex06: 総合演習 ユーザー一括作成ミニ版(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている書き方は案件No.1の create_users.sh とほぼ同じです。
# 「ex01〜ex05で作った小さな部品を並べると、実務のツールになる」ことを
# 確かめながら読んでください。
#
# 部品の出どころ:
#   usage / 終了ステータス            -> ex01
#   ファイルの存在チェック             -> ex02
#   CSVを1行ずつ読むループ             -> ex03
#   log 関数(レベル付きの出力)        -> ex04
#   getopts とドライラン               -> ex05
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する(タイプミス検知のため)。
#
# set -e(エラーが起きたら即終了)はあえて使わない。
#   このスクリプトは「1行の失敗で全体を止めず、失敗として数えて次の行へ進む」
#   という仕様のため、エラーの扱いは if 文で1件ずつ自分で決める必要がある。
set -u

#===============================================================================
# 1. 既定値と集計用カウンタ
#===============================================================================
CSV_FILE=""                        # -f で指定される。未指定なら空文字のまま
DRY_RUN="false"                    # -n / --dry-run が指定されたら "true"
SCRIPT_NAME="$(basename "$0")"     # パスを除いたスクリプト名(使い方の表示に使う)

SUCCESS_COUNT=0
SKIP_COUNT=0
FAIL_COUNT=0

#===============================================================================
# 2. 使い方の表示(ex01・ex05の復習)
#
#   複数行のメッセージは cat <<EOF ... EOF(ヒアドキュメント)で書くと
#   echo を何行も並べるより読みやすい。
#===============================================================================
usage() {
    cat <<HELP_EOF
使い方: ${SCRIPT_NAME} -f <CSVファイル> [-n]

CSVファイル(氏名,ユーザー名,部署,初期パスワード)を読み込み、
Linuxのユーザーアカウントを一括作成します。

オプション:
  -f <file>   読み込むCSVファイル(必須)
  -n          ドライラン。実際には作成せず、実行内容だけを表示します。
              --dry-run も同じ意味です。
  -h          この使い方を表示して終了します。--help も同じ意味です。
HELP_EOF
}

#===============================================================================
# 3. ログ出力関数(ex04で作った log 関数の簡易版)
#
#   書式は「<レベル> <メッセージ>」。レベルは INFO / SKIP / ERROR の3種類。
#   shift で第1引数(レベル)を捨ててから "$*" を使うと、
#   2番目以降の引数を空白でつないだ1つの文章として扱える。
#   local を付けた変数は、この関数の中だけで有効になる。
#===============================================================================
log() {
    local level="$1"
    shift
    echo "${level} $*"
}

#===============================================================================
# 4. 引数の解析(ex05の復習)
#
#   bash組み込みの getopts は "-n" のような1文字オプションしか扱えないため、
#   まず --dry-run / --help を -n / -h に置き換えてから getopts に渡す。
#===============================================================================
args=()
for arg in "$@"; do
    case "$arg" in
        --dry-run) args+=("-n") ;;
        --help)    args+=("-h") ;;
        *)         args+=("$arg") ;;
    esac
done
set -- "${args[@]}"     # 変換後の引数リストで $1, $2, ... を置き換える

while getopts "f:nh" opt; do
    case "$opt" in
        f)  CSV_FILE="$OPTARG" ;;      # -f に渡された値は $OPTARG に入る
        n)  DRY_RUN="true" ;;
        h)  usage; exit 0 ;;           # ヘルプは「求められた出力」なので成功(0)
        \?) usage >&2; exit 1 ;;       # 未定義のオプションが来た場合
    esac
done
shift $((OPTIND - 1))

#===============================================================================
# 5. 入力のチェック(ex02の復習)
#
#   チェックは「誰が実行しても結果が変わらないもの」から先に行う。
#   引数の書き間違いは権限に関係なく間違いなので、root判定より前に伝えるほうが
#   利用者にとって親切になる。
#===============================================================================
if [[ -z "$CSV_FILE" ]]; then
    echo "エラー: -f でCSVファイルを指定してください。" >&2
    usage >&2
    exit 1
fi

if [[ ! -f "$CSV_FILE" ]]; then
    echo "エラー: CSVファイルが見つかりません: ${CSV_FILE}" >&2
    exit 1
fi

#===============================================================================
# 6. root権限のチェック
#
#   useradd / groupadd / chpasswd / chage は、いずれもroot権限が必要なコマンド。
#   一般ユーザーのまま実行すると「Permission denied」が並ぶだけの読みにくい
#   ログになるため、処理を始める前に自分でチェックして分かりやすく止める。
#
#   $EUID はbashの組み込み変数で、実行中のユーザーの実効ユーザーID。
#   root は必ず 0 なので、0以外なら一般ユーザーだと判定できる。
#   ($(id -u) を使っても同じ判定ができる)
#===============================================================================
if [[ "$EUID" -ne 0 ]]; then
    echo "エラー: このスクリプトはroot権限で実行してください。" >&2
    exit 1
fi

#===============================================================================
# 7. 本体処理: CSVを1行ずつ処理する(ex03の復習)
#===============================================================================
log "INFO" "CSVファイル: ${CSV_FILE} を読み込みます"

if [[ "$DRY_RUN" == "true" ]]; then
    log "INFO" "ドライランモードで実行しています。実際の作成は行いません。"
fi

# IFS=',' を while の行に書くと、カンマ区切りの1行を4つの変数に振り分けられる。
# read -r は「バックスラッシュを特別扱いしない」オプション。read には必ず付ける。
# || [[ -n "$fullname" ]] は、最終行に改行が無いCSVでも最後の1行を落とさない保険。
while IFS=',' read -r fullname username group password || [[ -n "$fullname" ]]; do

    # --- 行末のCR(復帰文字)を取り除く ---
    # WindowsのExcelで保存したCSVは行末が CRLF になっており、そのままだと
    # 「dev」ではなく「dev<CR>」という別の文字列として扱われてしまう。
    fullname="${fullname%$'\r'}"
    username="${username%$'\r'}"
    group="${group%$'\r'}"
    password="${password%$'\r'}"

    # --- 空行は何も出さずに読み飛ばす ---
    if [[ -z "$fullname" && -z "$username" && -z "$group" && -z "$password" ]]; then
        continue
    fi

    # --- ユーザー名の形式チェック ---
    # Linuxのユーザー名は「英小文字か _ で始まり、英小文字・数字・_・- のみ」が基本。
    # =~ は正規表現マッチ演算子で、[[ ]] の中だけで使える。
    if [[ ! "$username" =~ ^[a-z_][a-z0-9_-]*$ ]]; then
        log "ERROR" "不正なユーザー名のためスキップ: ${username}"
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi

    # --- 既存ユーザーの確認(べき等性の要) ---
    # getent passwd <名> は、/etc/passwd だけでなくLDAP連携環境でも使える
    # 標準的な存在確認の方法。見つかれば終了ステータス0を返す。
    # 出力は不要なので /dev/null に捨てる。
    if getent passwd "$username" > /dev/null 2>&1; then
        log "SKIP" "ユーザー ${username} は既に存在するためスキップしました"
        SKIP_COUNT=$((SKIP_COUNT + 1))
        continue
    fi

    # --- グループの確認と作成 ---
    # 「無ければ作る、あれば触らない」がべき等な書き方。
    if ! getent group "$group" > /dev/null 2>&1; then
        if [[ "$DRY_RUN" == "true" ]]; then
            log "INFO" "[dry-run] グループ ${group} を作成します"
        elif groupadd "$group"; then
            log "INFO" "グループ ${group} を作成しました"
        else
            log "ERROR" "グループ ${group} の作成に失敗したため ${username} をスキップしました"
            FAIL_COUNT=$((FAIL_COUNT + 1))
            continue
        fi
    fi

    # --- ドライランならここで打ち切り、実行内容だけを記録する ---
    # 危険なコマンド(useradd 以降)に到達させないことが安全装置の本体。
    if [[ "$DRY_RUN" == "true" ]]; then
        log "INFO" "[dry-run] ユーザー ${username}" \
            "(氏名: ${fullname} / 部署: ${group}) を作成します"
        SUCCESS_COUNT=$((SUCCESS_COUNT + 1))
        continue
    fi

    # --- ユーザーの作成 ---
    #   -m : ホームディレクトリを作る
    #   -c : 氏名などのコメント(GECOS情報)を設定する
    #   -g : プライマリグループを指定する
    #   -s : ログインシェルを指定する
    # if ! コマンド; then ... fi は「失敗したときだけ処理する」書き方。
    if ! useradd -m -c "$fullname" -g "$group" -s /bin/bash "$username"; then
        log "ERROR" "ユーザー ${username} の作成に失敗しました"
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue     # 1行の失敗で全体を止めず、次の行へ進む
    fi

    # --- 初期パスワードの設定 ---
    # chpasswd は「ユーザー名:パスワード」を標準入力から受け取るコマンド。
    # パイプで渡すため、パスワードが画面に表示されることはない。
    # (echo でパスワードそのものを表示してしまう書き方は絶対に避ける)
    echo "${username}:${password}" | chpasswd

    # --- 初回ログイン時のパスワード変更を強制する ---
    # chage -d 0 は「最終パスワード変更日」を1970-01-01に戻すコマンド。
    # 次回ログイン時にパスワードが期限切れとして扱われ、変更が求められる。
    chage -d 0 "$username"

    log "INFO" "ユーザー ${username} (氏名: ${fullname} / 部署: ${group}) を作成しました"
    SUCCESS_COUNT=$((SUCCESS_COUNT + 1))

done < <(tail -n +2 "$CSV_FILE")
# tail -n +2 : 1行目(ヘッダー行)を除いた2行目以降だけを while に渡す。
# < <(...) はプロセス置換。パイプ(cat file | while ...)で渡すと while が
# サブシェルで動くため、ループ内で数えたカウンタがループを抜けた瞬間に
# 元の値へ戻ってしまう。この書き方ならカウンタがそのまま残る。

#===============================================================================
# 8. 集計と終了ステータス
#===============================================================================
echo "成功: ${SUCCESS_COUNT}件 / スキップ: ${SKIP_COUNT}件 / 失敗: ${FAIL_COUNT}件"

if [[ "$DRY_RUN" == "true" ]]; then
    echo "ドライランのため、実際には作成していません。"
fi

# 失敗が1件でもあれば異常終了(1)。cron や CI は終了ステータスだけを見て
# 成否を判断するため、ここを正しく返すことがとても重要になる。
if [[ "$FAIL_COUNT" -gt 0 ]]; then
    exit 1
fi

exit 0
