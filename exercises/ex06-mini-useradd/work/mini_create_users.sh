# set -u : 未定義の変数を使ったらエラーで止める(タイプミス検知のため)
set -u

#-------------------------------------------------------------------------------
# 既定値と集計用カウンタ(ここは書けています)
#-------------------------------------------------------------------------------
CSV_FILE=""                        # -f で指定される。未指定なら空文字のまま
DRY_RUN="false"                    # -n / --dry-run が指定されたら "true" にする
SCRIPT_NAME="$(basename "$0")"     # パスを除いたスクリプト名

SUCCESS_COUNT=0
SKIP_COUNT=0
FAIL_COUNT=0

#-------------------------------------------------------------------------------
# 使い方を表示する関数(ここは書けています)
#-------------------------------------------------------------------------------
usage() {
    cat <<HELP_EOF
使い方: ${SCRIPT_NAME} -f <CSVファイル> [-n]

CSVファイル(氏名,ユーザー名,部署,初期パスワード)を読み込み、
Linuxのユーザーアカウントを一括作成します。

オプション:
  -f <file>   読み込むCSVファイル(必須)
  -n          ドライラン。実際には作成せず、実行内容だけを表示します。
              --dry-run も同じ意味です。
  -h          この使い方を表示して終了します。--help も同じ意味です。
HELP_EOF
}

#-------------------------------------------------------------------------------
# ログ出力関数(ex04 の log 関数の簡易版。ここは書けています)
#   log "INFO" "メッセージ"  ->  INFO メッセージ
#-------------------------------------------------------------------------------
log() {
    local level="$1"
    shift
    echo "${level} $*"
}

