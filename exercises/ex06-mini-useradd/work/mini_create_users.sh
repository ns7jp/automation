#   終了ステータス 1 で終わる。
#   ヒント: root の実効ユーザーIDは必ず 0 です。実効ユーザーIDを取り出す
#           bashの組み込み変数については README の「3分でわかる予備知識」を参照
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# 本体処理の開始(ここは書けています)
#-------------------------------------------------------------------------------
log "INFO" "CSVファイル: ${CSV_FILE} を読み込みます"

#-------------------------------------------------------------------------------
# TODO 6: ドライランのときだけ
#   「INFO ドライランモードで実行しています。実際の作成は行いません。」を出す
#   ヒント: if [[ "$DRY_RUN" == "true" ]]; then log "INFO" "..."; fi
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# CSVを1行ずつ処理するループ(枠と ex03 の復習部分は書けています)
#-------------------------------------------------------------------------------
while IFS=',' read -r fullname username group password || [[ -n "$fullname" ]]; do

    # 行末のCR(復帰文字)を取り除く。WindowsのExcelで保存したCSV対策(ex03の復習)
    fullname="${fullname%$'\r'}"
    username="${username%$'\r'}"
    group="${group%$'\r'}"
    password="${password%$'\r'}"

    # 空行は何も出さずに読み飛ばす(ex03の復習)
    if [[ -z "$fullname" && -z "$username" && -z "$group" && -z "$password" ]]; then
        continue
    fi

    #---------------------------------------------------------------------------
    # TODO 7: ユーザー名の形式チェック
    #   ^[a-z_][a-z0-9_-]*$ に一致しなければ
    #   「ERROR 不正なユーザー名のためスキップ: <ユーザー名>」を出し、
    #   FAIL_COUNT を1増やして continue する。
    #   ヒント: if [[ ! "$username" =~ ^[a-z_][a-z0-9_-]*$ ]]; then ... fi
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 8: 既存ユーザーの確認
    #   getent passwd "$username" が成功したら
    #   「SKIP ユーザー <ユーザー名> は既に存在するためスキップしました」を出し、
    #   SKIP_COUNT を1増やして continue する(useradd は実行しない)。
    #   ヒント: if getent passwd "$username" > /dev/null 2>&1; then ... fi
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 9: グループの確認と作成
    #   getent group "$group" が失敗したら groupadd で作り、
    #   「INFO グループ <部署> を作成しました」を出す。
    #   ドライランのときは作らずに「INFO [dry-run] グループ <部署> を作成します」。
    #   ヒント: if ! getent group "$group" > /dev/null 2>&1; then ... fi
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 10: ドライランならここで打ち切る
    #   「INFO [dry-run] ユーザー <名> (氏名: <氏名> / 部署: <部署>) を作成します」
    #   を出し、SUCCESS_COUNT を1増やして continue する。
    #   ここで止めることが「危険なコマンドを実行しない」安全装置になる。
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 11: ユーザーを作成する
    #   useradd -m -c "<氏名>" -g "<部署>" -s /bin/bash "<ユーザー名>"
    #   失敗したら「ERROR ユーザー <名> の作成に失敗しました」を出し、
    #   FAIL_COUNT を1増やして continue する(1行の失敗で全体を止めない)。
    #   ヒント: if ! useradd ... ; then ... fi
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 12: 初期パスワードの設定と、初回ログイン時の変更強制
    #   echo "<ユーザー名>:<初期パスワード>" | chpasswd
    #   chage -d 0 "<ユーザー名>"
    #   パスワードは画面に表示しないこと(echo で直接出さない)。
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 13: 作成できたことを記録する
    #   「INFO ユーザー <名> (氏名: <氏名> / 部署: <部署>) を作成しました」を出し、
    #   SUCCESS_COUNT を1増やす。
    #---------------------------------------------------------------------------
    :

done < <(tail -n +2 "$CSV_FILE")
# tail -n +2 でヘッダー行を飛ばし、< <(...) のプロセス置換で while に渡している。
# パイプで渡すとカウンタがループの外に残らない(ex03の復習)。

