#-------------------------------------------------------------------------------
# TODO 2: getopts で -f / -n / -h を解析する
#   -f は値を取るので "f:nh" と書く。-h は usage を表示して exit 0。
#   未定義のオプション(\?)のときは usage を標準エラーに出して exit 1。
