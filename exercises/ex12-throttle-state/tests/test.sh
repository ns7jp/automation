#!/bin/bash
#===============================================================================
# ex12 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#
#   このテストは「現在時刻そのもの」ではなく「現在時刻との差」で判定する。
#   状態ファイルの中身をこちらで作ってから実行するので、採点をいつ実行しても
#   結果は変わらない(決定的)。待ち時間も発生しない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

# 採点で使う通知メッセージ(毎回同じ文字列を使う)
ALERT_MESSAGE="ディスク使用率が90%を超えました"

#-------------------------------------------------------------------------------
describe "異常系: メッセージを渡さずに実行したとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。\$1 を参照するより前にチェックしてください。"
assert_status 1 "引数が無いと終了ステータス1で終わる"

hint "使い方は usage >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: 1回目の実行(前回通知なし)"
#-------------------------------------------------------------------------------
rm -f "${WORKDIR}/throttle.state"
run_target "$ALERT_MESSAGE"

hint "状態ファイルが無いときは「前回通知なし」として、必ず通知します。"
assert_stdout_contains "通知しました: ${ALERT_MESSAGE}" \
    "「通知しました: <メッセージ>」を標準出力に表示する"

hint "通知できたのだから正常終了です。exit 0 で終わります。"
assert_status 0 "通知したときは終了ステータス0で終わる"

hint "状態ファイルの既定の場所は ./throttle.state です。printf ... > \"\$STATE_FILE\" で書き込みます。"
assert_file_exists "${WORKDIR}/throttle.state" "通知したときに状態ファイル throttle.state を作る"

hint "書き込むのは date +%s の値(epoch秒の数字だけ)です。日付文字列は書きません。"
assert_file_contains "${WORKDIR}/throttle.state" '^[0-9]+$' \
    "状態ファイルには epoch秒の数字だけを書き込む"

#-------------------------------------------------------------------------------
describe "正常系: 抑止間隔(既定300秒)の中で再実行したとき"
#-------------------------------------------------------------------------------
# 「たった今通知したばかり」の状態を作る
LAST_EPOCH="$(date +%s)"
printf '%s\n' "$LAST_EPOCH" > "${WORKDIR}/throttle.state"
run_target "$ALERT_MESSAGE"

hint "書式は「抑止しました: 前回の通知から <経過秒>秒しか経っていません (抑止間隔: 300秒)」です。「から」の後ろに半角スペースが1つ入ります。"
assert_stdout_matches '抑止しました: 前回の通知から [0-9]+秒しか経っていません \(抑止間隔: 300秒\)' \
    "抑止したときは「抑止しました: 前回の通知から <経過秒>秒しか経っていません (抑止間隔: <抑止間隔>秒)」を表示する"

hint "抑止は想定どおりの動作なので失敗ではありません。exit 0 で終わります。"
assert_status 0 "抑止したときも終了ステータス0で終わる"

hint "抑止したときに状態ファイルを更新すると、最終通知時刻が先送りされ続けて永久に通知されなくなります。"
assert_file_contains "${WORKDIR}/throttle.state" "^${LAST_EPOCH}\$" \
    "抑止したときは状態ファイルを更新しない"

#-------------------------------------------------------------------------------
describe "正常系: 抑止間隔を過ぎてから実行したとき"
#-------------------------------------------------------------------------------
# 前回通知を「1000秒前」ということにする(既定の300秒より前なので通知される)
printf '%s\n' "$(( $(date +%s) - 1000 ))" > "${WORKDIR}/throttle.state"
run_target "$ALERT_MESSAGE"

hint "経過秒が抑止間隔以上なら通知します。比較は [[ \"\$ELAPSED\" -lt \"\$THROTTLE_SEC\" ]] で行います。"
assert_stdout_contains "通知しました: ${ALERT_MESSAGE}" \
    "経過秒が抑止間隔以上なら再び通知する"

hint "通知したら状態ファイルを現在時刻(date +%s の値)で上書きします。"
assert_cmd "通知したときは状態ファイルを現在時刻で更新する" \
    test "$(cat "${WORKDIR}/throttle.state" 2>/dev/null)" -ge "$(( $(date +%s) - 60 ))"

#-------------------------------------------------------------------------------
describe "正常系: STATE_FILE と THROTTLE_SEC を環境変数で変えたとき"
#-------------------------------------------------------------------------------
# 抑止間隔を1秒にすると、5秒前の通知は「もう十分経った」と判定される。
# 状態ファイルの場所も alert.state に変える。
export STATE_FILE="alert.state"
export THROTTLE_SEC="1"
SEED_EPOCH="$(( $(date +%s) - 5 ))"
printf '%s\n' "$SEED_EPOCH" > "${WORKDIR}/alert.state"
run_target "$ALERT_MESSAGE"

hint "THROTTLE_SEC は \"\${THROTTLE_SEC:-300}\" の形で受け取り、既定値を上書きできるようにします。"
assert_stdout_contains "通知しました: ${ALERT_MESSAGE}" \
    "THROTTLE_SEC で抑止間隔を短くすると通知される"

hint "STATE_FILE も \"\${STATE_FILE:-./throttle.state}\" の形で受け取り、指定された場所を読み書きします。"
assert_file_not_contains "${WORKDIR}/alert.state" "^${SEED_EPOCH}\$" \
    "STATE_FILE で指定した状態ファイルを更新する"

#-------------------------------------------------------------------------------
describe "異常系: 状態ファイルの中身が壊れているとき"
#-------------------------------------------------------------------------------
# 手で編集された、書き込み途中で中断されたなどで数値以外が入っている状況。
export STATE_FILE="broken.state"
export THROTTLE_SEC="300"
printf '%s\n' "abc" > "${WORKDIR}/broken.state"
run_target "$ALERT_MESSAGE"

hint "数字でない値を \$(( )) に渡すとエラーで落ちます。読み込んだ値は正規表現で確認してください。"
assert_stdout_contains "通知しました: ${ALERT_MESSAGE}" \
    "状態ファイルが数値でなければ「前回通知なし」として通知する"

hint "状態ファイルが壊れていてもスクリプトは落ちてはいけません。異常終了していないか確認してください。"
assert_status 0 "状態ファイルが壊れていても終了ステータス0で終わる"

finish
