#!/bin/bash
#===============================================================================
# ex12: 状態ファイルで通知を抑止する(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている「環境変数で既定値を上書きできるようにする」
# 「状態ファイルは壊れている前提で読む」という書き方は、無人で動く運用
# スクリプトの必須作法です。案件No.3 log-watch-alert.sh の handle_match()
# とほぼ同じ構成なので、意味を理解したうえで真似してください。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   時刻の変数名をタイプミスすると、経過秒が異常な値になって
#   「永久に抑止される」「毎回通知される」という気づきにくい不具合になる。
#   set -u はそれを実行時に止めてくれる。
set -u

#===============================================================================
# 1. 設定値
#
#   "${STATE_FILE:-./throttle.state}" は
#   「環境変数 STATE_FILE が設定されていればその値、無ければ既定値」という意味。
#
#   こう書いておくと、スクリプト本体を書き換えずに動きを変えられる。
#     ・本番    : systemd の EnvironmentFile= から値を渡す
#     ・テスト  : THROTTLE_SEC=1 ./throttle.sh "..." のように一時的に変える
#   設定を「コードの外」に出しておくのは、運用スクリプトの基本的な作法。
#===============================================================================
SCRIPT_NAME="$(basename "$0")"
STATE_FILE="${STATE_FILE:-./throttle.state}"
THROTTLE_SEC="${THROTTLE_SEC:-300}"

#===============================================================================
# 2. 使い方の表示
#
#   実際に使われる値(既定値または環境変数で上書きされた値)を埋め込んでおくと、
#   「どの状態ファイルを見ているのか分からない」という調査の手間が減る。
#===============================================================================
usage() {
    echo "使い方: ${SCRIPT_NAME} <メッセージ>"
    echo "  前回の通知から ${THROTTLE_SEC} 秒経っていれば通知し、経っていなければ抑止します。"
    echo "  状態ファイル: ${STATE_FILE}"
}

#===============================================================================
# 3. 引数チェック
#
#   set -u を付けているため、$1 をそのまま参照すると引数なしの実行で
#   スクリプトが異常終了してしまう。個数チェックを必ず先に置く。
#
#   エラーは標準エラー出力(>&2)に出す。通知メッセージ(標準出力)と
#   混ざらないように分けておくと、呼び出し元でログを分離できる。
#===============================================================================
if [[ "$#" -lt 1 ]]; then
    usage >&2
    exit 1
fi

MESSAGE="$1"

#===============================================================================
# 4. 現在時刻の取得
#
#   date +%s は epoch秒(1970年1月1日からの経過秒数)。
#   ただの整数なので、引き算するだけで経過時間が求められる。
#   日付文字列のままでは引き算できないので、時間差を扱うときは必ずこの形にする。
#===============================================================================
NOW="$(date +%s)"

#===============================================================================
# 5. 状態ファイルの読み込み
#
#   スクリプトは実行が終わると変数の内容をすべて忘れる。
#   「前回いつ通知したか」を次回に引き継ぐ唯一の方法が、この状態ファイル。
#
#   head -n 1 で先頭1行だけ読むのは、将来ファイルに項目が増えても
#   1行目の意味(最終通知時刻)が変わらないようにするため。
#===============================================================================
LAST_NOTIFIED=""
if [[ -f "$STATE_FILE" ]]; then
    LAST_NOTIFIED="$(head -n 1 "$STATE_FILE")"
fi

#===============================================================================
# 6. 読み込んだ値の妥当性チェック(防御的プログラミング)
#
#   状態ファイルは壊れることがある。書き込みの途中で電源が落ちた、
#   誰かが調査中に手で編集した、といった理由で中身が空や文字列になりうる。
#
#   数字でない値を $(( )) に渡すと、bash はそれを変数名とみなして評価し、
#   set -u と組み合わさるとスクリプトが異常終了する。
#   障害の真っ最中に通知スクリプト自体が落ちるのは最悪なので、
#   「おかしければ前回通知なしに倒す」という安全側の判断をする。
#
#   正規表現 ^(0|[1-9][0-9]*)$ は「0、または0で始まらない数字列」。
#   単なる ^[0-9]+$ にしないのは、008 のような先頭ゼロ付きの値を弾くため。
#   bashの算術式は先頭が0の数を8進数として解釈するので、008 は
#   「8進数として無効な桁」となりエラーになる。
#===============================================================================
if [[ ! "$LAST_NOTIFIED" =~ ^(0|[1-9][0-9]*)$ ]]; then
    LAST_NOTIFIED=""
fi

#===============================================================================
# 7. 抑止の判定
#
#   前回通知があり、かつ経過秒が抑止間隔より短ければ「抑止」。
#   このとき状態ファイルは更新しない。更新してしまうと、検知が続くたびに
#   最終通知時刻が先送りされ、いつまで経っても次の通知が出なくなる。
#
#   抑止しても終了ステータスは 0(正常)にする。抑止はスクリプトの
#   想定どおりの動作であって、失敗ではないため。
#===============================================================================
if [[ -n "$LAST_NOTIFIED" ]]; then
    ELAPSED=$(( NOW - LAST_NOTIFIED ))
    if [[ "$ELAPSED" -lt "$THROTTLE_SEC" ]]; then
        printf '抑止しました: 前回の通知から %d秒しか経っていません (抑止間隔: %s秒)\n' \
            "$ELAPSED" "$THROTTLE_SEC"
        exit 0
    fi
fi

#===============================================================================
# 8. 通知
#
#   printf を使っているのは、メッセージが -n のような文字列で始まっていても
#   echo がオプションと誤解しないようにするため。
#
#   状態ファイルへの書き込みは > (上書き)。>> (追記)にすると行が増え続け、
#   head -n 1 で読む値が古いままになってしまう。
#
#   「通知を出してから状態ファイルを更新する」順序にしているのは、
#   通知に失敗した場合でも次回の実行で再挑戦できるようにするため。
#===============================================================================
printf '通知しました: %s\n' "$MESSAGE"
printf '%s\n' "$NOW" > "$STATE_FILE"

exit 0
