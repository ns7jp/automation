#!/bin/bash
#===============================================================================
# ex15 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#
#   本物の ping / curl は実行せず、ダミーコマンド(スタブ)に差し替えて
#   「web03 は停止中」「web04 は500を返す」という状況を再現する。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

# 危険なコマンド・実サーバーが必要なコマンドをダミーに差し替える
enable_stubs ping curl

#-------------------------------------------------------------------------------
# 採点用の定義ファイルを作る(harness が作業ディレクトリに cd 済み)
#   コメント行・空行・不正な種別をわざと混ぜてある。
#-------------------------------------------------------------------------------
cat > targets.conf <<'EOF'
# commented01,ping,commented01

web01,ping,web01
web02,http,http://web02/
web03,ping,web03
web04,http,http://web04/
web05,pong,web05
EOF

cat > all_ok.conf <<'EOF'
web01,ping,web01
web02,http,http://web02/
EOF

#-------------------------------------------------------------------------------
describe "異常系: -t で定義ファイルを指定しないとき"
#-------------------------------------------------------------------------------
run_target

hint "監視対象が分からないまま進んではいけません。exit 1 で止めてください。"
assert_status 1 "-t を指定しないと終了ステータス1で終わる"

hint "エラーは echo \"...\" >&2 や usage >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "異常系: 定義ファイルが存在しないとき"
#-------------------------------------------------------------------------------
run_target -t no_such_file.conf

hint "[[ ! -f \"\$TARGETS_FILE\" ]] でファイルの有無を確認してください。"
assert_status 1 "存在しないファイルを指定すると終了ステータス1で終わる"

hint "メッセージには「見つかりません」という言葉を含めてください。"
assert_stderr_contains "見つかりません" "「見つかりません」を含むエラーを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: -h を指定したとき"
#-------------------------------------------------------------------------------
run_target -h

hint "ヘルプは利用者が意図して求めた出力なので、成功(0)で終了します。"
assert_status 0 "-h を指定すると終了ステータス0で終わる"

hint "ヘルプは標準出力に出します(>&2 を付けない)。"
assert_stdout_contains "使い方" "-h で使い方を標準出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: 正常・異常・不正な種別が混ざった定義ファイル"
#-------------------------------------------------------------------------------
# web03 は停止中、web02 は200、web04 は500 を返す状況を作る
export STUB_DOWN_HOSTS="web03"
export STUB_HTTP_CODES="web02=200 web04=500"
run_target -t targets.conf

hint "ping が成功したときは [OK] <表示名> (ping) の形式です。半角スペースとかっこに注意。"
assert_stdout_contains "[OK] web01 (ping)" "ping で応答があった行を「[OK] web01 (ping)」と表示する"

hint "http のときはステータスコードも出します: [OK] <表示名> (http: 200)"
assert_stdout_contains "[OK] web02 (http: 200)" "HTTPが200のとき「[OK] web02 (http: 200)」と表示する"

hint "ping が失敗したときの理由は「応答なし」という固定の文言です。"
assert_stdout_contains "[NG] web03 (ping: 応答なし)" "ping が失敗した行を「[NG] web03 (ping: 応答なし)」と表示する"

hint "200番台以外はすべて異常です。判定は [[ \"\$code\" =~ ^2[0-9][0-9]\$ ]] で書けます。"
assert_stdout_contains "[NG] web04 (http: 500)" "HTTPが500のとき「[NG] web04 (http: 500)」と表示する"

hint "種別が ping / http のどちらでもない行は [SKIP] を出して次の行へ進みます。"
assert_stdout_contains "[SKIP] web05 種別が不正です: pong" "不正な種別の行を「[SKIP] web05 種別が不正です: pong」と表示する"

DETAIL_LINES="$(printf '%s\n' "$LAST_STDOUT" | grep -c '^\[')"
hint "空行と # で始まる行は読み飛ばします。[[ -z \"\$name\" || \"\$name\" == \\#* ]] && continue"
assert_eq "5" "$DETAIL_LINES" "コメント行と空行は読み飛ばし、判定行を5行だけ表示する"

hint "集計行の区切りは半角スペース+スラッシュ+半角スペースです。[SKIP] は数えません。"
assert_stdout_contains "正常: 2件 / 異常: 2件" "最後に「正常: 2件 / 異常: 2件」と集計を表示する"

hint "異常が1件でもあれば exit 1 です。cron 側はこの数字で失敗に気づきます。"
assert_status 1 "異常が1件以上あるときは終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "正常系: すべて正常だったとき"
#-------------------------------------------------------------------------------
export STUB_DOWN_HOSTS=""
export STUB_HTTP_CODES="web02=200"
run_target -t all_ok.conf

hint "異常が0件のときだけ exit 0 です。NG_COUNT を数えて判定してください。"
assert_status 0 "異常が0件のときは終了ステータス0で終わる"

finish
