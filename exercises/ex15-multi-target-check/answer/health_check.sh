#!/bin/bash
#===============================================================================
# ex15: 複数台をまとめて監視する(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただしここで使っている書き方(設定ファイルの外出し、case による分岐、
# 終了ステータスでの成否通知)は、案件No.4 health_check.sh でも
# そのまま使われている実務の定番なので、意味を理解して真似することを勧めます。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   監視スクリプトは無人で動くため、タイプミスによる「静かな誤動作」が最も怖い。
#   なお -e (エラーで即終了) は付けない。1台の監視に失敗しても残りの監視と
#   集計まで必ず実行したいためで、これは案件No.4 の本体と同じ方針。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#
#   -h のときと引数エラーのときの2か所から呼ぶので、関数にまとめておく。
#   出力先(標準出力か標準エラー出力か)は呼び出す側で切り替える。
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") -t <定義ファイル>"
    echo "  定義ファイルに書かれたサーバーを順に監視し、結果を表示します。"
    echo "  書式: <表示名>,<種別>,<宛先>   種別は ping または http"
}

#-------------------------------------------------------------------------------
# 1. オプションの解析
#
#   getopts の ":t:h" の読み方:
#     先頭の ":" … 不明なオプションを getopts 自身にエラー表示させず、
#                   自分で処理する(メッセージを日本語で統一できる)
#     "t:"       … -t は値を取る。値は $OPTARG に入る
#     "h"        … -h は値を取らない
#-------------------------------------------------------------------------------
TARGETS_FILE=""

while getopts ":t:h" opt; do
    case "$opt" in
        t)
            TARGETS_FILE="$OPTARG"
            ;;
        h)
            # ヘルプは利用者が意図して求めた出力なので、標準出力に出して成功終了する
            usage
            exit 0
            ;;
        *)
            # 不明なオプション、または -t の値が無い場合
            echo "エラー: オプションの指定が正しくありません。" >&2
            usage >&2
            exit 1
            ;;
    esac
done

#-------------------------------------------------------------------------------
# 2. 入力チェック(処理を始める前の安全装置)
#
#   監視スクリプトは cron から無人で動く。前提が崩れているときは
#   中途半端に動かさず、標準エラー出力にはっきり理由を出して止めるのが正しい。
#-------------------------------------------------------------------------------
if [[ -z "$TARGETS_FILE" ]]; then
    echo "エラー: -t で監視対象の定義ファイルを指定してください。" >&2
    usage >&2
    exit 1
fi

if [[ ! -f "$TARGETS_FILE" ]]; then
    echo "エラー: 定義ファイルが見つかりません: ${TARGETS_FILE}" >&2
    exit 1
fi

#-------------------------------------------------------------------------------
# 3. 監視の実行
#
#   カウンタはループの「前」で初期化する。ループの中で 0 を代入すると
#   毎回リセットされてしまい、集計が常に 0 件になる。
#-------------------------------------------------------------------------------
OK_COUNT=0
NG_COUNT=0

# IFS=',' … この read の間だけ「区切り文字はカンマ」にする指定。
# read -r … バックスラッシュを特別扱いしない(パスやURLを壊さないための定番)。
while IFS=',' read -r name type dest; do

    # 空行(name が空)と、# で始まるコメント行は読み飛ばす。
    # 設定ファイルには必ず人間向けの注釈が書かれるため、この2行は必須。
    # \#* の \ は、# をコメント開始と誤解させないためのエスケープ。
    [[ -z "$name" || "$name" == \#* ]] && continue

    case "$type" in
        ping)
            # ping の出力(統計情報)は使わないので捨てる。
            # 判定に使うのは「成功したか失敗したか」という終了ステータスだけ。
            #   -c 1 : パケットを1回だけ送る
            #   -W 2 : 応答を最大2秒待つ(応答が遅いだけのサーバーへの猶予)
            if ping -c 1 -W 2 "$dest" > /dev/null 2>&1; then
                echo "[OK] ${name} (ping)"
                OK_COUNT=$((OK_COUNT + 1))
            else
                echo "[NG] ${name} (ping: 応答なし)"
                NG_COUNT=$((NG_COUNT + 1))
            fi
            ;;
        http)
            # -s              : 進捗表示を出さない(silent)
            # -o /dev/null    : 応答本文は判定に使わないので捨てる
            # -w '%{http_code}' : HTTPステータスコードだけを出力させる
            # --max-time 5    : 5秒で諦める(無人実行が止まり続けないための保険)
            # 接続自体に失敗した場合、コードは "000" になる。
            code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "$dest")"

            # 200番台だけを正常とみなす。=~ は正規表現による判定で、
            # ^2[0-9][0-9]$ は「2で始まる3桁の数字ちょうど」という意味。
            # 数値比較 -ge 200 でも書けるが、"000" のような値でも安全に
            # 扱えるこの書き方のほうが事故が少ない。
            if [[ "$code" =~ ^2[0-9][0-9]$ ]]; then
                echo "[OK] ${name} (http: ${code})"
                OK_COUNT=$((OK_COUNT + 1))
            else
                echo "[NG] ${name} (http: ${code})"
                NG_COUNT=$((NG_COUNT + 1))
            fi
            ;;
        *)
            # 種別の書き間違いで監視が静かに漏れるのが一番危ない。
            # 「見なかったこと」にせず、SKIP として画面に残す。
            echo "[SKIP] ${name} 種別が不正です: ${type}"
            ;;
    esac

done < "$TARGETS_FILE"

#-------------------------------------------------------------------------------
# 4. 集計と終了ステータス
#
#   人間向けの集計行を出したうえで、機械向けには終了ステータスで結果を伝える。
#   cron や上位の仕組みは画面の文字を読まないので、
#   「異常があったかどうか」を数字で返すことが欠かせない。
#-------------------------------------------------------------------------------
echo "正常: ${OK_COUNT}件 / 異常: ${NG_COUNT}件"

if [[ "$NG_COUNT" -gt 0 ]]; then
    exit 1
fi

exit 0
