# set -u : 未定義の変数を使ったらエラーで止める(タイプミス検知のため)
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") -t <定義ファイル>"
    echo "  定義ファイルに書かれたサーバーを順に監視し、結果を表示します。"
    echo "  書式: <表示名>,<種別>,<宛先>   種別は ping または http"
}

#-------------------------------------------------------------------------------
# オプションの解析
#
# TODO 1: getopts を使って -t <定義ファイル> と -h を受け取る
#   ヒント: while getopts ":t:h" opt; do case "$opt" in ... esac done
#           -t の値は $OPTARG に入る。-h は usage を表示して exit 0
#           それ以外(不明なオプション)は usage を標準エラーに出して exit 1
#-------------------------------------------------------------------------------
TARGETS_FILE=""

#-------------------------------------------------------------------------------
# TODO 2: -t が指定されなかった場合、エラーを「標準エラー出力」に出して
#         終了ステータス1で終わる
#   ヒント: [[ -z "$TARGETS_FILE" ]] で「空かどうか」を判定できる
#           メッセージには「使い方」という単語を含める(usage >&2 でよい)
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 3: 指定された定義ファイルが存在しない場合、
#         「エラー: 定義ファイルが見つかりません: <パス>」を標準エラー出力に出して
#         終了ステータス1で終わる
#   ヒント: [[ ! -f "$TARGETS_FILE" ]] でファイルの有無を判定できる
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# 集計用のカウンタ
#   ループの「前」で初期化する。ループの中に書くと毎回0に戻ってしまう。
#-------------------------------------------------------------------------------
OK_COUNT=0
NG_COUNT=0

#-------------------------------------------------------------------------------
# 定義ファイルを1行ずつ読んで監視する
#
# TODO 4: 今は最後の done の右側が /dev/null(中身が空のファイル)なので、
#         ループが1回も回りません。定義ファイルを読むように直してください。
#   ヒント: done < "$TARGETS_FILE" と書く。IFS=',' はカンマ区切りで列に分ける指定
#-------------------------------------------------------------------------------
while IFS=',' read -r name type dest; do

    #---------------------------------------------------------------------------
    # TODO 5: 空行(name が空)と、# で始まるコメント行を読み飛ばす
    #   ヒント: [[ -z "$name" || "$name" == \#* ]] && continue
    #---------------------------------------------------------------------------

    #---------------------------------------------------------------------------
    # TODO 6: 種別($type)によって処理を分ける
    #
    #   ping の場合:
    #     ping -c 1 -W 2 "$dest" > /dev/null 2>&1 を実行し、
    #       成功 → echo "[OK] ${name} (ping)"          … OK_COUNT を1増やす
    #       失敗 → echo "[NG] ${name} (ping: 応答なし)" … NG_COUNT を1増やす
    #
    #   http の場合:
    #     code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "$dest")"
    #     で HTTPステータスコードを取得し、
    #       200番台 → echo "[OK] ${name} (http: ${code})"  … OK_COUNT を1増やす
    #       それ以外 → echo "[NG] ${name} (http: ${code})"  … NG_COUNT を1増やす
    #
    #   それ以外の種別:
    #     echo "[SKIP] ${name} 種別が不正です: ${type}"
    #     (正常にも異常にも数えない)
    #
    #   ヒント: case "$type" in ping) ... ;; http) ... ;; *) ... ;; esac
    #           200番台の判定は [[ "$code" =~ ^2[0-9][0-9]$ ]]
    #           数を1増やすのは OK_COUNT=$((OK_COUNT + 1))
    #---------------------------------------------------------------------------
    :

done < /dev/null

#-------------------------------------------------------------------------------
# TODO 7: 集計行を表示する
#   形式: 正常: <件数>件 / 異常: <件数>件
#-------------------------------------------------------------------------------
echo "正常: 件 / 異常: 件"

#-------------------------------------------------------------------------------
# TODO 8: 異常が1件以上なら終了ステータス1、0件なら0で終わる
#   ヒント: [[ "$NG_COUNT" -gt 0 ]] で「1件以上か」を判定できる
#-------------------------------------------------------------------------------
exit 0
