#!/bin/bash
#===============================================================================
# ex09: 失敗時のWebhook通知(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている書き方(秘密情報を環境変数で受け取る、JSONの
# エスケープ、curl の終了ステータスで成否を判定する)は実務でも定番なので、
# 意味を理解したうえで真似することを勧めます。
#
# 使い方:
#   WEBHOOK_URL="https://hooks.slack.com/services/..." \
#       ./notify.sh failure "バックアップに失敗しました"
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   このスクリプトは WEBHOOK_URL という「外から渡される変数」を扱う。
#   set -u があると「渡し忘れ」を黙って見逃さずに済むが、
#   それだと未設定のときにスキップする処理まで書けなくなるため、
#   参照する場所では ${WEBHOOK_URL:-} と書いて未定義でも空文字として扱う。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#
#   引数エラーが2か所(個数の誤り・種別の誤り)で起きるため、
#   関数にまとめて両方から呼び出す。
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <success|failure> <メッセージ>"
    echo "  実行結果を Webhook (Slackなど) へ通知します。"
    echo "  送信先は環境変数 WEBHOOK_URL で指定します。"
}

#-------------------------------------------------------------------------------
# 1. 引数の個数チェック
#
#   通知の種別とメッセージの2つが必須。エラーメッセージは >&2 を付けて
#   標準エラー出力へ出す。呼び出し元(バックアップスクリプトなど)が
#   標準出力をログにリダイレクトしていても、異常だけは画面に残る。
#-------------------------------------------------------------------------------
if [[ "$#" -ne 2 ]]; then
    echo "エラー: 引数は2つ必要です。" >&2
    usage >&2
    exit 1
fi

STATUS="$1"
MESSAGE="$2"

#-------------------------------------------------------------------------------
# 2. 通知の種別からラベルを決める
#
#   case は「値がどのパターンに当てはまるか」で分岐する構文。
#   success / failure 以外を弾いておくと、呼び出し側のタイプミス
#   (sucess など)に気づけて、通知の内容が壊れるのを防げる。
#-------------------------------------------------------------------------------
case "$STATUS" in
    success)
        LABEL="[SUCCESS]"
        ;;
    failure)
        LABEL="[FAILURE]"
        ;;
    *)
        echo "エラー: 第1引数は success または failure を指定してください。" >&2
        usage >&2
        exit 1
        ;;
esac

#-------------------------------------------------------------------------------
# 3. 送信先の確認
#
#   WebhookのURLは「知っている人なら誰でも投稿できる」秘密情報なので、
#   スクリプトにもリポジトリにも書かず、環境変数で外から渡す。
#
#   未設定のときにエラーで止めてしまうと、開発中のPCやテスト環境で
#   本処理まで失敗扱いになってしまう。「通知できないこと」は
#   「バックアップが失敗したこと」ではないので、ここは 0(成功)で終える。
#
#   ${WEBHOOK_URL:-} は「未定義なら空文字」。-z は「空文字かどうか」の判定。
#   この2つを組み合わせると「未設定」と「空」をまとめて扱える。
#-------------------------------------------------------------------------------
if [[ -z "${WEBHOOK_URL:-}" ]]; then
    echo "WEBHOOK_URL が未設定のため通知をスキップします"
    exit 0
fi

#-------------------------------------------------------------------------------
# 4. 送信する本文(JSON)の組み立て
#
#   JSONは 値をダブルクォートで囲む形式なので、メッセージ自体に
#   ダブルクォートが入っていると、そこで文字列が終わったと解釈されて
#   JSON全体が壊れる。送信前にバックスラッシュでエスケープしておく。
#
#   ${MESSAGE//\"/\\\"} は「MESSAGE の中の " を すべて \" に置換する」
#   という書き方。// は「すべて置換」(/ ひとつだと最初の1件だけ)。
#-------------------------------------------------------------------------------
HOST_NAME="$(hostname)"
ESCAPED_MESSAGE="${MESSAGE//\"/\\\"}"
TEXT="${LABEL} ${HOST_NAME}: ${ESCAPED_MESSAGE}"
PAYLOAD="{\"text\":\"${TEXT}\"}"

#-------------------------------------------------------------------------------
# 5. 送信
#
#   curl のオプションの意味:
#     -s  進捗メーターを出さない(cronから動かすと邪魔になるため)
#     -S  -s を付けていてもエラーだけは表示する(-sS はセットで使う定番)
#     -X POST         POSTメソッドで送る
#     -H "Content-Type: application/json"   本文がJSONであることを伝える
#     -d "<本文>"     送信する本文
#
#   応答本文(Slackなら ok)は使わないので /dev/null へ捨てる。
#   if ! コマンド; then ... fi は「コマンドが失敗したら」という意味。
#-------------------------------------------------------------------------------
if ! curl -sS -X POST \
        -H "Content-Type: application/json" \
        -d "$PAYLOAD" \
        "$WEBHOOK_URL" > /dev/null; then
    echo "エラー: 通知の送信に失敗しました" >&2
    exit 1
fi

#-------------------------------------------------------------------------------
# 6. 送信できたことを記録として残す
#
#   画面に出しておくと、cronのログを見たときに
#   「通知は飛んでいたのか」がすぐ分かる。
#-------------------------------------------------------------------------------
echo "通知を送信しました: ${LABEL} ${HOST_NAME}: ${MESSAGE}"
exit 0
