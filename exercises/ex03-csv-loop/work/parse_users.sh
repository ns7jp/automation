#!/bin/bash
#===============================================================================
# ex03: CSVを1行ずつ処理する(あなたが完成させるファイル)
#
# 課題の詳細は ../README.md を読んでください。
# TODO と書かれた場所を埋めれば完成します。
#
# 採点: exercises ディレクトリで ./check.sh 03
#===============================================================================

# set -u : 未定義の変数を使ったらエラーで止める(タイプミス検知のため)
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数(ここは完成しています)
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <CSVファイル>"
    echo "  CSVの列は「氏名,ユーザー名,部署,初期パスワード」の順です。"
}

#-------------------------------------------------------------------------------
# TODO 1: 引数がちょうど1個でなければ、エラーメッセージと usage を
#         「標準エラー出力」に表示して、終了ステータス 1 で終わる
#   ヒント: ex02 と同じ書き方。引数の個数は $# 、標準エラー出力は >&2
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 2: 1個目の引数を、読み込むCSVファイルとして変数に入れる
#-------------------------------------------------------------------------------
CSV_FILE=""

#-------------------------------------------------------------------------------
# TODO 3: CSVファイルが存在しなければ、標準エラー出力に
#           エラー: ファイルが見つかりません: <パス>
#         を表示して、終了ステータス 1 で終わる
#   ヒント: [[ ! -f "$CSV_FILE" ]]
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# 集計用のカウンタ(ここは完成しています)
#   LINE_NO は「今読んでいる行が、ファイルの何行目か」を覚えておく変数。
#   1行目はヘッダー行なので 1 から始め、ループの先頭で1ずつ増やす。
#-------------------------------------------------------------------------------
OK_COUNT=0
SKIP_COUNT=0
LINE_NO=1

#-------------------------------------------------------------------------------
# TODO 4: CSVの2行目以降を1行ずつ読み込むループを書く
#
#   ループの中でやること(この順番で書くと素直に書けます):
#     4-1. LINE_NO を1増やす
#     4-2. 4つの変数それぞれから、行末のCR(Windowsの改行の名残)を取り除く
#          ヒント: fullname="${fullname%$'\r'}"
#     4-3. 4項目とも空なら「空行」なので、何も表示せず次の行へ進む
#          ヒント: [[ -z "$a" && -z "$b" ... ]] と continue
#     4-4. 1項目でも空なら
#            スキップ: <行番号>行目 項目が足りません
#          を表示し、SKIP_COUNT を1増やして次の行へ進む
#     4-5. ここまで来たら正常な行。OK_COUNT を1増やして
#            [<連番>] <氏名> / <ユーザー名> / <部署>
#          を表示する(初期パスワードは絶対に表示しない)
#
#   ループの形のヒント:
#     while IFS=',' read -r fullname username dept password || [[ -n "$fullname" ]]; do
#         ...
#     done < <(tail -n +2 "$CSV_FILE")
#
#   ヘッダー行は tail -n +2 で読み飛ばします。
#   パイプ( tail ... | while ... )で渡すとカウンタが消えるので使わないこと。
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 5: 最後に合計を表示する
#           合計: <正常件数>件 (スキップ: <スキップ件数>件)
#   ヒント: 変数は ${OK_COUNT} ${SKIP_COUNT} 。括弧は半角
#-------------------------------------------------------------------------------
echo "合計: "

# ここまで来たら正常終了。1行ごとの成否にかかわらず、
# 「ファイルを最後まで読み切れた」ことを終了ステータス0で伝える。
exit 0
