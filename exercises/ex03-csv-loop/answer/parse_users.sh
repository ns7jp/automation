#!/bin/bash
#===============================================================================
# ex03: CSVを1行ずつ処理する(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている読み込みループの形は、汚れたCSVでも壊れないよう
# 実務で磨かれてきた定番の書き方です。案件No.1 create_users.sh も同じ形をしています。
#
# このスクリプトの役割:
#   「氏名,ユーザー名,部署,初期パスワード」の4列のCSVを1行ずつ読み、
#   正常な行を一覧表示し、不正な行はスキップとして記録して、最後に件数を出す。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する(タイプミス検知のため)。
# ※ set -e はあえて使わない。1行が不正でも処理を止めず、次の行へ進みたいため、
#   エラー処理は if 文で自分で制御する。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <CSVファイル>"
    echo "  CSVの列は「氏名,ユーザー名,部署,初期パスワード」の順です。"
}

#===============================================================================
# 1. 引数と入力ファイルの確認(ex02の復習)
#
#   本処理を始める前に、駄目な条件をここですべて弾いておく。
#   ここを通過した時点で「CSVは必ず読める」と保証されるので、
#   このあとのループは処理そのものに集中できる。
#===============================================================================
if [[ "$#" -ne 1 ]]; then
    echo "エラー: CSVファイルを1つ指定してください。" >&2
    usage >&2
    exit 1
fi

CSV_FILE="$1"

if [[ ! -f "$CSV_FILE" ]]; then
    echo "エラー: ファイルが見つかりません: ${CSV_FILE}" >&2
    exit 1
fi

#===============================================================================
# 2. 集計用のカウンタ
#
#   OK_COUNT は正常に処理できた行数で、表示する連番も兼ねている。
#   LINE_NO は「今読んでいる行がファイルの何行目か」。
#   1行目はヘッダー行なので 1 から始め、ループの先頭で1ずつ増やす。
#   こうすると最初のデータ行がちょうど 2行目 になり、
#   利用者がテキストエディタで開いたときの行番号とぴったり一致する。
#===============================================================================
OK_COUNT=0
SKIP_COUNT=0
LINE_NO=1

#===============================================================================
# 3. CSVを1行ずつ読み込んで処理する
#
#   IFS=',' : この read の間だけ区切り文字をカンマにする。
#             これで1行が4つの変数に振り分けられる。
#             while の行に書くことで、スクリプトの他の場所の動作
#             (通常の空白区切り)には影響しない。
#
#   read -r : バックスラッシュ(\)をエスケープ文字として特別扱いしない。
#             パスワードに \ が含まれていても、そのままの文字として読める。
#             read には基本的に -r を付ける、と覚えてよい。
#
#   || [[ -n "$fullname" ]] :
#             最終行に改行が無いCSVでも、最後の1行を落とさないための保険。
#             read はファイル末尾で改行が無いと「失敗」を返すが、
#             読んだ内容自体は変数に入っている。そこで「read が成功したか、
#             または1つ目の変数に中身が残っているなら」ループを続ける。
#===============================================================================
while IFS=',' read -r fullname username dept password || [[ -n "$fullname" ]]; do

    # --- 行番号を先に1増やす -------------------------------------------------
    # ループの先頭で増やしておけば、この後どこで continue しても
    # 行番号がずれない。
    LINE_NO=$((LINE_NO + 1))

    # --- 行末のCR除去(WindowsのExcel等で保存されたCSV対策)-----------------
    # Windowsの改行は CR + LF の2文字。Linuxで読むと最後の項目に CR が
    # 1文字残り、見た目には分からないのに「空ではない」と判定されてしまう。
    # ${変数%パターン} は「末尾がパターンに一致すれば取り除く」書き方。
    # $'\r' は CR という1文字を表すbash独自の書き方。
    # CRが無ければ何も起きないので、Linuxで作ったCSVに適用しても安全。
    fullname="${fullname%$'\r'}"
    username="${username%$'\r'}"
    dept="${dept%$'\r'}"
    password="${password%$'\r'}"

    # --- 空行は何も出さずに読み飛ばす ---------------------------------------
    # -z は「文字列が空である」という判定。&& は「かつ」。
    # 4項目すべてが空なら、その行は空行(またはCRだけの行)とみなす。
    # continue は「この行の残りの処理を飛ばして次の行へ進む」命令。
    if [[ -z "$fullname" && -z "$username" && -z "$dept" && -z "$password" ]]; then
        continue
    fi

    # --- 必須項目のチェック --------------------------------------------------
    # || は「または」。1項目でも空ならデータとして使えないので、
    # その行だけをスキップして次へ進む。ここで exit してしまうと、
    # 1行の記入漏れのせいで残り全員が処理されなくなってしまう。
    if [[ -z "$fullname" || -z "$username" || -z "$dept" || -z "$password" ]]; then
        echo "スキップ: ${LINE_NO}行目 項目が足りません"
        SKIP_COUNT=$((SKIP_COUNT + 1))
        continue
    fi

    # --- 正常な行の処理 ------------------------------------------------------
    # $(( )) は算術式。中では変数に $ を付けなくてもよい。
    # 初期パスワード($password)は絶対に表示しない。画面やログに残った
    # パスワードは、そのまま情報漏えいにつながるため。
    # ここが案件No.1では useradd / chpasswd の呼び出しに置き換わる。
    OK_COUNT=$((OK_COUNT + 1))
    echo "[${OK_COUNT}] ${fullname} / ${username} / ${dept}"

done < <(tail -n +2 "$CSV_FILE")
#   tail -n +2 : 1行目(ヘッダー行)を除いた2行目以降だけを取り出す。
#                -n 2 と書くと「最後の2行」という全く別の意味になるので注意。
#   < <(...)   : プロセス置換。コマンドの出力をファイルのように扱ってループへ流す。
#                tail ... | while ... とパイプで書くと、パイプの右側が
#                サブシェル(別プロセス)になり、ループ内で数えた OK_COUNT や
#                SKIP_COUNT がループを抜けた瞬間に消えてしまう。
#                その結果、合計が必ず 0件 になるという有名な落とし穴がある。
#                なお < と <( の間には半角スペースが必要。

#===============================================================================
# 4. 結果サマリの出力
#
#   何件処理して何件飛ばしたかを最後に必ず出す。
#   運用では、この1行だけを見て「今日の取り込みは想定どおりか」を判断する。
#===============================================================================
echo "合計: ${OK_COUNT}件 (スキップ: ${SKIP_COUNT}件)"

# この演習では「ファイルを最後まで読み切れた」ことをもって成功とし、
# スキップがあっても終了ステータスは0とする。
# (案件No.1では、失敗件数が1件以上あれば1を返す設計にしている)
exit 0
