#!/bin/bash
#===============================================================================
# ex03 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# テスト用のCSVを作業ディレクトリに用意する
#
#   実務で実際に届く「汚れたCSV」を再現する。
#     ・2行目と4行目の行末は CR+LF (Windowsで保存されたCSV)
#     ・3行目は空行
#     ・4行目は初期パスワードが空(項目不足)
#     ・6行目(最終行)は改行で終わっていない
#   CR を含めるため、ヒアドキュメントではなく printf で1行ずつ作っている。
#   ( \r\n がWindowsの改行、\n がLinuxの改行 )
#-------------------------------------------------------------------------------
printf '%s\r\n' '氏名,ユーザー名,部署,初期パスワード'      >  users.csv
printf '%s\r\n' '佐藤 花子,sato_h,eigyou,Passw0rd!'        >> users.csv
printf '\n'                                                >> users.csv
printf '%s\r\n' '田中 太郎,tanaka_t,soumu,'                >> users.csv
printf '%s\n'   '鈴木 一郎,suzuki_i,kaihatsu,Pw12345'      >> users.csv
printf '%s'     '山田 次郎,yamada_j,jinji,TopSecret9'      >> users.csv

# ヘッダー行だけのCSV(データが1件も無いケース)
cat > header_only.csv <<'EOF'
氏名,ユーザー名,部署,初期パスワード
EOF

#-------------------------------------------------------------------------------
describe "異常系: 引数やファイルが正しくないとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。1個でなければ exit 1 で終了してください。"
assert_status 1 "引数なしで実行すると終了ステータス1で終わる"

hint "使い方のメッセージは echo \"...\" >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

run_target missing.csv

hint "読み込むファイルが無ければ、処理を始めずに exit 1 で終了します。"
assert_status 1 "存在しないファイルを指定すると終了ステータス1で終わる"

hint "メッセージは README の仕様表からそのままコピーしてください。"
assert_stderr_contains "エラー: ファイルが見つかりません: missing.csv" \
    "標準エラー出力に「エラー: ファイルが見つかりません: <パス>」を表示する"

#-------------------------------------------------------------------------------
describe "正常系: 汚れたCSVを読み込んだとき"
#-------------------------------------------------------------------------------
run_target users.csv

hint "1行が不正でも処理は止めません。最後まで読み切れたら exit 0 です。"
assert_status 0 "最後まで読み切ると終了ステータス0で終わる"

hint "1行目はヘッダー行です。tail -n +2 で読み飛ばしてください。"
assert_output_not_contains "氏名 / ユーザー名" "1行目のヘッダー行は処理しない"

hint "区切りは半角スペース+半角スラッシュ+半角スペースです。連番は1から始めます。"
assert_stdout_contains "[1] 佐藤 花子 / sato_h / eigyou" \
    "正常な行を「[<連番>] <氏名> / <ユーザー名> / <部署>」の形式で表示する"

hint "スキップした行は連番に数えません。次の正常な行が [2] になります。"
assert_stdout_contains "[2] 鈴木 一郎 / suzuki_i / kaihatsu" \
    "スキップした行のぶん連番を飛ばさずに採番する"

hint "最終行に改行が無いCSVです。while ... read ... || [[ -n \"\$fullname\" ]] の形にしてください。"
assert_stdout_contains "[3] 山田 次郎 / yamada_j / jinji" \
    "最終行に改行が無くても最後の1行を処理する"

hint "4行目は初期パスワードが空です。行末のCRを取り除かないと「空ではない」と判定されます。"
assert_stdout_contains "スキップ: 4行目 項目が足りません" \
    "項目が足りない行を「スキップ: <行番号>行目 項目が足りません」と表示する"

hint "空行は何も表示せずに読み飛ばします。行番号だけは1つ進めてください。"
assert_output_not_contains "3行目" "空行についてはメッセージを表示しない"

hint "パイプ( tail ... | while ... )で渡すとカウンタが消えて 0件 になります。done < <(tail -n +2 ...) の形にしてください。"
assert_stdout_contains "合計: 3件 (スキップ: 1件)" \
    "最後に「合計: <正常件数>件 (スキップ: <スキップ件数>件)」を表示する"

hint "初期パスワードは画面にもログにも出してはいけません。表示するのは氏名・ユーザー名・部署だけです。"
assert_output_not_contains "Passw0rd!" "初期パスワードを出力しない"

#-------------------------------------------------------------------------------
describe "正常系: データが1件も無いCSVのとき"
#-------------------------------------------------------------------------------
run_target header_only.csv

hint "データが0件でもエラーではありません。"
assert_status 0 "ヘッダー行だけのCSVでも終了ステータス0で終わる"

hint "カウンタは0で初期化しておき、合計行は必ず表示します。"
assert_stdout_contains "合計: 0件 (スキップ: 0件)" "データが0件のときも合計行を表示する"

finish
