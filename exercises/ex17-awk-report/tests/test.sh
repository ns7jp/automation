#!/bin/bash
#===============================================================================
# ex17 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#
#   固定の監視ログを作り、集計結果の数値・並び順・書式・終了ステータスを
#   1文字単位で確認する。時刻には依存しないので、いつ実行しても結果は同じ。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# 採点用の監視ログを作る($WORKDIR の中。harness が既に cd 済み)
#   web01 : 10件すべて OK          → 100.0%
#   web02 : 10件中 9件 OK          →  90.0%
#   web03 :  3件すべて NG          →   0.0%
#   先頭2行はコメント行、途中に空行を1つ入れてある(どちらも集計対象外)。
#-------------------------------------------------------------------------------
cat > monitor.log <<'EOF'
# 2026-09-01 の監視ログ
# 2026-09-01 10:00:00,web99,NG
2026-09-01 09:00:00,web01,OK
2026-09-01 09:05:00,web01,OK
2026-09-01 09:10:00,web01,OK
2026-09-01 09:15:00,web01,OK
2026-09-01 09:20:00,web01,OK
2026-09-01 09:25:00,web01,OK
2026-09-01 09:30:00,web01,OK
2026-09-01 09:35:00,web01,OK
2026-09-01 09:40:00,web01,OK
2026-09-01 09:45:00,web01,OK
2026-09-01 09:00:00,web02,OK
2026-09-01 09:05:00,web02,OK
2026-09-01 09:10:00,web02,OK
2026-09-01 09:15:00,web02,OK
2026-09-01 09:20:00,web02,NG
2026-09-01 09:25:00,web02,OK
2026-09-01 09:30:00,web02,OK
2026-09-01 09:35:00,web02,OK

2026-09-01 09:40:00,web02,OK
2026-09-01 09:45:00,web02,OK
2026-09-01 09:00:00,web03,NG
2026-09-01 09:05:00,web03,NG
2026-09-01 09:10:00,web03,NG
EOF

# すべてのホストがしきい値以上になるログ(終了ステータス0の確認用)
cat > all_ok.log <<'EOF'
2026-09-01 09:00:00,web01,OK
2026-09-01 09:05:00,web01,OK
2026-09-01 09:10:00,web01,OK
EOF

# 期待する明細行(README の「出力フォーマット」と同じ書式)
LINE_WEB01="web01  10/10  100.0%  判定: 正常"
LINE_WEB02="web02  9/10    90.0%  判定: 要確認"
LINE_WEB03="web03  0/3      0.0%  判定: 要確認"

#-------------------------------------------------------------------------------
describe "異常系: 引数の指定が正しくないとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。1個でも2個でもなければ exit 1 で終了してください。"
assert_status 1 "引数なしで実行すると終了ステータス1で終わる"

hint "使い方は echo \"...\" >&2 や usage >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

run_target monitor.log 99 extra

hint "受け付けるのは1個か2個だけです。[[ \"\$#\" -lt 1 || \"\$#\" -gt 2 ]] で弾けます。"
assert_status 1 "引数が3個のときも終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "異常系: ログファイルが存在しないとき"
#-------------------------------------------------------------------------------
run_target no_such_file.log

hint "集計を始める前に [[ ! -f \"\$LOG_FILE\" ]] で存在を確認して exit 1 してください。"
assert_status 1 "存在しないログファイルを指定すると終了ステータス1で終わる"

hint "エラーメッセージには「見つかりません」という言葉を含めてください(標準エラー出力へ)。"
assert_stderr_contains "見つかりません" "ファイルが無い旨のエラーを標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "正常系: しきい値を省略したとき(既定 99%)"
#-------------------------------------------------------------------------------
run_target monitor.log

hint "1行目は「ホスト名  OK/総数  稼働率  判定」です。区切りは半角スペース2つです。"
assert_stdout_contains "ホスト名  OK/総数  稼働率  判定" "見出し行を表示する"

hint "10件すべてOKなら 100.0% です。printf '%-6s %-6s %5.1f%%  判定: %s\\n' の書式で出します。"
assert_stdout_contains "$LINE_WEB01" "web01 の稼働率を 100.0% として表示する"

hint "10件中9件OKなら 90.0% です。稼働率は %5.1f(右寄せ5桁・小数第1位)で出します。"
assert_stdout_contains "$LINE_WEB02" "web02 の稼働率を 90.0% として表示する"

hint "1件もOKが無いホストでは ok[host] が空文字です。ok[host] + 0 として数値の0にしてください。"
assert_stdout_contains "$LINE_WEB03" "web03 の稼働率を 0.0% として表示する"

hint "for (host in total) の順番は不定です。awk の出力を sort に通してください。"
assert_stdout_contains "${LINE_WEB01}"$'\n'"${LINE_WEB02}"$'\n'"${LINE_WEB03}" \
    "ホスト名の昇順(web01 → web02 → web03)で並べる"

hint "総レコード数は各ホストの総件数の合計です。空行とコメント行は数えません。"
assert_stdout_contains "集計対象: 23件 / ホスト数: 3件 / しきい値: 99%" \
    "サマリ行を「集計対象: 23件 / ホスト数: 3件 / しきい値: 99%」の形式で表示する"

hint "空行と # で始まる行は awk の中で next を使って読み飛ばしてください。"
assert_output_not_contains "web99" "コメント行(# で始まる行)は集計しない"

hint "しきい値未満のホストが1つでもあれば exit 1 です(web02 と web03 が該当)。"
assert_status 1 "しきい値未満のホストがあれば終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "正常系: しきい値を第2引数で指定したとき"
#-------------------------------------------------------------------------------
run_target monitor.log 80

hint "しきい値は -v th=\"\$THRESHOLD\" で awk へ渡します。90.0% は 80% 以上なので正常です。"
assert_stdout_contains "web02  9/10    90.0%  判定: 正常" \
    "しきい値80のとき web02 (90.0%) の判定が正常になる"

hint "サマリ行のしきい値は 99 固定ではなく、第2引数で受け取った値を表示します。"
assert_stdout_contains "しきい値: 80%" "サマリ行に指定したしきい値を表示する"

#-------------------------------------------------------------------------------
describe "正常系: すべてのホストがしきい値以上のとき"
#-------------------------------------------------------------------------------
run_target all_ok.log

hint "要確認のホストが1つも無ければ exit 0 で終わります。"
assert_status 0 "しきい値未満のホストが無ければ終了ステータス0で終わる"

#-------------------------------------------------------------------------------
describe "書き方のチェック"
#-------------------------------------------------------------------------------
hint "1行目に #!/bin/bash(シバン)を書きます。"
assert_file_contains "$TARGET" '^#!/bin/bash' "1行目にシバンがある"

finish
