#!/bin/bash
#===============================================================================
# ex17: awkで稼働率を集計する(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている「集計は awk に任せ、整形はシェルの printf で行う」
# という分担は実務でも定番なので、意味を理解したうえで真似することを勧めます。
#
# 処理の流れ:
#   1. 引数を確認する(ログファイル / しきい値)
#   2. awk でホストごとに集計し、sort で並べ替えて中間データを作る
#   3. 中間データを1行ずつ読み、printf で表の形に整える
#   4. サマリ行を出し、しきい値未満のホストがあれば終了ステータス1で終わる
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   -e は付けていない。この演習では「しきい値未満のホストがあれば exit 1」を
#   自分で制御したいので、途中のコマンドの失敗で勝手に止まってほしくないため。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#
#   引数エラーは2か所(個数エラー・将来のオプション追加)から呼ぶ可能性があるので
#   関数にまとめておく。メッセージを直す場所も1か所で済む。
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <監視ログファイル> [<しきい値(%)>]"
    echo "  監視ログを集計し、ホストごとの稼働率レポートを表示します。"
    echo "  しきい値を省略した場合は 99 (%) として判定します。"
}

#-------------------------------------------------------------------------------
# 1. 引数の個数チェック
#
#   受け付けるのは1個(ログファイルのみ)か2個(ログファイル+しきい値)。
#   それ以外は使い方を標準エラー出力(>&2)に出して失敗で終わる。
#   >&2 を付けると、レポート本体をファイルに保存していてもエラーだけは画面に残る。
#-------------------------------------------------------------------------------
if [[ "$#" -lt 1 || "$#" -gt 2 ]]; then
    echo "エラー: 引数の指定が正しくありません。" >&2
    usage >&2
    exit 1
fi

#-------------------------------------------------------------------------------
# 2. 引数の取り込み
#
#   "${2:-99}" は「$2 があればその値、無ければ 99」という書き方。
#   set -u を付けていても、この形なら未定義エラーにならない。
#   「既定値をコードの1か所に書いておく」のは設定を持つスクリプトの定石。
#-------------------------------------------------------------------------------
LOG_FILE="$1"
THRESHOLD="${2:-99}"

#-------------------------------------------------------------------------------
# 3. 入力ファイルの存在チェック
#
#   awk は存在しないファイルを渡されるとエラーを出すが、
#   その英語メッセージより「どのファイルが無いのか」を日本語で伝えたほうが
#   運用担当者にとって親切なので、自前で確認して止める。
#-------------------------------------------------------------------------------
if [[ ! -f "$LOG_FILE" ]]; then
    echo "エラー: 監視ログファイルが見つかりません: ${LOG_FILE}" >&2
    exit 1
fi

#-------------------------------------------------------------------------------
# 4. awk による集計
#
#   -F','          : 列の区切り文字をカンマにする。$1=日時 $2=ホスト名 $3=結果
#   -v th="..."    : シェルの変数を awk へ渡す。awk のプログラムはシングル
#                    クォートで囲むため、中に $THRESHOLD と書いても展開されない
#                    (awk の $ は「列番号」の意味なので混ぜると事故になる)。
#
#   /^[[:space:]]*$/ { next }  空行を読み飛ばす
#   /^[[:space:]]*#/ { next }  # で始まるコメント行を読み飛ばす
#     この2つを書かないと、$2 が空文字の「名前の無いホスト」が
#     集計結果に混ざってしまう。
#
#   END { }        : 全行を読み終えたあとに1回だけ実行されるブロック。
#   ok[host] + 0   : 一度もOKが無かったホストは ok[host] が空文字のまま。
#                    + 0 を付けることで数値の 0 として扱える。
#
#   for (host in total) の取り出し順は不定なので、出力を sort に通して
#   ホスト名の昇順にそろえる。
#
#   ここで出しているのは表そのものではなく、
#     web01 10 10 100.0 正常
#   という「1ホスト1行のスペース区切り中間データ」。
#   整形をシェル側に任せることで、awk のプログラムを短く保てる。
#-------------------------------------------------------------------------------
STATS="$(
    awk -F',' -v th="$THRESHOLD" '
        /^[[:space:]]*$/ { next }
        /^[[:space:]]*#/ { next }
        {
            total[$2]++
            if ($3 == "OK") {
                ok[$2]++
            }
        }
        END {
            for (host in total) {
                rate = (ok[host] + 0) / total[host] * 100
                judge = (rate < th) ? "要確認" : "正常"
                printf "%s %d %d %.1f %s\n", host, ok[host] + 0, total[host], rate, judge
            }
        }
    ' "$LOG_FILE" | sort
)"

#-------------------------------------------------------------------------------
# 5. 見出し行
#-------------------------------------------------------------------------------
echo "ホスト名  OK/総数  稼働率  判定"

#-------------------------------------------------------------------------------
# 6. 明細行の整形と、サマリ用の数え上げ
#
#   <<< "$STATS" はヒアストリング。変数の中身を while read の入力にする。
#   read -r の -r は「バックスラッシュをエスケープとして解釈しない」指定で、
#   read を使うときは常に付けると覚えてよい。
#
#   STATS が空文字のときでも <<< は改行1つを渡すため、read は空行を1回読む。
#   そのまま処理すると空のホストが1件表示されてしまうので、先頭で弾いておく。
#
#   printf の書式:
#     %-6s  … 左寄せ6桁の文字列(ホスト名、OK/総数)
#     %5.1f … 右寄せ5桁・小数第1位の数値(稼働率)
#     %%    … % そのもの
#-------------------------------------------------------------------------------
TOTAL_RECORDS=0
HOST_COUNT=0
NG_HOSTS=0

while read -r host ok total rate judge; do
    [[ -z "$host" ]] && continue

    printf '%-6s %-6s %5.1f%%  判定: %s\n' "$host" "${ok}/${total}" "$rate" "$judge"

    TOTAL_RECORDS=$((TOTAL_RECORDS + total))
    HOST_COUNT=$((HOST_COUNT + 1))
    if [[ "$judge" == "要確認" ]]; then
        NG_HOSTS=$((NG_HOSTS + 1))
    fi
done <<< "$STATS"

#-------------------------------------------------------------------------------
# 7. サマリ行
#
#   「何件を対象に集計したのか」を必ず書き添える。件数が想定より少ないときに
#   「ログの切り出し範囲が間違っている」とすぐ気づけるようにするため。
#-------------------------------------------------------------------------------
echo "集計対象: ${TOTAL_RECORDS}件 / ホスト数: ${HOST_COUNT}件 / しきい値: ${THRESHOLD}%"

#-------------------------------------------------------------------------------
# 8. 終了ステータス
#
#   しきい値未満のホストが1つでもあれば失敗(1)として終わる。
#   こうしておくと cron や CI から呼んだときに、
#   「レポートを見なくても異常があったかどうか」を呼び出し側が判断できる。
#-------------------------------------------------------------------------------
if [[ "$NG_HOSTS" -gt 0 ]]; then
    exit 1
fi

exit 0
