#!/bin/bash
#===============================================================================
# ex05 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
# 採点用の練習ファイルを作業ディレクトリに用意する
#   tmp/     … 既定の対象ディレクトリ。.tmp が2件、.txt が1件
#   applogs/ … -d と -e の動作確認用。.log が2件、.tmp が1件
#   empty/   … 対象が0件のときの確認用
#-------------------------------------------------------------------------------
mkdir -p tmp applogs empty
: > tmp/a.tmp
: > tmp/b.tmp
: > tmp/c.txt
: > applogs/x.log
: > applogs/y.log
: > applogs/keep.tmp

#-------------------------------------------------------------------------------
describe "正常系: -n (ドライラン) を指定したとき"
#-------------------------------------------------------------------------------
run_target -n

hint "ドライランのときの書式は「[dry-run] 削除します: <ファイル名>」です。パスは付けず basename で名前だけにします。"
assert_stdout_contains "[dry-run] 削除します: a.tmp" \
    "-n のとき「[dry-run] 削除します: a.tmp」と表示する"

hint "件数の後ろに、もう1行「ドライランのため、実際には削除していません。」を出します(句点まで含めます)。"
assert_stdout_contains "ドライランのため、実際には削除していません。" \
    "-n のとき「ドライランのため、実際には削除していません。」と表示する"

hint "ドライランでは rm を実行してはいけません。DRY_RUN の判定と rm の位置を確認してください。"
assert_file_count "tmp/*.tmp" 2 "-n のときはファイルを1件も削除しない"

run_target --dry-run

hint "getopts は1文字のオプションしか扱えません。--dry-run を -n に置き換えてから getopts に渡します。変換しないと、その場でエラーになって処理が始まりません。"
assert_stdout_contains "[dry-run] 削除します: a.tmp" \
    "--dry-run でも -n と同じくドライランとして動く"

assert_file_count "tmp/*.tmp" 2 "--dry-run でもファイルを1件も削除しない"

#-------------------------------------------------------------------------------
describe "正常系: オプションなしで実行したとき(既定の ./tmp の *.tmp を削除)"
#-------------------------------------------------------------------------------
run_target

hint "削除できたら1件ごとに「削除しました: <ファイル名>」を標準出力に出します。"
assert_stdout_contains "削除しました: a.tmp" "「削除しました: a.tmp」と表示する"

hint "最後に「対象: <件数>件」を出します。数えるのは処理したファイルの件数です。"
assert_stdout_contains "対象: 2件" "「対象: 2件」と表示する"

hint "オプション指定が無いときの既定値は -d が ./tmp、-e が tmp です。変数の初期値として入れておきます。"
assert_file_count "tmp/*.tmp" 0 "既定値のまま実行すると ./tmp の *.tmp が削除される"

hint "ループのパターンは *.\"\${EXT}\" です。* だけにすると対象外のファイルまで消えてしまいます。"
assert_file_exists "tmp/c.txt" "拡張子が違う c.txt は削除しない"

#-------------------------------------------------------------------------------
describe "正常系: -d と -e で対象を変えたとき"
#-------------------------------------------------------------------------------
run_target -d applogs -e log

hint "値を取るオプションは getopts \"d:e:nh\" のように : を付け、値を \$OPTARG から受け取ります。"
assert_file_count "applogs/*.log" 0 "-d applogs -e log で applogs の *.log が削除される"

#-------------------------------------------------------------------------------
describe "正常系: 対象が0件のとき"
#-------------------------------------------------------------------------------
run_target -d empty

hint "グロブが1件もマッチしないとパターン文字列がそのまま入ります。[[ -f \"\$file\" ]] で存在チェックしてから数えます。"
assert_stdout_contains "対象: 0件" "対象が0件のときは「対象: 0件」と表示する"

hint "対象が0件でも処理は成功しています。exit 0 で終わってください。"
assert_status 0 "対象が0件でも終了ステータス0で終わる"

#-------------------------------------------------------------------------------
describe "正常系: -h を指定したとき"
#-------------------------------------------------------------------------------
run_target -h

hint "ヘルプは利用者が意図して求めた出力なので、標準出力に出して exit 0 で終わります。"
assert_status 0 "-h を指定すると終了ステータス0で終わる"

hint "ヘルプは標準出力に出します(>&2 を付けない)。usage の中身に「使い方」という言葉を入れてください。"
assert_stdout_contains "使い方" "-h で使い方を標準出力に表示する"

#-------------------------------------------------------------------------------
describe "異常系: 未定義のオプションを指定したとき"
#-------------------------------------------------------------------------------
run_target -z

hint "getopts は未定義のオプションのとき opt に ? を入れます。case では \\?) と書いて受け取ります。"
assert_status 1 "未定義のオプション -z を指定すると終了ステータス1で終わる"

hint "誤操作の通知なので、-h のときとは違って使い方を標準エラー出力に出します(usage >&2)。"
assert_stderr_contains "使い方" "未定義のオプションのとき、使い方を標準エラー出力に表示する"

#-------------------------------------------------------------------------------
describe "異常系: 対象ディレクトリが存在しないとき"
#-------------------------------------------------------------------------------
run_target -d nosuchdir

hint "[[ ! -d \"\$TARGET_DIR\" ]] でディレクトリの存在を確認し、無ければ exit 1 で止めます。"
assert_status 1 "存在しないディレクトリを指定すると終了ステータス1で終わる"

hint "エラーメッセージは echo \"...\" >&2 で標準エラー出力に出します。"
assert_stderr_contains "エラー: ディレクトリが見つかりません: nosuchdir" \
    "「エラー: ディレクトリが見つかりません: <パス>」を標準エラー出力に出す"

finish
