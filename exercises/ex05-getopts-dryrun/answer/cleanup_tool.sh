#!/bin/bash
#===============================================================================
# ex05: オプション解析とドライラン(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている書き方(長いオプションの変換 → getopts → 既定値、
# そしてドライラン)は案件No.1の create_users.sh とまったく同じ構成です。
# 削除を伴うスクリプトの「型」として、意味を理解したうえで真似してください。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   削除処理では、変数のタイプミスで意図しないパスを対象にしてしまう事故が
#   最も怖い。set -u は、その事故を実行前に止めるための最初の防御線になる。
set -u

#===============================================================================
# 1. 既定値の設定
#
#   「オプションで上書きできる既定値」は、変数の初期値として先に入れておく。
#   こうしておくと、getopts の case では「指定されたときだけ上書きする」
#   という単純な処理を書けばよくなる。
#===============================================================================
SCRIPT_NAME="$(basename "$0")"
TARGET_DIR="./tmp"        # -d で指定が無ければこのディレクトリを掃除する
EXT="tmp"                 # -e で指定が無ければこの拡張子を対象にする
DRY_RUN="false"           # -n / --dry-run が指定されたら "true" になる

#===============================================================================
# 2. 使い方の表示
#
#   既定値を ${TARGET_DIR} のように埋め込んでおくと、ヘルプと実装の
#   食い違いが起きない。既定値を変えたときにヘルプの修正を忘れずに済む。
#===============================================================================
usage() {
    echo "使い方: ${SCRIPT_NAME} [-d <ディレクトリ>] [-e <拡張子>] [-n] [-h]"
    echo "  指定ディレクトリ直下の *.<拡張子> を削除します。"
    echo "  -d <ディレクトリ>  対象ディレクトリ (既定: ${TARGET_DIR})"
    echo "  -e <拡張子>        削除する拡張子   (既定: ${EXT})"
    echo "  -n                 ドライラン。実際には削除しません (--dry-run も可)"
    echo "  -h                 この使い方を表示します (--help も可)"
}

#===============================================================================
# 3. 長いオプションを短いオプションに変換する
#
#   bash組み込みの getopts は、仕様上 -n のような1文字オプションしか扱えない。
#   --dry-run のような長いオプションも受け付けるため、getopts に渡す前に
#   対応する短いオプションへ置き換えてしまう、という手法を使う。
#
#   args=() は空の配列(値を順番に入れておける箱)。
#   args+=("$arg") で末尾に追加していき、最後に set -- で位置引数
#   ($1, $2, ...)を丸ごと置き換える。
#===============================================================================
args=()
for arg in "$@"; do
    case "$arg" in
        --dry-run) args+=("-n") ;;
        --help)    args+=("-h") ;;
        *)         args+=("$arg") ;;
    esac
done
set -- "${args[@]}"

#===============================================================================
# 4. オプションの解析
#
#   "d:e:nh" の : は「そのオプションは値を取る」という印。
#   値は $OPTARG に入る。値を取らない -n や -h には : を付けない。
#
#   ヘルプ(-h)は利用者が意図して求めた出力なので標準出力に出して exit 0。
#   未定義のオプション(\?)は誤操作なので標準エラー出力に出して exit 1。
#   この2つを区別することが、パイプやcronから使われるツールでは重要になる。
#===============================================================================
while getopts "d:e:nh" opt; do
    case "$opt" in
        d)  TARGET_DIR="$OPTARG" ;;
        e)  EXT="$OPTARG" ;;
        n)  DRY_RUN="true" ;;
        h)  usage; exit 0 ;;
        \?) usage >&2; exit 1 ;;
    esac
done
# 処理したオプションの分だけ引数をずらす。
# 今回は使わないが、この後ろで位置引数を扱う場合に必要になる定番の1行。
shift $((OPTIND - 1))

#===============================================================================
# 5. 対象ディレクトリの存在チェック
#
#   存在チェックはオプション解析より「後」に置く。先に置いてしまうと、
#   -h でヘルプを見たいだけのときにもエラーで止まってしまう。
#
#   -d は「ディレクトリとして存在するか」の判定。-f(通常ファイル)と
#   間違えやすいので注意する。
#===============================================================================
if [[ ! -d "$TARGET_DIR" ]]; then
    echo "エラー: ディレクトリが見つかりません: ${TARGET_DIR}" >&2
    exit 1
fi

#===============================================================================
# 6. 対象ファイルの処理
#
#   ${TARGET_DIR%/} は末尾のスラッシュを取り除くパラメータ展開。
#   -d ./tmp/ のように指定されても ./tmp//*.tmp とならないようにする。
#
#   グロブ(*.tmp)は、1件もマッチしない場合、bashの既定では
#   パターン文字列そのものを1回返す。そのまま数えると「対象: 1件」と
#   表示され、rm に渡せば「そんなファイルはない」というエラーになる。
#   そこでループの先頭で [[ -f ]] による存在チェックを行い、
#   実在する通常ファイル以外は continue で読み飛ばしている。
#   これはディレクトリ(例: sub.tmp/)を誤って削除しないための守りにもなる。
#===============================================================================
COUNT=0

for file in "${TARGET_DIR%/}"/*."${EXT}"; do
    [[ -f "$file" ]] || continue

    # 表示用にはパスを除いたファイル名だけを使う
    filename="$(basename "$file")"
    COUNT=$((COUNT + 1))

    if [[ "$DRY_RUN" == "true" ]]; then
        # ドライランでは「何が起きるか」を見せるだけで、一切変更しない。
        echo "[dry-run] 削除します: ${filename}"
        continue
    fi

    # rm の -- は「これ以降はオプションではなくファイル名」という区切り。
    # -foo.tmp のようなファイル名をオプションと誤解させないための保険。
    if rm -- "$file"; then
        echo "削除しました: ${filename}"
    else
        echo "エラー: 削除できませんでした: ${filename}" >&2
    fi
done

#===============================================================================
# 7. 結果の表示
#
#   対象が0件でも「対象: 0件」と表示する。何も出力せずに終わるより、
#   「動いた結果、対象が無かった」と分かるほうが運用では圧倒的に助かる。
#===============================================================================
echo "対象: ${COUNT}件"

if [[ "$DRY_RUN" == "true" ]]; then
    echo "ドライランのため、実際には削除していません。"
fi

# 削除件数が0件でも、処理そのものは成功しているので終了ステータスは0。
exit 0
