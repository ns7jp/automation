#!/bin/bash
#===============================================================================
# ex01: サーバー情報表示スクリプト(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし、ここで使っている書き方(クォート、$#、>&2、exit)は実務の
# シェルスクリプトでも定番なので、意味を理解したうえで真似することを勧めます。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   例えば $SERVR_NAME のようにタイプミスした場合、set -u が無いと
#   「空文字」として動いてしまい、原因の分かりにくいバグになる。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#
#   関数にしておくと「引数エラーのとき」と「--help のとき」の2か所から
#   同じメッセージを呼び出せる。メッセージを直す場所も1か所で済む。
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <サーバー名>"
    echo "  指定したサーバー名と、実行環境の情報を表示します。"
}

#-------------------------------------------------------------------------------
# 1. ヘルプオプションの判定
#
#   ${1:-} は「$1 が未定義なら空文字として扱う」という書き方。
#   set -u を付けていると、引数なしで実行したときに $1 をそのまま参照すると
#   エラーになってしまうため、この形にしておく。
#
#   ヘルプは「利用者が意図して求めた出力」なので、標準出力に出し、
#   終了ステータスは 0(成功)とする。
#-------------------------------------------------------------------------------
case "${1:-}" in
    -h|--help)
        usage
        exit 0
        ;;
esac

#-------------------------------------------------------------------------------
# 2. 引数の個数チェック
#
#   $# は引数の個数。-ne は「等しくない(not equal)」。
#   エラーメッセージは標準エラー出力(>&2)に出す。こうしておくと
#     ./server_info.sh > result.txt
#   のように出力をファイルへ保存したとき、エラーだけは画面に残る。
#-------------------------------------------------------------------------------
if [[ "$#" -ne 1 ]]; then
    echo "エラー: サーバー名を1つ指定してください。" >&2
    usage >&2
    exit 1
fi

#-------------------------------------------------------------------------------
# 3. 情報の取得
#
#   $( ) はコマンド置換。コマンドの実行結果を文字列として変数に入れられる。
#   バッククォート ` ` でも同じことができるが、入れ子にしづらく読みにくいため
#   現在は $( ) を使うのが一般的。
#-------------------------------------------------------------------------------
SERVER_NAME="$1"
HOST_NAME="$(hostname)"
NOW="$(date '+%Y-%m-%d %H:%M:%S')"
RUN_USER="$(whoami)"

#-------------------------------------------------------------------------------
# 4. 表示
#
#   変数は必ずダブルクォートで囲む。囲まないと、値に空白が含まれる場合に
#   意図せず複数の引数に分割されてしまう。
#-------------------------------------------------------------------------------
echo "===== サーバー情報 ====="
echo "サーバー名: ${SERVER_NAME}"
echo "ホスト名: ${HOST_NAME}"
echo "実行日時: ${NOW}"
echo "実行ユーザー: ${RUN_USER}"

# 成功を表す終了ステータス0で終了する。
# 明示的に書かなくても最後のコマンドの終了ステータスが返るが、
# 「意図して成功で終わらせている」ことを示すために書いておく。
exit 0
