#!/bin/bash
#===============================================================================
# ex01 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

#-------------------------------------------------------------------------------
describe "異常系: 引数なしで実行したとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。1個でなければ exit 1 で終了してください。"
assert_status 1 "引数なしで実行すると終了ステータス1で終わる"

hint "エラーメッセージは echo \"...\" >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

hint "引数が足りないのにサーバー情報を表示してはいけません。exit 1 で処理を止めてください。"
assert_output_not_contains "サーバー名:" "引数なしのときはサーバー情報を表示しない"

#-------------------------------------------------------------------------------
describe "異常系: 引数が2つ以上のとき"
#-------------------------------------------------------------------------------
run_target web01 web02

hint "「1個ではないとき」はエラーです。-ne 1 で判定すると多い場合も検出できます。"
assert_status 1 "引数が2つのときも終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "正常系: -h / --help を指定したとき"
#-------------------------------------------------------------------------------
run_target -h

hint "ヘルプは利用者が意図して求めた出力なので、成功(0)で終了します。"
assert_status 0 "-h を指定すると終了ステータス0で終わる"

hint "ヘルプは標準出力に出します(>&2 を付けない)。"
assert_stdout_contains "使い方" "-h で使い方を標準出力に表示する"

run_target --help
assert_status 0 "--help でも終了ステータス0で終わる"

#-------------------------------------------------------------------------------
describe "正常系: サーバー名を1つ指定したとき"
#-------------------------------------------------------------------------------
run_target web01

hint "正常に処理できた場合は exit 0 です。"
assert_status 0 "終了ステータス0で終わる"

assert_stdout_contains "===== サーバー情報 =====" "見出し行を表示する"

hint "引数で受け取った値をそのまま表示します。区切りは半角コロン+半角スペースです。"
assert_stdout_contains "サーバー名: web01" "サーバー名を「サーバー名: web01」の形式で表示する"

hint "ホスト名は hostname コマンドの結果を \$( ) で取り込みます。"
assert_stdout_contains "ホスト名: $(hostname)" "hostname コマンドの結果を表示する"

hint "date '+%Y-%m-%d %H:%M:%S' を使うと、この形式になります。"
assert_stdout_matches "実行日時: [0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2}" \
    "実行日時を YYYY-MM-DD HH:MM:SS 形式で表示する"

hint "実行ユーザーは whoami コマンドの結果です。"
assert_stdout_contains "実行ユーザー: $(whoami)" "whoami コマンドの結果を表示する"

#-------------------------------------------------------------------------------
describe "書き方のチェック"
#-------------------------------------------------------------------------------
hint "1行目に #!/bin/bash(シバン)を書きます。"
assert_file_contains "$TARGET" '^#!/bin/bash' "1行目にシバンがある"

finish
