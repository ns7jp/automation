#!/bin/bash
#===============================================================================
# ex10 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#
#   この演習の対象はシェルスクリプトではなく設定ファイル(cron定義)なので、
#   bash の構文チェック(assert_no_syntax_error)は行わない。
#   代わりに、各行が cron の書式どおりかを正規表現で確認する。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target

# 実行行(数字または * で始まる行)の数を数えておく
JOB_COUNT="$(grep -Ec '^[0-9*]' "$TARGET" || true)"

# 「直前に説明コメントが書かれている実行行」の数を数える。
#   雛形のヘッダーにも # で始まる行があるため、単純にコメント行を数えるだけでは
#   何も書かなくても合格してしまう。そこで「実行行の1つ上が # で始まる行か」を見る。
#   コメントと実行行の間に空行があってもよいものとして数える。
COMMENTED_JOBS="$(awk '
    /^[[:space:]]*#/  { commented = 1; next }
    /^[[:space:]]*$/  { next }
    /^[0-9*]/         { if (commented) n++; commented = 0; next }
                      { commented = 0 }
    END { print n + 0 }
' "$TARGET")"

# ファイルの最後の1文字。改行で終わっていれば、変数展開の結果は空になる
LAST_CHAR="$(tail -c 1 "$TARGET")"

#-------------------------------------------------------------------------------
describe "全体: ファイルの体裁"
#-------------------------------------------------------------------------------
hint "TODO の行はすべて消して、実際の設定を書いてください。"
assert_file_not_contains "$TARGET" "TODO" "雛形の TODO 行が残っていない"

hint "実行する行は MAILTO を除いて4行です。分 時 日 月 曜日 コマンド の形で書きます。"
assert_cmd "cron の実行行を4行書く (現在 ${JOB_COUNT} 行)" test "$JOB_COUNT" -eq 4

hint "4つの実行行それぞれの直前の行に「何をいつ実行するか」を日本語で書いた # で始まる行を入れてください(コメントと実行行の間に空行が入るのはかまいません)。"
assert_cmd "4つの実行行それぞれの直前に説明コメント行を書く (現在 ${COMMENTED_JOBS} 行)" \
    test "$COMMENTED_JOBS" -ge 4

hint "cron の設定ファイルは最終行も改行で終わっている必要があります。行末で改行してください。"
assert_cmd "ファイルの最後が改行で終わっている" test -z "$LAST_CHAR"

#-------------------------------------------------------------------------------
describe "設定: 実行結果メールの宛先"
#-------------------------------------------------------------------------------
hint "MAILTO=\"admin@example.com\" を、行の先頭から書きます。# を付けるとコメントになり無効です。"
assert_file_contains "$TARGET" '^MAILTO="?admin@example\.com"?' \
    'MAILTO="admin@example.com" を設定する'

#-------------------------------------------------------------------------------
describe "ジョブ1: 毎日 深夜2時30分 のバックアップ"
#-------------------------------------------------------------------------------
hint "「毎日 2時30分」は 分=30 時=2 で、日・月・曜日はすべて * です。分が先、時が後です。"
assert_file_contains "$TARGET" '^30 +2 +\* +\* +\*' \
    "毎日 深夜2時30分 を表す 30 2 * * * を書く"

hint "cron は PATH が最小限なので、必ず /opt/scripts/backup.sh のように絶対パスで書きます。"
assert_file_contains "$TARGET" '^30 +2 +\* +\* +\* +/opt/scripts/backup\.sh' \
    "/opt/scripts/backup.sh を絶対パスで実行する"

hint "追記は >> です。> だと毎回上書きされます。2>&1 は >> の後ろに書きます。"
assert_file_contains "$TARGET" \
    '^30 +2 +\* +\* +\* +/opt/scripts/backup\.sh +>> */var/log/backup\.log +2>&1' \
    "backup.sh の出力を >> /var/log/backup.log 2>&1 で追記する"

#-------------------------------------------------------------------------------
describe "ジョブ2: 平日 9時から18時までの死活監視"
#-------------------------------------------------------------------------------
hint "「9時から18時の毎時0分」は 分=0 時=9-18、「月曜から金曜」は曜日=1-5 です。"
assert_file_contains "$TARGET" '^0 +9-18 +\* +\* +1-5' \
    "平日9時から18時の毎時0分を表す 0 9-18 * * 1-5 を書く"

hint "コマンドは絶対パス、出力は >> /var/log/health_check.log 2>&1 で追記します。"
assert_file_contains "$TARGET" \
    '^0 +9-18 +\* +\* +1-5 +/opt/scripts/health_check\.sh +>> */var/log/health_check\.log +2>&1' \
    "health_check.sh の出力を >> /var/log/health_check.log 2>&1 で追記する"

#-------------------------------------------------------------------------------
describe "ジョブ3: 5分ごとのログ監視"
#-------------------------------------------------------------------------------
hint "「5分ごと」は */5 です。5 と書くと「毎時5分に1回だけ」になってしまいます。"
assert_file_contains "$TARGET" '^\*/5 +\* +\* +\* +\*' \
    "5分ごとを表す */5 * * * * を書く"

hint "出力を捨てるのは > /dev/null 2>&1 です。2>&1 は > /dev/null より後ろに書きます。"
assert_file_contains "$TARGET" \
    '^\*/5 +\* +\* +\* +\* +/opt/scripts/log_watch\.sh +> */dev/null +2>&1' \
    "log_watch.sh の出力を > /dev/null 2>&1 で捨てる"

#-------------------------------------------------------------------------------
describe "ジョブ4: 毎月1日の世代削除"
#-------------------------------------------------------------------------------
hint "「毎月1日の3時0分」は 分=0 時=3 日=1 で、月と曜日は * です。"
assert_file_contains "$TARGET" '^0 +3 +1 +\* +\*' \
    "毎月1日の3時0分を表す 0 3 1 * * を書く"

# この行だけ指定が長いため、正規表現を前半と後半に分けて組み立てる
ROTATE_PATTERN='^0 +3 +1 +\* +\* +/opt/scripts/rotate_backups\.sh'
ROTATE_PATTERN+=' +-d +/backup +-g +7 +>> */var/log/rotate\.log +2>&1'

hint "オプションも含めて rotate_backups.sh -d /backup -g 7 と書き、出力は rotate.log へ追記します。"
assert_file_contains "$TARGET" "$ROTATE_PATTERN" \
    "rotate_backups.sh -d /backup -g 7 の出力を >> /var/log/rotate.log 2>&1 で追記する"

finish
