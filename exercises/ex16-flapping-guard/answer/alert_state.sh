#!/bin/bash
#===============================================================================
# ex16: 連続失敗しきい値と復旧通知(解答例)
#
# 解答例は「1つの正解」ではありません。仕様を満たしていれば書き方は自由です。
# ただし「状態をファイルに残し、状態が変わった瞬間だけ通知する」という
# ここでの組み立て方は、案件No.4 health_check.sh の心臓部と同じ考え方です。
# 監視ツールを自作するときは、ほぼ必ずこの形になります。
#===============================================================================

# set -u : 未定義の変数を参照したらエラーで停止する。
#   このスクリプトは環境変数(STATE_DIR / FAIL_THRESHOLD)を読むため、
#   「設定し忘れ」に気づけるよう -u を付けたうえで、後述のとおり
#   ${変数:-既定値} で明示的に既定値を与えている。
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#
#   引数エラーは2か所(個数エラーと値エラー)で起きるので、関数にまとめる。
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <ホスト名> <ok|ng>"
    echo "  監視結果を1件受け取り、通知すべきかどうかを判断して表示します。"
    echo "  環境変数 STATE_DIR (既定: ./state) と FAIL_THRESHOLD (既定: 3) で動作を変えられます。"
}

#-------------------------------------------------------------------------------
# 1. 引数のチェック
#
#   状態を書き換えるスクリプトなので、入力が怪しいときは
#   「何もせずに止まる」ことが最も安全な振る舞いになる。
#   状態ファイルを壊してしまうと、次回以降の判定がすべて狂うため。
#-------------------------------------------------------------------------------
if [[ "$#" -ne 2 ]]; then
    echo "エラー: 引数はホスト名と監視結果の2つです。" >&2
    usage >&2
    exit 1
fi

HOST="$1"
RESULT="$2"

# 想定内の値(ok / ng)を先に通し、それ以外をまとめて弾く。
# 「正常な値を列挙する」書き方にしておくと、想定外の値が
# 素通りして意図しない分岐に落ちる事故を防げる。
case "$RESULT" in
    ok|ng)
        :   # 正しい値。何もしない(: は「何もしない」コマンド)
        ;;
    *)
        echo "エラー: 監視結果は ok または ng を指定してください: ${RESULT}" >&2
        usage >&2
        exit 1
        ;;
esac

#-------------------------------------------------------------------------------
# 2. 設定の読み込み
#
#   ${変数:-既定値} は「変数が未定義または空なら既定値を使う」という書き方。
#   こう書いておくと、スクリプトを書き換えずに
#     FAIL_THRESHOLD=2 ./alert_state.sh web01 ng
#   のように実行時だけ設定を変えられる(案件No.4 では設定ファイルで指定する)。
#-------------------------------------------------------------------------------
STATE_DIR="${STATE_DIR:-./state}"
FAIL_THRESHOLD="${FAIL_THRESHOLD:-3}"

# 状態はホストごとに1ファイルに分ける。1つのファイルに全ホストをまとめると、
# 同時に複数の監視が動いたときに書き込みがぶつかって壊れやすい。
STATE_FILE="${STATE_DIR}/${HOST}.state"

# -p を付けると、既にあってもエラーにならず、途中のディレクトリも作られる。
# 無人で動くスクリプトでは「初回でも黙って動く」ことが重要。
mkdir -p "$STATE_DIR"

#-------------------------------------------------------------------------------
# 3. 前回の状態を読み込む
#
#   状態ファイルの中身は「<連続失敗回数> <通知済みフラグ>」の1行(例: 3 yes)。
#   まだファイルが無い初回のために、読む前に既定値を入れておく。
#   read -r a b < ファイル は、1行目を空白で区切って2つの変数に入れる。
#-------------------------------------------------------------------------------
FAIL_COUNT=0
NOTIFIED="no"

if [[ -f "$STATE_FILE" ]]; then
    read -r FAIL_COUNT NOTIFIED < "$STATE_FILE"
    # 状態ファイルが空だったり、途中で壊れていた場合の保険。
    # 空文字のまま計算や比較に使うとエラーになるため、既定値に戻す。
    FAIL_COUNT="${FAIL_COUNT:-0}"
    NOTIFIED="${NOTIFIED:-no}"
fi

#-------------------------------------------------------------------------------
# 4. 状態遷移の判定(この演習の中心)
#
#   通知は「状態が変わった瞬間」だけ出す(エッジトリガ)。
#   異常な状態が続いている間ずっと出す(レベルトリガ)と、
#   5分おきに同じ通知が鳴り続けて誰も見なくなる。
#-------------------------------------------------------------------------------
if [[ "$RESULT" == "ng" ]]; then
    # 先に回数を1増やしてから判定すると、仕様の表どおりの分岐になる。
    FAIL_COUNT=$((FAIL_COUNT + 1))

    if [[ "$FAIL_COUNT" -lt "$FAIL_THRESHOLD" ]]; then
        # まだしきい値未満。一瞬の通信の揺らぎかもしれないので通知しない。
        # ただし「見なかったこと」にはせず、様子見として記録は残す。
        echo "様子見: ${HOST} 連続${FAIL_COUNT}回目の失敗 (しきい値: ${FAIL_THRESHOLD}回)"
    elif [[ "$NOTIFIED" != "yes" ]]; then
        # しきい値に到達した最初の1回。ここが「異常になった瞬間」なので通知する。
        echo "通知: ${HOST} が異常です (連続${FAIL_COUNT}回失敗)"
        NOTIFIED="yes"
    else
        # すでに通知済み。同じ内容を鳴らし続けないよう抑止する。
        echo "抑止: ${HOST} は通知済みです (連続${FAIL_COUNT}回失敗)"
    fi
else
    # RESULT が ok の場合。
    # リセットする「前」の FAIL_COUNT を使うので、判定と表示を先に行う。
    if [[ "$NOTIFIED" == "yes" ]]; then
        # 異常を通知したあとの復旧。ここが「正常に戻った瞬間」。
        # 復旧通知が無いと、担当者は現地に着くまで直ったことに気づけない。
        echo "通知: ${HOST} が復旧しました (連続${FAIL_COUNT}回失敗のあと復旧)"
    else
        # もともと正常だった。毎回の記録として1行だけ出す。
        echo "正常: ${HOST}"
    fi

    # 1回でも成功したら、連続失敗のカウントと通知済みフラグをリセットする。
    FAIL_COUNT=0
    NOTIFIED="no"
fi

#-------------------------------------------------------------------------------
# 5. 更新後の状態を保存する
#
#   状態は「最新の1行」だけあればよいので、追記(>>)ではなく上書き(>)にする。
#   追記にすると行が増え続け、read が古い1行目を読んでしまう。
#-------------------------------------------------------------------------------
echo "${FAIL_COUNT} ${NOTIFIED}" > "$STATE_FILE"

exit 0
