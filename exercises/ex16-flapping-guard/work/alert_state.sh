#!/bin/bash
#===============================================================================
# ex16: 連続失敗しきい値と復旧通知(あなたが完成させるファイル)
#
# 課題の詳細は ../README.md を読んでください。
# TODO と書かれた場所を埋めれば完成します。
#
# 採点: exercises ディレクトリで ./check.sh 16
#===============================================================================

# set -u : 未定義の変数を使ったらエラーで止める(タイプミス検知のため)
set -u

#-------------------------------------------------------------------------------
# 使い方を表示する関数
#-------------------------------------------------------------------------------
usage() {
    echo "使い方: $(basename "$0") <ホスト名> <ok|ng>"
    echo "  監視結果を1件受け取り、通知すべきかどうかを判断して表示します。"
    echo "  環境変数 STATE_DIR (既定: ./state) と FAIL_THRESHOLD (既定: 3) で動作を変えられます。"
}

#-------------------------------------------------------------------------------
# TODO 1: 引数がちょうど2個でなければ、usage を「標準エラー出力」に出して
#         終了ステータス1で終わる
#   ヒント: 引数の個数は $# 。標準エラー出力に出すには >&2 を付ける
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 2: 1つ目の引数をホスト名、2つ目を監視結果として変数に入れる
#   ヒント: HOST="$1" のように書く
#-------------------------------------------------------------------------------
HOST=""
RESULT=""

#-------------------------------------------------------------------------------
# TODO 3: 監視結果が ok / ng のどちらでもなければ、usage を標準エラー出力に出して
#         終了ステータス1で終わる
#   ヒント: case "$RESULT" in ok|ng) ;; *) ... ;; esac
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 4: 設定を環境変数から受け取る(指定が無ければ既定値を使う)
#   STATE_DIR       : 状態ファイルを置くディレクトリ(既定 ./state)
#   FAIL_THRESHOLD  : 異常とみなす連続失敗回数(既定 3)
#   ヒント: STATE_DIR="${STATE_DIR:-./state}" のように書く
#-------------------------------------------------------------------------------
STATE_DIR=""
FAIL_THRESHOLD=""

# 状態ファイルのパス(ホストごとに1ファイル)
STATE_FILE="${STATE_DIR}/${HOST}.state"

#-------------------------------------------------------------------------------
# TODO 5: 状態ファイルを置くディレクトリを作る(既にあってもエラーにしない)
#   ヒント: mkdir -p "$STATE_DIR"
#-------------------------------------------------------------------------------


#-------------------------------------------------------------------------------
# TODO 6: 前回の状態を読み込む
#   状態ファイルの中身は「<連続失敗回数> <通知済みフラグ>」の1行(例: 3 yes)。
#   ファイルがまだ無い初回のために、既定値(0 と no)を先に入れてある。
#   ヒント: if [[ -f "$STATE_FILE" ]]; then read -r FAIL_COUNT NOTIFIED < "$STATE_FILE"; fi
#-------------------------------------------------------------------------------
FAIL_COUNT=0
NOTIFIED="no"


#-------------------------------------------------------------------------------
# TODO 7: 監視結果によって状態を更新し、メッセージを1行だけ表示する
#
#   RESULT が ng のとき:
#     - FAIL_COUNT を1増やす
#     - しきい値未満        → echo "様子見: ${HOST} 連続${FAIL_COUNT}回目の失敗 (しきい値: ${FAIL_THRESHOLD}回)"
#     - しきい値以上で未通知 → echo "通知: ${HOST} が異常です (連続${FAIL_COUNT}回失敗)"
#                              そのあと NOTIFIED を "yes" にする
#     - しきい値以上で通知済 → echo "抑止: ${HOST} は通知済みです (連続${FAIL_COUNT}回失敗)"
#
#   RESULT が ok のとき:
#     - 通知済みだった  → echo "通知: ${HOST} が復旧しました (連続${FAIL_COUNT}回失敗のあと復旧)"
#     - 通知していない  → echo "正常: ${HOST}"
#     - どちらの場合も、表示したあとに FAIL_COUNT を0、NOTIFIED を "no" に戻す
#
#   ヒント: 数値の比較は -lt (より小さい) / -ge (以上)
#           1増やすのは FAIL_COUNT=$((FAIL_COUNT + 1))
#-------------------------------------------------------------------------------
echo "正常: ${HOST}"

#-------------------------------------------------------------------------------
# TODO 8: 更新後の状態を状態ファイルに書き出す(追記ではなく上書き)
#   形式: <連続失敗回数> <通知済みフラグ>   例: 3 yes
#   ヒント: echo "${FAIL_COUNT} ${NOTIFIED}" > "$STATE_FILE"
#-------------------------------------------------------------------------------


# 正常終了(成功を表す終了ステータス0を返す)
exit 0
