#!/bin/bash
#===============================================================================
# ex16 の採点テスト
#   check.sh から呼び出される。単体で直接実行するものではない。
#
#   同じスクリプトを何度も実行し、状態ファイルを介して
#   「連続失敗回数」と「通知済みフラグ」が正しく引き継がれるかを確認する。
#===============================================================================

# shellcheck source=../../lib/harness.sh
source "${EX_LIB}/harness.sh"

require_target
assert_no_syntax_error

# 既定値(STATE_DIR=./state / FAIL_THRESHOLD=3)の動作を確かめるため、
# 採点する側の環境変数は空にしておく。
unset STATE_DIR
unset FAIL_THRESHOLD

#-------------------------------------------------------------------------------
describe "異常系: 引数の指定が正しくないとき"
#-------------------------------------------------------------------------------
run_target

hint "引数の個数は \$# で調べます。2個でなければ exit 1 で終了してください。"
assert_status 1 "引数なしで実行すると終了ステータス1で終わる"

hint "エラーは echo \"...\" >&2 や usage >&2 のように標準エラー出力へ出します。"
assert_stderr_contains "使い方" "使い方のメッセージを標準エラー出力に表示する"

run_target web01 down

hint "2つ目の引数は ok か ng だけです。case \"\$RESULT\" in ok|ng) ;; *) ... で弾きます。"
assert_status 1 "監視結果に ok / ng 以外を指定すると終了ステータス1で終わる"

#-------------------------------------------------------------------------------
describe "正常系: しきい値(既定3回)に達するまでは通知しない"
#-------------------------------------------------------------------------------
run_target web01 ng

hint "1回の失敗では通知しません。文言は「様子見: <ホスト> 連続<回数>回目の失敗 (しきい値: <N>回)」です。"
assert_stdout_contains "様子見: web01 連続1回目の失敗 (しきい値: 3回)" \
    "1回目の失敗は様子見として表示する"

run_target web01 ng

hint "前回の回数を状態ファイルから読み、1増やしてから判定します。"
assert_stdout_contains "様子見: web01 連続2回目の失敗 (しきい値: 3回)" \
    "2回目の失敗も様子見として表示する"

hint "状態ファイルは <STATE_DIR>/<ホスト名>.state に「<回数> <フラグ>」の1行で保存します。"
assert_file_contains "state/web01.state" '^2 no$' \
    "状態ファイル state/web01.state に「2 no」を保存する"

#-------------------------------------------------------------------------------
describe "正常系: しきい値に到達したときだけ通知する"
#-------------------------------------------------------------------------------
run_target web01 ng

hint "しきい値に到達し、まだ通知していないときだけ通知します。"
assert_stdout_contains "通知: web01 が異常です (連続3回失敗)" \
    "3回目の失敗でしきい値に到達し、異常を通知する"

hint "通知したら、通知済みフラグを yes に変えて保存します。"
assert_file_contains "state/web01.state" '^3 yes$' \
    "通知後の状態ファイルに「3 yes」を保存する"

run_target web01 ng

hint "すでに通知済みなら、同じ通知を繰り返さず抑止します。"
assert_stdout_contains "抑止: web01 は通知済みです (連続4回失敗)" \
    "通知済みのあとの失敗は抑止として表示する"

#-------------------------------------------------------------------------------
describe "正常系: 復旧したときの通知とリセット"
#-------------------------------------------------------------------------------
run_target web01 ok

hint "復旧通知の回数は、リセットする前の連続失敗回数です。表示してからリセットします。"
assert_stdout_contains "通知: web01 が復旧しました (連続4回失敗のあと復旧)" \
    "通知済みの状態で ok を受けると復旧を通知する"

hint "ok を受けたら、連続失敗回数を0、通知済みフラグを no に戻して保存します。"
assert_file_contains "state/web01.state" '^0 no$' \
    "復旧後の状態ファイルに「0 no」を保存する"

run_target web01 ok

hint "通知していない状態での ok は「正常: <ホスト>」とだけ表示します。"
assert_stdout_contains "正常: web01" "通知していない状態の ok は「正常: web01」と表示する"

hint "復旧通知は「通知済みだったとき」だけです。毎回出してはいけません。"
assert_output_not_contains "復旧" "すでに復旧済みのときは復旧通知を出さない"

hint "正常に処理できた場合は exit 0 です。"
assert_status 0 "正常に処理できたときは終了ステータス0で終わる"

#-------------------------------------------------------------------------------
describe "正常系: FAIL_THRESHOLD でしきい値を変えられる"
#-------------------------------------------------------------------------------
# export しないと run_target が起動するサブシェルに値が渡らない
export FAIL_THRESHOLD=2

run_target web09 ng
run_target web09 ng

hint "しきい値は環境変数 FAIL_THRESHOLD から受け取ります: \${FAIL_THRESHOLD:-3}"
assert_stdout_contains "通知: web09 が異常です (連続2回失敗)" \
    "FAIL_THRESHOLD=2 のときは2回目の失敗で通知する"

finish
