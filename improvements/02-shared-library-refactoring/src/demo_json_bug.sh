#!/usr/bin/env bash
#
# =====================================================================
# demo_json_bug.sh
# 改善案件No.2: Slack通知のJSONエスケープ漏れバグを「目で見て確認する」デモ
#
# 何を確かめるスクリプトか:
#   案件No.2(backup.sh)と案件No.4(health_check.sh)の notify_slack() は、
#   Slackへ送るJSONを次のように文字列連結で組み立てている。
#
#       --data "{\"text\": \"${message}\"}"
#
#   この書き方だと、message の中にダブルクォート(")・バックスラッシュ(\)・
#   改行が入った瞬間に、JSONとして壊れた文字列が出来上がってしまう。
#   一方、案件No.3(log-watch-alert.sh)だけは jq -n --arg を使っており、
#   この問題を回避できている。
#
#   このスクリプトは、両方の作り方で実際にJSON文字列を生成し、
#   jq でJSONとして妥当かどうかを判定して結果を並べて表示する。
#
# 安全性について:
#   Slackへは一切送信しない(curlを実行しない)。生成される文字列を
#   画面に表示して比較するだけなので、Webhook URLも不要。
#
# 使い方:
#   ./demo_json_bug.sh
#
# 依存コマンド: jq
# =====================================================================

set -uo pipefail
# -u : 未定義変数の参照でエラーにする(タイプミスの早期発見)
# -o pipefail : パイプの途中で失敗したら、そのパイプ全体を失敗とみなす
# ※ -e は付けない。壊れたJSONを jq に食わせてわざと失敗させる場面が
#    あるため、失敗した時点でスクリプトを止められると困る。

if ! command -v jq > /dev/null 2>&1; then
    echo "エラー: このデモには jq が必要です。'sudo apt-get install -y jq' でインストールしてください。" >&2
    exit 1
fi

# ---------------------------------------------------------------------
# 【Before】案件No.2 / No.4 と同じ、文字列連結でJSONを組み立てる方式
#   引数1: Slackに送りたいメッセージ本文
#   出力 : 組み立てたJSON文字列(のつもりの文字列)
#
#   実際の notify_slack() では、この文字列をそのまま curl --data に渡している。
#   ここでは curl を呼ばず、渡す直前の文字列を echo するだけにしている。
# ---------------------------------------------------------------------
build_payload_before() {
    local message="$1"
    echo "{\"text\": \"${message}\"}"
}

# ---------------------------------------------------------------------
# 【After】案件No.3 と同じ、jq -n --arg でJSONを組み立てる方式
#   引数1: Slackに送りたいメッセージ本文
#   出力 : JSONとして正しくエスケープされた文字列
#
#   jq -n     : 入力を読まずに(null入力で)JSONを新規生成するモード
#   --arg K V : シェルの値 V を、JSON文字列として安全な形に変換して
#               jq プログラム内の変数 $K に渡す。" や \ や改行は
#               jq が自動的に \" \\ \n へエスケープしてくれる。
#   -c        : 結果を1行(compact)で出力する。比較を見やすくするため。
# ---------------------------------------------------------------------
build_payload_after() {
    local message="$1"
    jq -nc --arg text "$message" '{text: $text}'
}

# ---------------------------------------------------------------------
# check_json: 渡された文字列がJSONとして妥当かどうかを判定する
#   引数1: 判定したい文字列
#   戻り値: 0=妥当なJSON / 1=壊れている
#
#   jq empty は「JSONとして読み込めるかどうかだけを確認し、何も出力しない」
#   という定番の書き方。読み込めなければ終了コードが0以外になる。
# ---------------------------------------------------------------------
check_json() {
    local candidate="$1"
    printf '%s' "$candidate" | jq empty > /dev/null 2>&1
}

# ---------------------------------------------------------------------
# 1件分の比較を表示する
#   引数1: テストケースの説明
#   引数2: Slackに送りたいメッセージ本文
# ---------------------------------------------------------------------
compare_one() {
    local title="$1"
    local message="$2"

    local before_payload after_payload
    before_payload="$(build_payload_before "$message")"
    after_payload="$(build_payload_after "$message")"

    local before_result after_result
    if check_json "$before_payload"; then
        before_result="OK (JSONとして妥当)"
    else
        before_result="NG (壊れたJSON)"
    fi
    if check_json "$after_payload"; then
        after_result="OK (JSONとして妥当)"
    else
        after_result="NG (壊れたJSON)"
    fi

    echo "-------------------------------------------------------------------"
    echo "■ ケース: ${title}"
    echo "  メッセージ本文: ${message}"
    echo ""
    echo "  [Before] 文字列連結方式(案件No.2 / No.4 の notify_slack)"
    echo "    生成された文字列: ${before_payload}"
    echo "    JSON妥当性判定  : ${before_result}"
    echo ""
    echo "  [After ] jq方式(案件No.3 の send_slack_notification と同じ)"
    echo "    生成された文字列: ${after_payload}"
    echo "    JSON妥当性判定  : ${after_result}"
    echo ""
}

echo "==================================================================="
echo " Slack通知ペイロードのJSONエスケープ検証"
echo " (Slackへの送信は行いません。生成される文字列を比較するだけです)"
echo "==================================================================="
echo ""

# --- ケース1: 普通のメッセージ。この場合は Before でも壊れない ---
compare_one \
    "特殊文字を含まない普通のメッセージ" \
    ':x: [バックアップ失敗] html-backup-20260907.tar.gz の作成に失敗しました'

# --- ケース2: ダブルクォートを含む。Before が壊れる ---
# 実際に起こりうる例: tarのエラー出力やファイル名をそのままメッセージに載せた場合
compare_one \
    'メッセージ本文にダブルクォート(")が含まれる' \
    'tar: 対象 "public html" を開けません'

# --- ケース3: バックスラッシュを含む。Before が壊れる ---
# 実際に起こりうる例: Windows由来のパスや正規表現をメッセージに載せた場合
compare_one \
    'メッセージ本文にバックスラッシュ(\)が含まれる' \
    'パスの検証に失敗しました: C:\backup\html'

# --- ケース4: 改行を含む。Before が壊れる ---
# 実際に起こりうる例: コマンドの複数行エラー出力をそのまま載せた場合
compare_one \
    'メッセージ本文に改行が含まれる' \
    "$(printf 'バックアップ失敗\n終了コード: 2')"

echo "==================================================================="
echo " まとめ"
echo "-------------------------------------------------------------------"
echo " ・Before(文字列連結)は、\" \\ 改行 を含むと壊れたJSONになる。"
echo "   壊れたJSONをSlackに送るとHTTP 400が返り、通知が届かない。"
echo "   しかも curl の戻り値を見ていないため、失敗しても気づけない。"
echo " ・After(jq -n --arg)はすべてのケースで妥当なJSONを生成する。"
echo " ・この修正は案件No.3で既に行われていたが、"
echo "   コピペ元だった案件No.2 / No.4 には反映されていなかった。"
echo "   これが「コピペで増やすと修正が伝播しない」ことの実例である。"
echo "==================================================================="
