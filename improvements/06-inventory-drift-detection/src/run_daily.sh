#!/usr/bin/env bash
#
# =====================================================================
# run_daily.sh
# 改善案件No.6: サーバー台帳の自動収集・差分検知 - 日次実行のまとめ役
#
# 概要:
#   cronから呼ばれ、以下の3つを決まった順番で実行する。
#     1. collect_inventory.sh … 構成情報を収集してスナップショットを保存
#     2. detect_drift.sh      … 前回との差分を検知してレポート・通知
#     3. generate_ledger.sh   … 最新スナップショットから台帳を再生成
#
# なぜ「まとめ役」を作るのか:
#   cronに3行書いても動くが、それだと「収集がまだ終わっていないのに
#   差分検知が始まる」という順序の事故が起きうる。
#   1本のスクリプトにまとめて順番に呼ぶことで、確実に直列実行されるうえ、
#   cronの登録が1行で済み、手順書もシンプルになる。
#
# 二重起動の防止:
#   flock(=ファイルを使った排他ロック)で、前回の実行が終わっていない
#   場合は起動しないようにしている。収集が長引いたときに2つのプロセスが
#   同じスナップショットを書き合う事故を防ぐため。
#
# 使い方:
#   ./run_daily.sh
#   ./run_daily.sh --config /opt/inventory-drift/inventory.conf
#
# 終了コード:
#   0 : 正常終了(差分なし)
#   2 : 収集に失敗したサーバーがある
#   3 : 差分を検知した(異常ではなく「要確認」の意味)
# =====================================================================

set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_ARGS=()
LOCK_FILE="/var/lock/inventory-drift.lock"

while [ $# -gt 0 ]; do
    case "$1" in
        --config)
            CONFIG_ARGS=(--config "${2:-}")
            shift 2 || true
            ;;
        --lock-file)
            LOCK_FILE="${2:-}"
            shift 2 || true
            ;;
        --help|-h)
            cat <<'USAGE'
使い方: run_daily.sh [オプション]

  --config <ファイル>     3つのスクリプトへ渡す設定ファイル
  --lock-file <ファイル>  二重起動防止用のロックファイル
  --help                  このヘルプを表示する
USAGE
            exit 0
            ;;
        *)
            echo "[ERROR] 不明なオプション: $1" >&2
            exit 1
            ;;
    esac
done

# ---------------------------------------------------------------
# 二重起動の防止
#   exec 9> でファイルディスクリプタ9番をロックファイルに割り当て、
#   flock -n で「すぐに取れなければ諦める(待たない)」ロックを取る。
# ---------------------------------------------------------------
mkdir -p "$(dirname "$LOCK_FILE")" 2>/dev/null || true
exec 9>"$LOCK_FILE" || {
    echo "[ERROR] ロックファイルを作成できません: ${LOCK_FILE}" >&2
    exit 1
}
if ! flock -n 9; then
    echo "[WARN] 前回の実行がまだ終わっていないため、今回の実行を見送ります" >&2
    exit 0
fi

exit_code=0

# ---------------------------------------------------------------
# 1. 収集
#   収集に失敗したサーバーがあっても(終了コード2)、
#   残りのサーバーの差分検知と台帳生成は続ける。
#   「6台中1台が落ちていたら台帳が一切更新されない」のは不便なため。
# ---------------------------------------------------------------
"${SCRIPT_DIR}/collect_inventory.sh" "${CONFIG_ARGS[@]+"${CONFIG_ARGS[@]}"}"
collect_rc=$?
if [ "$collect_rc" -eq 2 ]; then
    exit_code=2
elif [ "$collect_rc" -ne 0 ]; then
    echo "[ERROR] 収集処理が異常終了しました (終了コード: ${collect_rc})" >&2
    exit 1
fi

# ---------------------------------------------------------------
# 2. 差分検知
#   終了コード3は「差分を検知した」という正常な結果であり、
#   エラーではない点に注意(cronのメール通知を無駄に鳴らさないため)。
# ---------------------------------------------------------------
"${SCRIPT_DIR}/detect_drift.sh" "${CONFIG_ARGS[@]+"${CONFIG_ARGS[@]}"}"
drift_rc=$?
if [ "$drift_rc" -eq 3 ]; then
    exit_code=3
elif [ "$drift_rc" -ne 0 ]; then
    echo "[ERROR] 差分検知が異常終了しました (終了コード: ${drift_rc})" >&2
    exit 1
fi

# ---------------------------------------------------------------
# 3. 台帳の再生成
# ---------------------------------------------------------------
if ! "${SCRIPT_DIR}/generate_ledger.sh" "${CONFIG_ARGS[@]+"${CONFIG_ARGS[@]}"}"; then
    echo "[ERROR] 台帳の生成に失敗しました" >&2
    exit 1
fi

exit "$exit_code"
