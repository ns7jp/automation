#!/bin/bash
#===============================================================================
# create_users.sh
#
# 概要:
#   CSVファイル(氏名,ユーザー名,部署(グループ),初期パスワード)を読み込み、
#   Linuxユーザーアカウントを一括作成するツール。
#   株式会社サンプル商事 情報システム部門向けに作成(架空案件)。
#
# 主な機能:
#   - CSVから複数ユーザーを一括作成
#   - 既存ユーザーは自動スキップ(ログに記録)
#   - 所属グループが存在しなければ自動作成
#   - 作成したユーザーは初回ログイン時にパスワード変更を強制(chage -d 0)
#   - 処理結果(成功/失敗/スキップ)を標準出力とログファイルの両方に記録
#   - --dry-run(-n)指定時は実際の変更を一切行わず、動作確認のみを行う
#
# 使い方:
#   sudo ./create_users.sh -f users.csv          本番実行
#   sudo ./create_users.sh -f users.csv -n        ドライラン(動作確認のみ)
#   ./create_users.sh -h                          ヘルプ表示
#
# 終了ステータス:
#   0 : すべて成功(失敗0件)
#   1 : 引数エラー・実行環境エラー、または1件以上の失敗あり
#===============================================================================

#-------------------------------------------------------------------------
# シバン(1行目の #!/bin/bash)について
#   このファイルをコマンドとして実行したとき、OSに
#   「/bin/bash というプログラムにこのファイルの中身を読ませて実行してくれ」
#   と伝えるための特別な1行。必ずファイルの一番先頭(1文字目から)に書く。
#-------------------------------------------------------------------------

# set -u : 未定義の変数を参照した場合にエラーで停止する(タイプミス検知のため)
# ※ set -e はあえて使わない。CSVを1行処理するたびに useradd 等が失敗する
#   可能性があるが、1行の失敗で全体を止めず「その行だけ失敗として記録し
#   次の行へ処理を継続する」という要件のため、エラー制御は if 文で個別に行う。
set -u

#===============================================================================
# 1. デフォルト値の設定
#===============================================================================
CSV_FILE="users.csv"      # -f で指定がなければこのファイルを読み込む
LOG_DIR="./logs"          # -l で指定がなければこのディレクトリにログを出す
DRY_RUN="false"           # -n / --dry-run 指定時に "true" になる
SCRIPT_NAME=$(basename "$0")
TIMESTAMP=$(date '+%Y%m%d_%H%M%S')

# 集計用カウンタ(0で初期化)
SUCCESS_COUNT=0
SKIP_COUNT=0
FAIL_COUNT=0

#===============================================================================
# 2. ヘルプ表示関数
#===============================================================================
usage() {
    cat <<EOF
使い方: ${SCRIPT_NAME} [オプション]

CSVファイルを読み込み、Linuxユーザーアカウントを一括作成します。
CSVの列順は「氏名,ユーザー名,部署(グループ),初期パスワード」固定です。

オプション:
  -f <file>      読み込むCSVファイルのパス (デフォルト: ${CSV_FILE})
  -l <dir>       ログ出力先ディレクトリ   (デフォルト: ${LOG_DIR})
  -n             ドライランモード。実際には変更を加えず、
                 何が実行されるかだけを画面とログに出力します。
                 --dry-run も同じ意味で使えます。
  -h             このヘルプを表示して終了します。--help も同じ意味です。

実行例:
  sudo ${SCRIPT_NAME} -f users.csv          # 本番実行(要root権限)
  sudo ${SCRIPT_NAME} -f users.csv -n       # ドライラン(root権限は必要だが変更なし)
  ${SCRIPT_NAME} -h                         # ヘルプ表示のみ(root権限不要)
EOF
}

#===============================================================================
# 3. コマンドライン引数の解析
#
#   bash組み込みの getopts は "-f" のような1文字オプションしか扱えない。
#   要件の --dry-run / --help を使えるようにするため、まず長いオプションを
#   対応する短いオプションに変換してから getopts に渡す、という一般的な
#   手法を使う。
#===============================================================================
args=()
for arg in "$@"; do
    case "$arg" in
        --dry-run) args+=("-n") ;;
        --help)    args+=("-h") ;;
        *)         args+=("$arg") ;;
    esac
done
set -- "${args[@]}"   # 変換後の引数リストで $1, $2, ... を上書きする

while getopts "f:l:nh" opt; do
    case "$opt" in
        f) CSV_FILE="$OPTARG" ;;
        l) LOG_DIR="$OPTARG" ;;
        n) DRY_RUN="true" ;;
        h) usage; exit 0 ;;
        \?) # 未定義オプションが渡された場合
            usage
            exit 1
            ;;
    esac
done
shift $((OPTIND - 1))   # ここまでで処理したオプション分だけ引数をずらす

#===============================================================================
# 4. root権限チェック
#
#   useradd / groupadd / chpasswd / chage はすべてroot権限が必須のコマンド。
#   一般ユーザーのまま実行すると各コマンドが権限エラーで失敗し、原因が
#   分かりにくいログになってしまう。そこで処理を始める前に自分自身で
#   チェックし、分かりやすい日本語メッセージを出して終了する。
#
#   $EUID はbashの組み込み変数で、実行中のユーザーの実効ユーザーID。
#   root の EUID は必ず 0 なので、0以外なら一般ユーザーと判定できる。
#===============================================================================
if [[ "${EUID}" -ne 0 ]]; then
    echo "エラー: このスクリプトはroot権限で実行してください。(例: sudo ${SCRIPT_NAME} -f ${CSV_FILE})" >&2
    exit 1
fi

#===============================================================================
# 5. CSVファイルの存在チェック
#===============================================================================
if [[ ! -f "$CSV_FILE" ]]; then
    echo "エラー: CSVファイルが見つかりません: ${CSV_FILE}" >&2
    exit 1
fi

if [[ ! -r "$CSV_FILE" ]]; then
    echo "エラー: CSVファイルの読み取り権限がありません: ${CSV_FILE}" >&2
    exit 1
fi

#===============================================================================
# 6. ログ出力先の準備
#===============================================================================
if ! mkdir -p "$LOG_DIR"; then
    echo "エラー: ログディレクトリの作成に失敗しました: ${LOG_DIR}" >&2
    exit 1
fi
# ${LOG_DIR%/} は「末尾にスラッシュがあれば取り除く」パラメータ展開。
# -l /var/log/ のように末尾に / を付けて指定されても "//" にならないようにする。
LOG_FILE="${LOG_DIR%/}/create_users_${TIMESTAMP}.log"

#===============================================================================
# 7. ログ出力関数
#
#   tee コマンドは「標準入力で受け取った内容を、画面(標準出力)と
#   指定ファイルの両方に同時に書き出す」コマンド。-a はファイルへ
#   追記(append)するオプション(付けないと毎回上書きされてしまう)。
#   これにより、実行中はリアルタイムに画面で経過を確認しつつ、
#   後から見返せるログファイルも同時に残せる。
#===============================================================================
log() {
    local level="$1"
    shift
    local message="$*"
    local now
    now=$(date '+%Y-%m-%d %H:%M:%S')
    echo "[${now}] [${level}] ${message}" | tee -a "$LOG_FILE"
}

#===============================================================================
# 8. 処理開始
#===============================================================================
log "INFO" "===== ユーザーアカウント一括作成処理を開始します ====="
log "INFO" "CSVファイル: ${CSV_FILE}"
log "INFO" "ログファイル: ${LOG_FILE}"

if [[ "$DRY_RUN" == "true" ]]; then
    log "INFO" "ドライランモードで実行しています。実際のアカウント作成・変更は行いません。"
fi

#===============================================================================
# 9. CSVを1行ずつ読み込んで処理する
#
#   IFS(Internal Field Separator = 単語の区切り文字)を ',' に設定した状態で
#   read コマンドを使うことで、CSVの1行を "," 区切りでそのまま4つの変数
#   (fullname, username, group, password)に振り分けられる。
#   IFS=',' は while の行だけに書くことで、スクリプトの他の部分の動作
#   (通常の空白区切り)に影響を与えないようにしている。
#
#   read -r の -r は「バックスラッシュ(\)をエスケープ文字として特別扱い
#   しない」オプション。付けないとパスワードに \ が含まれる場合などに
#   意図しない挙動になるため、read には基本的に -r を付ける。
#
#   || [[ -n "$fullname" ]] は、CSVの最終行に改行がない場合でも最後の
#   1行を読み落とさないための保険(read はファイル末尾で改行が無いと
#   終了ステータス非0を返すが、行の中身自体は変数に入っている)。
#
#   tail -n +2 で1行目(ヘッダー行)を読み飛ばしてから while に渡している。
#===============================================================================
while IFS=',' read -r fullname username group password || [[ -n "$fullname" ]]; do

    # --- 行末の\r除去(WindowsのExcel等でCRLF改行のまま保存されたCSV対策) ---
    # $'\r' はbashの特殊な書き方で「復帰(CR)の1文字」を表す。
    fullname="${fullname%$'\r'}"
    username="${username%$'\r'}"
    group="${group%$'\r'}"
    password="${password%$'\r'}"

    # --- 空行はスキップ(何もログに残さず読み飛ばす) ---
    if [[ -z "$fullname" && -z "$username" && -z "$group" && -z "$password" ]]; then
        continue
    fi

    # --- 必須項目チェック ---
    # [[ ]] はbash拡張版のtestコマンド。[ ] と違いクォート漏れによる
    # 事故が起きにくく、&& / || や =~(正規表現)がそのまま使えるため
    # 本スクリプトでは基本的に [[ ]] を使用している。
    if [[ -z "$fullname" || -z "$username" || -z "$group" || -z "$password" ]]; then
        log "ERROR" "不正な行のためスキップ: 必須項目が空です (氏名=${fullname}, ユーザー名=${username}, 部署=${group})"
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi

    # --- ユーザー名の形式チェック ---
    # Linuxのユーザー名は「英小文字またはアンダースコアで始まり、
    # 英小文字・数字・アンダースコア・ハイフンのみ」が基本ルール。
    # =~ は正規表現マッチ演算子([[ ]] の中でのみ使える)。
    if [[ ! "$username" =~ ^[a-z_][a-z0-9_-]*$ ]]; then
        log "ERROR" "不正なユーザー名のためスキップ: ${username} (使用可能文字: 英小文字/数字/_/- のみ)"
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi

    # --- 既存ユーザーチェック ---
    # getent passwd <name> は、/etc/passwd だけでなくLDAP連携環境などでも
    # 正しく存在確認ができる標準的な方法。存在すれば終了ステータス0を返す。
    if getent passwd "$username" > /dev/null 2>&1; then
        log "SKIP" "ユーザー ${username} は既に存在するためスキップしました。"
        SKIP_COUNT=$((SKIP_COUNT + 1))
        continue
    fi

    # --- グループの存在チェック・自動作成 ---
    if ! getent group "$group" > /dev/null 2>&1; then
        if [[ "$DRY_RUN" == "true" ]]; then
            log "INFO" "[dry-run] グループ ${group} が存在しないため作成します(実際には作成していません)"
        else
            if groupadd "$group"; then
                log "INFO" "グループ ${group} を新規作成しました。"
            else
                log "ERROR" "グループ ${group} の作成に失敗したため ${username} をスキップしました。"
                FAIL_COUNT=$((FAIL_COUNT + 1))
                continue
            fi
        fi
    fi

    # --- ドライランの場合はここで打ち切り、実行内容だけ記録する ---
    if [[ "$DRY_RUN" == "true" ]]; then
        log "INFO" "[dry-run] ユーザー ${username} (氏名: ${fullname} / 部署: ${group}) を作成します(実際には作成していません)"
        SUCCESS_COUNT=$((SUCCESS_COUNT + 1))
        continue
    fi

    # --- ユーザー作成 ---
    # -m : ホームディレクトリを作成する
    # -c : GECOS情報(氏名などのコメント)を設定する
    # -g : 所属させるプライマリグループを指定する
    # -s : ログインシェルを指定する
    if useradd -m -c "$fullname" -g "$group" -s /bin/bash "$username"; then
        log "INFO" "ユーザー ${username} (氏名: ${fullname} / 部署: ${group}) を作成しました。"
    else
        log "ERROR" "ユーザー ${username} の作成に失敗しました。"
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi

    # --- 初期パスワード設定 ---
    # chpasswd は「ユーザー名:パスワード」の形式を標準入力から受け取り、
    # 一括でパスワードを設定できるコマンド(パスワード入力プロンプトが出ない)。
    if echo "${username}:${password}" | chpasswd; then
        log "INFO" "ユーザー ${username} の初期パスワードを設定しました。"
    else
        log "ERROR" "ユーザー ${username} のパスワード設定に失敗しました。"
        FAIL_COUNT=$((FAIL_COUNT + 1))
        continue
    fi

    # --- 初回ログイン時のパスワード変更強制 ---
    # chage -d 0 は「最終パスワード変更日」を1970-01-01(epoch=0)に
    # 設定するコマンド。これにより、次回ログイン時にパスワードが
    # 期限切れとして扱われ、新しいパスワードへの変更が強制される。
    if chage -d 0 "$username"; then
        log "INFO" "ユーザー ${username} に初回ログイン時のパスワード変更を強制しました。"
    else
        log "ERROR" "ユーザー ${username} の chage 設定に失敗しました(ユーザー自体は作成済みです)。"
    fi

    SUCCESS_COUNT=$((SUCCESS_COUNT + 1))

done < <(tail -n +2 "$CSV_FILE")
# tail -n +2 : ヘッダー行(1行目)を除いた2行目以降だけをwhileに渡す。
# < <(...) はプロセス置換。「コマンドの実行結果をファイルのように扱って
# whileに読ませる」書き方で、これを使うとwhileループの中で作った変数
# (SUCCESS_COUNTなど)がループの外でもそのまま使える
# (もし command | while ... と書くと、パイプの右側がサブシェルになり
#  ループ内でのカウンタ更新がループを抜けた後に消えてしまう)。

#===============================================================================
# 10. 処理結果サマリの出力
#===============================================================================
log "INFO" "===== 処理結果サマリ ====="
log "INFO" "成功: ${SUCCESS_COUNT}件 / スキップ: ${SKIP_COUNT}件 / 失敗: ${FAIL_COUNT}件"

if [[ "$DRY_RUN" == "true" ]]; then
    log "INFO" "ドライランモードのため、実際のアカウント作成・変更は行われていません。"
fi

log "INFO" "===== 処理を終了します ====="

# 失敗が1件でもあれば異常終了(終了ステータス1)として扱う。
# シェルスクリプトの終了ステータスは、cron(=指定した時刻・間隔でコマンドを
# 自動実行するLinuxの定期実行の仕組み)やAnsible(=複数サーバーへの操作を
# まとめて自動化する構成管理ツール)等の呼び出し元が成功/失敗を機械的に
# 判定するために使うため、正しく返すことが重要。
if [[ "$FAIL_COUNT" -gt 0 ]]; then
    exit 1
fi

exit 0
